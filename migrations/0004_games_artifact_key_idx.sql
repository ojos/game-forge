-- 作品が指す R2 のキーで `games` を引けるようにする（確定26 / 3.4 / 3.7 / #116）。
--
-- **なぜ要るのか。** 3.8 のビルド結果キャッシュ（#19）は生成ソースのコンテンツ
-- ハッシュを鍵にするため、**同一ソースから生まれた複数の作品が R2 の同じオブジェクトを
-- 指す**（フォークは同一ソースからの派生を作る経路であり、稀事象ではない）。
-- 確定26 はこの共有を正とし、**削除する側が「他の作品が参照していないこと」を
-- 確かめる**ことで公開済み作品を守ると決めた。その問い合わせが
-- 「このキーを `source_key` か `wasm_key` に持つ他の作品はあるか」であり、
-- それを索引なしで引くと `games` の全走査になる。
--
-- **0001 / 0002 の方針（必要とする問い合わせが決まっているものだけを張る）に従う。**
-- 0002 は「3.7 のゴミ掃除（M5-4）が走査する形になったら、そのときに足す」と書いていた。
-- **その問い合わせが確定26 で決まった**ので、ここで足す。
--
-- **2 本張るのは、2 つのキーの寿命が別だからである。** 5.3 は「親の削除は物理削除せず
-- tombstone 化し、子は残す」と定め、フォークの再現には `source.go` が要る（5.3）。
-- すなわち **`wasm_key` だけを落として `source_key` を残す**削除がありうる。片方の列だけに
-- 索引を張ると、残ったほうの被参照チェックが全走査に戻る。
--
-- **3.6 の書き込み枠への影響。** 索引 2 本は `games` への 1 行 insert あたり最大 2 行の
-- 索引書き込みを足す。`games` の作成は月数百件（3.6）であり、無料枠 10 万行/日 に対して
-- 桁で下にある。**引き換えに得るのは、削除ごとの読み取りが全走査でなくなること**で、
-- 読み取りは書き込みの 1/1000 の単価とはいえ、フォークで `games` が伸びるほど
-- 走査の行数も伸びる（読み取りは行数で課金される）。
--
-- **部分索引にしない。** `WHERE source_key IS NOT NULL` を付ければ tombstone 後の行を
-- 索引から外せるが、SQLite の部分索引は問い合わせ側の WHERE 句が索引の条件を含むときしか
-- 使われない。被参照チェックの綴りに `is not null` を書き足す必要が生まれ、
-- **索引の定義と問い合わせの綴りが暗黙に結合する。** 得られる差（NULL 行の分だけ索引が
-- 小さい）に見合わない。

-- 「このキーを持つ他の作品はあるか」を引く（`src/build-cache.ts` の
-- `countArtifactReferences`）。
CREATE INDEX games_source_key_idx ON games(source_key);
CREATE INDEX games_wasm_key_idx ON games(wasm_key);
