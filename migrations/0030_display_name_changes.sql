-- 表示名の変更の履歴と、その履歴を書き始めた時刻（5.1 / 5.9 / 8.4 / #405）。
--
-- ## なぜ履歴が要るのか（なりすましの証拠が消えるため）
--
-- **審査キューで通報を開いても、通報された時点の作者の表示名が分からなかった。**
-- `users` が持つのはいまの `display_name` と、最後に利用者が決めた時刻
-- （`display_name_set_at`。0022）だけである。**「運営」を名乗って通報された作者が名前を
-- 変えると、運営に見えるのは変えたあとの穏当な名前だけ**になり、通報を「問題なし」に
-- するしかない（#405 の背景）。
--
-- **題名と説明は既に履歴を持つ**（`title_changes` 0027 / `description_changes` 0028）。
-- #405 は「通報ごとのスナップショットは持たず、既存の履歴から通報の時点の値を復元し、
-- 表示名には同じ形の履歴を足す」と決めた（利用者が作った中身の写しを通報の件数だけ
-- 増やさない。削除申請で消すときに写しを別に探す手順も要らない）。
--
-- ## 書く経路は 2 つある（どちらも書く）
--
--   1. **利用者が `/account` で変える**（`src/account.ts` の `changeDisplayName`）
--   2. **Google の名前への追随**（`src/auth/google.ts` の `refreshExistingUser`。
--      `display_name_set_at` が NULL のあいだ、ログインのたびに上書きされる）
--
-- **2 も書く。** なりすましの証拠としては、どちらの経路で変わっても意味が同じである
-- ——Google アカウントの名前を「運営」にしてログインし直せば、`/account` を通らずに
-- 名乗れる。**書かない経路を 1 つ残すと、そちらが証拠を消す道になる。**
--
-- **値が実際に変わったときだけ書く**（`old_display_name <> new_display_name`）。2 の
-- UPDATE は名前が変わらないログインでも走るので、毎回書くとログインのたびに 1 行増える
-- （3.6 の書き込みの無料枠）。同じ名前を `/account` で入れ直す操作（Google に追随するのを
-- やめる唯一の方法。5.9）も、名前は変わらないので書かない。
--
-- ## 更新と履歴は 1 つの `D1.batch` で書く（断られた変更で履歴を書かない）
--
-- **履歴を先に積み、UPDATE を後に置く**（`title_changes` の `renameGame` と同じ順序。
-- 旧い名前は UPDATE の前の行からしか取れない）。**履歴の insert の WHERE は、UPDATE の
-- WHERE に「名前が変わる」を足しただけの綴り**にしてあり（`src/display-name-changes.ts`）、
-- 2 文はどちらも batch の前の `users` の行を見る——**UPDATE が当たらない要求（頻度の上限で
-- 断られた変更）では、履歴も 0 行になる。** 履歴の insert が落ちれば batch ごと巻き戻り、
-- **名前も変わらない**（履歴の無い変更を作らない。#361 / #366 の規律）。
--
-- ## 履歴を書き始めた時刻を 1 行持つ（`display_name_history_start`）
--
-- **この表を足す前の変更は、どこにも残っていない。** 題名と違い、表示名は 0030 より前から
-- 変わりうる（0022 以降は `/account` で、それ以前からログインのたびに Google の名前で）。
-- したがって**履歴に行が無いことは「変わっていない」を意味しない**——いまの値を、
-- 履歴を書き始める前の通報の時点の値として出すと、**証拠を捏造するのと同じ結果になる**
-- （#405 の constraints）。**その時点より前の通報では「記録がありません」と出す。**
--
-- 判定の基準に採らなかったもの。
--
--   - **「その利用者の履歴の最初の行」** … 通報 → （記録されない変更）→ 0030 の適用 →
--     記録された変更、の順だと、最初の行の旧い名前は通報の時点の名前ではない。**しかも
--     1 度も変えていない利用者について、いまの値が正しいことを言えなくなる**
--   - **「履歴の表全体の最初の行」** … 誤りは出さないが、**なりすましの最初の 1 件**（全体で
--     最初に記録される変更）が常に「記録がありません」になる。証拠が要る場面そのものを落とす
--   - **コードに埋めた固定の時刻** … 本番へ適用する時刻は実装の時点で決まっておらず、
--     手元とテストの D1 で意味が変わる（#394 が `admin_actions` について退けたのと同じ理由）
--   - **`d1_migrations` の `applied_at`** … wrangler の内部の表で、綴りも時刻の形（文字列）も
--     こちらの契約ではない。テストの適用経路（`applyD1Migrations`）で同じ意味になる保証が無い
--
-- **この migration 自身が、適用した時刻を書く。** 表を作った瞬間から、D1 の中に基準がある。
-- 行は 1 つだけで（`id = 1` の CHECK）、アプリは読むだけで書かない。
--
-- ### 適用からアプリの配備までの間は、記録されない（手順で狭め、後から詰められる）
--
-- **マイグレーションは配備より先に当てる**（CI の配備は未適用のマイグレーションがあると
-- 止まる。`scripts/check-migrations-applied.sh`）。**当ててから新しいコードが出るまでの間は、
-- 古いコードが名前を変えても履歴を書かない。** その間に付いた通報のあとに、その間に名前が
-- 変わると、いまの値が通報の時点の値として出てしまう。
--
-- **狭める手順と、詰める手順を `docs/admin-host.md` に置いた**（#405 の節）。当てるのは
-- マージの直前にし、配備を確かめたら `started_at` をその時刻へ進める。**進める向きは
-- 「記録がありません」を増やす側だけ**なので、後から打っても誤った値は出ない。
--
-- ### 同じ秒は「記録が無い」側へ倒す
--
-- **通報の時刻が `started_at` と同じ秒なら「記録がありません」と出す**（`src/admin/report-evidence.ts`）。
-- 同じ秒のうちに、適用の前に古いコードが名前を変えていたかは区別できない。**誤った値を
-- 出す側へは倒さない。**
--
-- ## 運営が D1 を直接 UPDATE して名前を直すとき
--
-- 5.9 は「不適切な名前は運営が D1 を直接 UPDATE して戻す」と定める。**その UPDATE は
-- 履歴を書かない**ので、通報の時点の名前の復元を誤らせる（変更が 1 件も記録されていない
-- 作者では、直した後の名前が通報の時点の名前として出る）。**直すときは同じコマンドで
-- 履歴も 1 行積むこと**（手順は 5.9 の実装注記と `docs/admin-host.md`）。保証できるのは
-- アプリの経路までで、端末からの操作は止められない（0026 と同じ但し書き）。
--
-- ## 追記のみ（0026 / 0027 / 0028 と同じ規律）
--
-- **更新も削除もしない。** アプリにこの表を UPDATE / DELETE する経路を 1 つも作らない。
--
-- ## 利用者と同じ寿命
--
-- **`users` の行を消すときは、この表の行を先に消す**（外部キー）。いまのアプリで `users` を
-- 消すのは、招待を消費できなかった直後の作りかけの行だけで（`src/auth/google.ts`）、
-- その行はまだログインの UPDATE も名前の変更も通っていない。**`on delete cascade` は
-- 書かない**（0027 と同じ。発火しない宣言は「消えるはず」という誤読だけを残す）。
--
-- ## `id` を主キーにする（`(user_id, changed_at)` にしない）
--
-- 0027 と同じ理由である。**同じ秒の 2 度目が一意制約で落ちると batch ごと巻き戻る**——
-- ログインの経路では、**履歴の都合でログインそのものが失敗する。**
--
-- ## 索引を張る
--
-- **審査キューが通報 1 件ごとに「その時点の前後で最も近い変更」を引く**（相関副問い合わせ）。
-- `(user_id, changed_at)` の範囲の端を読めば済むように、0027 / 0028 と同じ並びで張る。
-- **書き込みの増分は、名前が実際に変わったとき 1 回につき索引込み 2 行**（3.6）。
--
-- ## 名前そのものを持つ（公開されていた値である）
--
-- **旧い名前と新しい名前の両方を持つ。** 表示名は未ログインの閲覧者にも見える値だが、
-- **画面へ出すときは `escapeHtml` を通すこと**（利用者が名乗った値。5.9）。
--
-- ## CHECK は時刻の 1 つだけ
--
-- **`changed_at` は 0 より大きい**（0027 と同じ理由——0 は「時計が読めなかった」形で、
-- 復元の比較に 1970 年の変更として混ざる）。**`new_display_name` に「空ではない」の
-- CHECK は張らない。** Google の経路の名前は `/account` の検査（5.9）を通らない値で、
-- `users.display_name` 自体にも長さの CHECK が無い。**張ると、Google 側の名前の形の都合で
-- ログインの batch が落ちる**——証拠の都合で利用者を締め出す形にしない。
--
-- ## 連番が 0030 である理由
--
-- 着手時に空いている最小の番号である（`0029` は #394 が使用済み）。issue #405 の本文は
-- 「#404 が `0030` を取る可能性がある」と書いていたが、#404 はマイグレーションを足さずに
-- 入った（仕様 5.4 の #404 の実装注記）。並行するレーンとも、この番号を取ることを着手前に
-- 合わせた。

CREATE TABLE display_name_changes (
  id TEXT PRIMARY KEY,
  -- 名前を変えた利用者。**実在する利用者しか入らない**（書く経路は `users` を引いて書く）。
  user_id TEXT NOT NULL REFERENCES users(id),
  -- 変える前の表示名。
  old_display_name TEXT NOT NULL,
  -- 変えた後の表示名。**古い名前とは必ず違う**（同じなら書かない。上記）。
  new_display_name TEXT NOT NULL,
  -- 変えた時刻（UNIX 秒。0001 の方針）。**0 以下は入らない**（上記）。
  changed_at INTEGER NOT NULL CHECK (changed_at > 0)
);

-- 「その利用者の、ある時刻の前後で最も近い変更」を引くための索引（0027 / 0028 と同じ並び）。
CREATE INDEX display_name_changes_user_changed_idx ON display_name_changes (user_id, changed_at);

-- 表示名の履歴を書き始めた時刻（上記）。**行は 1 つだけ**で、この migration が書く。
CREATE TABLE display_name_history_start (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  -- 適用した時刻（UNIX 秒）。**これより前（同じ秒を含む）の通報では、表示名を復元しない。**
  started_at INTEGER NOT NULL CHECK (started_at > 0)
);

INSERT INTO display_name_history_start (id, started_at)
VALUES (1, CAST(strftime('%s', 'now') AS INTEGER));
