/**
 * 作品のタグの語彙（仕様 2.3.5 / 2.3.6 / 5.4 / #376）。
 *
 * ## 語彙は 8 個に固定する（#376 の利用者の決定。2026-09-13）
 *
 * **自由入力にしない。** 表記ゆれで絞り込みが機能しなくなるうえ、モデレーションの対象が
 * 増える（2.3.5）。**語彙を増やすことは「タグの追加・編集を利用者に開くこと」**
 * （#376 の scope.out）であり、この表に行を足すのは運営の判断である。
 *
 * ## DB と URL には識別子を、画面にはラベルを
 *
 * `games.tag1` / `tag2` / `tag3` と `/works?tag=` に入るのは **ASCII の識別子（`id`）** で、
 * 日本語のラベルは**このコードだけが持つ**。ラベルを言い換えても D1 の行も共有された URL も
 * 変わらない。**逆に識別子は変えてはいけない**——保存済みの行と、外へ出た URL が
 * 指すものが消える（変えるなら行の書き換えと旧 URL の受け皿を同時に用意する）。
 *
 * **並び順に意味がある。** 公開フォームと付け直しのフォームのチェックボックス、一覧の
 * 左カラム、そして**保存するときの枠の詰め方**（`src/games.ts` の `validateWorkTags` が
 * この順に並べ直してから tag1 から詰める）がこの順に従う。「その他」を最後に置くのは、
 * 選択肢を読み下した末尾で拾う受け皿だからである。
 *
 * ## 値だけの葉にする（関数を置かない）
 *
 * **このモジュールはリテラルの配列と定数だけを持つ。** 最上位で `new Set` や
 * `Object.freeze` を呼ばない——`src/games.ts`（オーケストレータの束に入る）がここを
 * import しており、**副作用を持ちうる式が最上位にあると、Lambda が 1 度も読まない値のために
 * 束の `CodeSha256` が変わりうる**（#241 の関門が本番配備を止める。`src/paths.ts` の冒頭と
 * 同じ事情）。検査・並べ替え・ラベルの引き当ては、それを使う側の関数に置く。
 */

