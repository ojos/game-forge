-- 作品のソースが方向キーを「押し続けて」読むか（仕様 3.9.6 の「方向の操作の形」/ #528 / #529 / M14-9）。
--
-- **仮想パッドの最初の形（スティックか十字か）を推定するための土台である。** 保存するのは読み方
-- （押し続けて読む `code` の集合）で、**形は保存しない**——形の規則を後で変えても、埋め戻しが要らないように
-- するためである（0040 で読むキーの全集合だけを保存したのと同じ理由）。
--
-- ## 0040 の表に列を足す（別の表にしない）
--
-- **引き方も、書く時点も、埋め戻しも 0040 と同じ**（ソースの R2 キーの等値 1 通り・完成の直後・版の古い行を
-- 拾い直す）。別の表にすると、2 つの表の行の有無が食い違う状態（キーはあるが読み方が無い、の逆など）を
-- 作れてしまう。**同じ行に持てば、`rule_version` 1 つで両方の鮮度を表せる。**
--
-- ## NULL の意味
--
-- **`held_codes` が NULL の行は、規則の版 1 で拾った行である**（この列が無かった時点の行）。
-- 3.9.6 の規則 6 で「読み方がまだ無い」として扱い、`codes` から十字で出す。
-- **`[]` は「拾ったが、押し続けて読むキーは無い」**（押した瞬間だけ読む作品。十字で出す）で、NULL と区別する。
--
-- ## 書く場所（`src/source-input-keys.ts`。M14-9 が実装する）
--
-- - 抽出の規則の版を 2 に上げ、完成の直後に `codes` と一緒に書く。
-- - **既存の行は、埋め戻し（`scripts/input-keys-backfill.mjs`）が版 1 の行を拾い直して埋める。**
--
-- **このマイグレーションだけを先にマージする**（#529 / #530 の実装より前）。今の作品ページ（#494）はこの列を
-- 読まないので、列が増えても振る舞いは変わらない。#530 はこの列を読むので、本番に列が無いまま出すと
-- 作品ページの問い合わせが失敗する（仕様 3.9.6 の #528 決定の末尾）。

