#!/usr/bin/env bash
# writeback-serial.sh — docs/handoff.md を触る open PR のうち、どれを通しどれを待たせるかを決める（#650）
#
# ══════════════════════════════════════════════════════════════════════════════
# 何のためにあるか
# ══════════════════════════════════════════════════════════════════════════════
#
# **書き戻しの PR を 1 本ずつに並べる。** 同じ日の追記は、先行する open PR へ足す。
#
# 理由は 2 つある。
#
#   1. **費用。** Copilot code review は PR 1 本あたり約 16.1 credits の固定費が支配的で、
#      2026-09 の実績では 63% が「本数 × 固定費」だった。書き戻しを同じ日 1 本にまとめると
#      260 本 → 176 本で、月 $13.52 減る（#650 の Phase 0）。
#   2. **事故。** 複数のセッションが同時に handoff.md を書き換えると、片方の追記がもう片方へ
#      相乗りするか、衝突する（handoff.md 4 章の #229）。
#
# **呼びかけ（「まとめてください」）では担保しない。** 並行するセッションは互いの open PR を
# 見ないまま書き戻す。ここで見るのは「同じファイルを触る open PR が既にあるか」という
# **実質**なので、`.ai-playbook/shared-ai-rules.md` 12 章の「機構化してよい」側に入る。
# PR の題の付け方では迂回できない。
#
# **束ねられるようになったのは #656 の後である。** それまで handoff.md の 8 行目は 48,859 B
# あり、書き戻し 1 本で GitHub が `patch` を落として Copilot が読めなかった。解体後の
# 書き戻しは `patch` 4 KB 台（#660）なので、数本ぶんをまとめても読める範囲に収まる。
#
# ══════════════════════════════════════════════════════════════════════════════
# 規則
# ══════════════════════════════════════════════════════════════════════════════
#
# **いちばん古い 1 本だけを通す。** 古さは作成時刻で決め、同時刻なら番号の小さいほう。
# 残りは「#N が先に open です」として落とす。
#
# **判定は入力に対して決定的である。** 同じ一覧を渡せば、どの契機から呼んでも同じ答えを
# 返す。ワークフローは、どの PR の出来事で起動しても**全件を判定し直す**ので、先行 PR が
# 閉じた時点で次の 1 本が緑に変わる。
#
# ══════════════════════════════════════════════════════════════════════════════
# 入出力
# ══════════════════════════════════════════════════════════════════════════════
#
# 入力: 標準入力。docs/handoff.md を触る open PR を 1 行 1 件、`番号 作成時刻`（ISO 8601）。
#
#   printf '662 2026-09-18T09:30:00Z\n670 2026-09-18T10:00:00Z\n' | bash scripts/writeback-serial.sh
#
# 出力: 1 行 1 件、入力と同じ PR について
#
#   662 success
#   670 failure 662
#
# 空の入力には何も出さず 0 で終わる（触っている PR が無い）。
# 形の崩れた行があれば、何も出さずに 2 で終わる。**一部だけ判定して出すと、落とすべき PR を
# 黙って緑のままにしうる**ので、全部か無しかにする。
set -euo pipefail

rows=()
while IFS= read -r line; do
  line="${line%$'\r'}"
  [ -n "$line" ] || continue
  if ! [[ "$line" =~ ^[0-9]+\ [0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:]+Z$ ]]; then
    echo "writeback-serial: 形の崩れた行: $line" >&2
    exit 2
  fi
  rows+=("$line")
done

[ "${#rows[@]}" -gt 0 ] || exit 0

# 作成時刻、次に番号で並べる。ISO 8601 の UTC は文字列順が時刻順になる。
sorted="$(printf '%s\n' "${rows[@]}" | sort -k2,2 -k1,1n)"
first="$(printf '%s\n' "$sorted" | head -n1 | cut -d' ' -f1)"

while read -r num _; do
  if [ "$num" = "$first" ]; then
    echo "$num success"
  else
    echo "$num failure $first"
  fi
done <<< "$sorted"
