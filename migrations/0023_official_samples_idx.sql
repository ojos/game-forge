-- 公式サンプルの節（#329 / M9-3 / 仕様 2.3.1・2.3.3）が引くための索引。
--
-- ## 何を引くのか
--
-- トップの 1 節目は「運営（`users.is_operator = 1`）が公開した作品」である
-- （選び方とその根拠は `src/home-feed.ts`）。引き方は 2 段になっている。
--
--   1. 運営アカウントの id を引く（`operatorIdsSql`）
--   2. その id ごとに、公開済みで審査に止められていない作品を新しい順に引く
--      （`officialSamplesSql`）
--
-- **索引はこの 2 段にそれぞれ要る。** 片方だけ張ると、そちらだけが速くなって
-- もう片方が母数に比例したまま残る（`0019` が「軸ごとに索引が要る」と書いたのと
-- 同じ形である）。
--
--
-- ## 1 本目: 運営アカウントを見つけるための部分索引
--
-- **`0021` は「この列で絞り込む経路は無い」として索引を張らなかった。#329 がその経路を
-- 作ったので、前提が変わっている。**
--
-- 索引が無いと、運営の行を見つけるまで `users` を走査する。**`limit` は走査を止めない**
-- ——1 人しか居なければ最後まで読む。読む行数は**利用者数に比例する**。母数（公開作品の
-- 総数）には比例しないので 2.3.3 の条件 1 の趣旨は保たれるが、**部分索引 1 本で消える
-- 比例をわざわざ残す理由が無い**（PR #349 の Copilot code review の指摘）。
--
-- **前例は `0020` の `users_banned_idx` である**（`users(id) WHERE banned_at IS NOT NULL`）。
-- あちらも「BAN された人だけを載せる」ために張った部分索引で、**同じ理由・同じ形**である。
--
-- **部分索引にする。** 運営は 1 アカウント（`docs/operator-account.md`）で、載るのは
-- 全利用者のうち 1 行だけである。`0007` の `generation_state` が部分索引を選んだ前提
-- （「その状態の行は全体のごく一部」）が、ここでは完全に成り立つ。
--
-- **`id` だけを載せる。** 問い合わせが選ぶのは `id` 1 列なので、索引だけで答えが出る
-- （covering index。表の行を 1 つも読まない）。
--
--
-- ## 2 本目: 公式サンプルそのものを引くための部分索引
--
-- `0008` の `games_author_id_created_at_idx`（`author_id, created_at DESC, id DESC`）でも
-- 並びは合う。**それでも張るのは、`0008` が審査と公開状態の条件を含まないからである。**
--
-- **運営の下書きと、審査で止められた作品が、並びの上位に挟まる。** 0008 の索引の上では
-- それらも `author_id` の下に並んでいるので、**8 件を集めるまでに挟まった数だけ余分に
-- 読む。** 運営アカウントは #43 のサンプルを作る過程で下書きを溜める側であり、
-- **「ふだんは 0〜数件」が成り立たない**（2.3.3 の v1.51 注記が審査中について置いた前提は、
-- 下書きには当てはまらない）。
--
-- **この索引は、節が引く条件そのもので絞る**——`status = 'published'` と、8.4 の審査で
-- 新規露出を止めていないこと。**`0020` の `games_status_like_count_idx` と同じ判断であり、
-- v1.52 追記が「部分索引は効いた」と実測で確かめた形をそのまま借りている。**
--
-- 条件は `src/reports.ts` の `reviewVisibleSql()` が返す文字列と**同じ綴り**にしてある。
-- SQLite は問い合わせの条件が索引の条件を含むと示せたときだけ部分索引を使うので、
-- **綴りがずれると黙って使われなくなる**（そして `0008` の索引へ落ちるだけなので、
-- 結果は正しいまま読み取りだけが増える——**いちばん気づきにくい壊れ方である**）。
-- **`test/schema-official-samples.test.ts` がこの一致と実行計画を機械で確かめる。**
--
-- 列順は `officialSamplesSql` の `order by created_at desc, id desc` に揃えてある。
-- **`published_at` ではない**——理由は `src/home-feed.ts` にある（`published_at` 順にすると
-- 一時 B-tree が入り、`LIMIT` を掛ける前に運営の公開作品を全件読む。実測）。
--
--
-- ## 費用
--
-- `users` 側は、運営フラグを立て下ろしするときだけ書き込みが増える（人の手による
-- `UPDATE` で、`docs/operator-account.md` の稀な操作である）。
--
-- `games` 側は、**運営アカウントの作品が公開・非公開になるときだけ**である（部分索引の
-- 条件を満たす行の出入り）。利用者の作品は 1 行も載らない。生成は月数百件の規模で
-- （3.7 / 確定25）、書き込みの無料枠 10 万行/日 に対して無視できる。
--
-- **必要とする問い合わせが決まっているから張る**（`0001` の冒頭が定める規約）。
--
--
-- ## 連番が 0023 である理由
--
-- 取り込む側が割り当てた番号である（`docs/handoff.md` 3 章。`0020`〜`0022` は本番へ適用済みで、
-- 次に足すのは `0023` と決まっている）。**`migrations/` を数えて max+1 を取っていない。**

-- 運営アカウントを見つけるための部分索引（`operatorIdsSql`）。
CREATE INDEX users_operator_idx ON users(id) WHERE is_operator = 1;

-- 公式サンプルを引くための部分索引（`officialSamplesSql`）。
CREATE INDEX games_official_samples_idx
  ON games(author_id, created_at DESC, id DESC)
  WHERE status = 'published' AND (review_state is null or review_state = 'cleared');
