-- 運営が画面から行った操作の履歴（仕様 2.4.4 / #361。M10-3）。
--
-- **残すのは実行者・日時・操作・対象の種類・対象 id・理由である。** 2.4.4 が
-- 「**取り消しも 1 行として積む**（前の行を書き換えない）」と定めているので、
-- **`queued` を `cleared` へ戻した操作も、BAN を外した操作も、それぞれ 1 行**になる。
--
--
-- ## なぜ表が要るのか（8.4 の「記録を残す」の実体）
--
-- 8.4 は「送信防止措置の手順と記録を残す」と定め、2.4.4 は「**あとから書き換えられる
-- 記録は、記録として弱い**」と書いている。**いまは記録が 1 行も無い**——審査キューの
-- 出し入れも BAN も `games` / `users` の列を上書きするだけで、**誰がいつ何を理由に
-- 行ったかは、どこにも残っていない。** 列の現在値からは「最後にどうなったか」しか
-- 読めない。
--
-- **削除申請への回答に使えることが、理由を必須にした理由である**（2.4.4）。「誰が何を
-- した」だけでは、なぜそう判断したかを答えられない。
--
--
-- ## 追記のみであり、保証できるのは画面と口までである
--
-- **アプリにこの表を UPDATE / DELETE する経路を 1 つも作らない**（`src/admin/actions.ts`。
-- 書くのは `insert` だけで、それ以外の文をこの表へ向けない）。
--
-- **しかし storage の層では止められない。** D1 に「この表は追記のみ」と宣言する手段は
-- 無く、**端末から `wrangler d1 execute DB --remote --command "delete from admin_actions"`
-- を打てば消える。** 資格情報を持つ人（＝運営自身）に対しては、**この表は改竄できる。**
--
--   - **その資格情報は、この機構より上位にある。** 同じ資格情報で `users.is_admin` を
--     立てられる（0025 の「立て方は直接 UPDATE である」）以上、**履歴だけを守っても
--     意味が無い**——管理者を増やしてから画面で操作すれば、正規の行として積める
--   - **防ぐとすれば置き場を D1 の外へ出すことになる**（追記専用のログ基盤など）。
--     それは 3.6 / 4.3 の費用の枠組みの外にあり、クローズドβ（2.1）の段で引き受ける
--     ものではない
--
-- **したがって「追記のみ」は、画面と口が守る性質であって、表が守る性質ではない。**
-- 限界は `docs/admin-host.md` の「限界（機械照合を置けないところ）」にも書いた
-- （0025 が `is_admin` について同じ限界を書いているのと同じ形である）。
--
--
-- ## 外部キーは実行者にだけ張る
--
-- **`actor_id` は `users(id)` を参照する。** 実行者は必ずこのサービスの利用者であり
-- （`is_admin = 1` の行がある）、**存在しない id が入る経路が無い。**
--
-- **`target_id` には張らない。** 対象は作品のことも利用者のこともあり、
-- **SQLite の外部キーは「行き先の表」を 1 つに決めなければ書けない**（`target_kind` で
-- 分かれる参照は表現できない）。**片方にだけ張ると、もう片方が黙って無検査になる**
-- ので、**どちらにも張らず、対象の種類を `target_kind` で明示する。**
--
-- **`0018` が `game_id` に外部キーを張らなかった理由とは別である**（あちらは「実在
-- しない id の申請も記録に残すほうが 8.4 に適う」という判断だった）。ここは表現できない
-- ことによる。
--
--
-- ## CHECK を 3 つ張る
--
-- **列名は仕様 5.1 の表の綴りに合わせる。** あの表は `admin_actions` を
-- 「`id`・`actor_id`・`action`・**`target_kind`**・`target_id`・`reason`・`created_at`」と
-- 定めている。**`target_type` にしない**——PR #364 のレビューで指摘を受けて直した
-- （**適用前に直せば済むが、適用後は列名を変えられない**。仕様どおりに読む人が、
-- 存在しない列を参照することになる）。
--
-- **`action` と `target_kind` は取りうる値が決まっている。** 0021 / 0025 が真偽の 2 値へ
-- CHECK を張ったのと同じ判断で、**この 2 列は「戻せる操作だけを置く」という 2.4.3 の
-- 決定そのものを表している。** 綴りの正本は `src/admin/actions.ts` の
-- `ADMIN_ACTIONS` / `ADMIN_ACTION_TARGET_KINDS` で、**一致は `test/admin-actions.test.ts` が
-- 機械照合する**（書き写した一覧は必ず腐る。`.ai-playbook/shared-ai-rules.md` 12 章）。
--
-- **`'game-removed'` をここへ足さない。** 作品の取り下げ（`games.status = 'removed'`）は
-- **画面に置かないと決めた操作**である（2.4.3。戻せない側）。CHECK に無ければ、
-- **後から画面が書こうとしても入らない。**
--
-- **`reason` は空を弾く**（`length(trim(reason)) > 0`）。2.4.4 の「理由を必須にする」を、
-- **口（`src/admin/actions.ts` の `validateReason`）と表の両方で守る。**
--
--   - **口だけでは足りない。** 理由を運ぶ項目を足し忘れた画面が、空文字のまま積める
--   - **表だけでは足りない。** `trim` が落とすのは空白・改行だけで、全角空白だけの理由は
--     通る（口の側は `String#trim` で全角空白 U+3000 も落とす）
--   - **この CHECK は、操作と履歴が 1 つの batch であることの検査にも使っている**
--     ——空の理由で書かせると履歴の insert だけが落ち、**batch ごと巻き戻って操作も
--     入らない**ことを `test/admin-actions.test.ts` が実際に見る
--
--
-- ## 索引を張らない
--
-- **読むのは履歴の画面（`/actions`）だけで、`order by created_at desc limit <固定件数>`
-- の 1 本である。** 3.6 が挙げるとおり索引は 1 行の insert につき 1 行の書き込みを足す。
--
-- **この表は運営が画面を押した回数しか増えない**（通報や生成と違い、利用者の数に比例
-- しない）。クローズドβ（2.1。数十人規模）で審査と BAN が 1 日に数回であれば、
-- 全走査で足りる。**「将来使うかもしれない」で足さない**（0001 / 0017 / 0025 の方針）。
--
-- 張る契機は、**この表が数千行になり、かつ一覧の読み取り行数が体感に出たとき**である。
-- そのときは `created_at DESC`（一覧の並びの第 1 キー）を張ることになる。**第 2 キーの
-- `rowid` は索引に書かない**——SQLite の索引は暗黙に rowid を持つ（`src/admin/actions.ts`
-- の `listAdminActions` が、同じ秒の並びを rowid で決めている理由もそこにある）。
--
--
-- ## 連番が 0026 である理由
--
-- 取り込む側が着手前に割り当てた番号である（`docs/handoff.md` 3 章。`0025` は M10-2 の
-- `is_admin` が使用済みで、**適用済みの番号へ後から足せない**ため 0025 へ相乗りしない
-- ——0025 の末尾がそう書いている）。`migrations/` を数えて max+1 を取っていない
-- （0009 の衝突はそれで起きた）。

CREATE TABLE admin_actions (
  id TEXT PRIMARY KEY,
  -- 実行した管理者（`users.is_admin = 1`）。**行を消さない**ので、後から誰の操作かを
  -- 引ける（0001 の `banned_at` が「行を消さない」と書いているのと同じ前提）。
  actor_id TEXT NOT NULL REFERENCES users(id),
  -- 操作した時刻（UNIX 秒。0001 の方針）。
  created_at INTEGER NOT NULL,
  -- 何をしたか。**綴りの正本は `src/admin/actions.ts` の `ADMIN_ACTIONS`。**
  action TEXT NOT NULL CHECK (
    action IN ('review-queued', 'review-cleared', 'user-banned', 'user-unbanned')
  ),
  -- 対象の種類。**`target_id` の行き先がどちらの表かを、この列だけが知っている**（上記）。
  target_kind TEXT NOT NULL CHECK (target_kind IN ('game', 'user')),
  -- 対象の id（`games.id` または `users.id`）。
  target_id TEXT NOT NULL,
  -- 判断の理由（**必須**。2.4.4）。空と空白だけを表の側でも弾く（上記）。
  reason TEXT NOT NULL CHECK (length(trim(reason)) > 0)
);
