-- 改造通知を受け取らない設定を `users` へ足す（5.5 / 5.11 / #384。M12-16）。
--
-- ## なぜ列が要るのか
--
-- **このサービスは、自分の作品が改造されたとき作者にメールを 1 通送る**（2.2-6 / 5.5 /
-- `src/mail/fork-notice.ts`）。**それを止める手段が、利用者側に 1 つも無かった。** 5.11 は
-- `/account` のメール配信タブで改造通知を止められるようにすると定めた。
--
-- 意味は 2 値である。
--
--   - **NULL: 受け取る**（いままでの振る舞い。**既定**）
--   - **値あり: 受け取らない**（値は受け取らない設定にした UNIX 秒）
--
-- ## 既定は「受け取る」。既存の行を埋めない
--
-- **新しい列を足したら、既存の行がその経路を 1 度も通っていないことを疑う**
-- （`docs/handoff.md` 1 章。#202 / #203）。ここで疑った結果は「埋めてはいけない」である。
-- 既存の利用者は**誰も止めていない**——いまは全員が改造通知を受け取っているので、
-- **NULL（受け取る）がその時点で真である値**になる。5.11 の「既存の利用者の挙動を黙って
-- 変えない」は、既定値を NULL にしたことだけで満たされる（UPDATE を書かない）。
--
-- **「受け取る」を 1 にする真偽値の列（`NOT NULL DEFAULT 1`）にしない。** 意味は同じだが、
-- 下の間隔の判定に要る時刻を別の列に持つことになり、片方だけが更新された行が
-- 「止めたのに時刻が無い」状態を作る（`display_name_set_at` / `banned_at` と同じ判断）。
--
-- ## 真偽値ではなく時刻で持つ
--
-- **設定の変更を連打で D1 の書き込みにしない**（3.6。書き込みの無料枠は読み取りより桁で
-- 小さく、枯れると D1 全体が止まる）。**受け取る設定へ戻すのは、受け取らない設定にしてから
-- 60 秒以上空いたときだけ**にする（`src/account.ts`）。判定に要るのは止めた時刻そのもので、
-- 1 列で足りる。**止める側（NULL → 時刻）には間隔を置かない**——止める・戻すの 1 往復が
-- 60 秒に 1 回へ絞られるので、1 人が 1 日張り付いても 2,880 行に収まる（無料枠 10 万行/日 の
-- 2.9%）。**同じ値の入れ直しは WHERE で 0 行にする**（書き込まない）。
--
-- ## 判定は、宛先を引く問い合わせの中で読む
--
-- **この列を読む送信の経路は `src/mail/fork-notice.ts` の 1 か所だけである**（止められる種別は
-- 改造通知だけで、その送信の口が 1 つしか無い。種別の一覧は `src/mail/kinds.ts`）。
-- 宛先（`users.email`）を引く JOIN で同じ行から読むので、**読み取りの往復は増えない。**
--
-- **止めた利用者への改造通知は、`fork_notices` を握る前に降りる。** 握らないので、0013 の
-- `outcome` の CHECK に新しい値を足さない。**受け取る設定へ戻しても、止めていたあいだに
-- 公開された改造は送らない**——通知の契機は公開の 1 回だけで（0013 の本文）、未送信を
-- 探して回る経路を作らない。
--
-- ## 索引を張らない
--
-- 引き方は `users` の主キー 1 本だけで、この列で絞る問い合わせが無い。**索引は 1 行の
-- 更新につき 1 行の書き込みを足す**（3.6）。

alter table users add column fork_notice_muted_at integer;
