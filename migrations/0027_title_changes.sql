-- 作者が題名を変えた履歴（5.4 / 8.4 / #366）。
--
-- ## なぜ履歴が要るのか（改名が開ける穴を塞ぐため）
--
-- **改名の口を開けると「穏当な題名で公開 → 通報 → 審査で `cleared` → 改名」が成立する。**
-- `cleared` は終端であり（`src/reports.ts`「再び閾値に達しても戻さない」）、通報の処理は
-- `review_state IS NOT NULL` で早期に return する。運営が見る一覧は `queued` だけなので
-- （`scripts/report-queue.sh`）、**`cleared` に付いた通報はどの画面にも出ない。**
--
-- **改名そのものは `review_state` を `NULL` へ戻すので、新しい通報はまたキューへ入る。**
-- それでも履歴が要るのは、**「最後の改名より後に通報が付いたか」を運営が引けなければ、
-- 改名で `cleared` を剥がした作品を見分けられない**ためである。条件の正本は
-- `src/reports.ts` の `REVIEW_RENAMED_SQL` で、`scripts/report-queue.sh` はそれを
-- 取り出して使う（**条件を 2 か所に書かない**）。
--
-- ## 追記のみ（0026 と同じ規律）
--
-- **更新も削除もしない。** アプリにこの表を UPDATE / DELETE する経路を 1 つも作らない
-- （`src/games.ts` の `renameGame` が書くのは `insert` だけである）。0026 が書いたとおり、
-- **保証できるのは画面と口までで、表の側では止められない**——資格情報を持つ人は
-- `wrangler d1 execute` で消せる。ここで主張するのはアプリの経路の性質だけである。
--
-- **改名と履歴は 1 つの `D1.batch` で書く**（`src/games.ts` の `renameGame`）。履歴の
-- insert が落ちれば batch ごと巻き戻り、**題名も変わらない。** 履歴の無い改名を作らない
-- という規律は #361（`admin_actions`）から借りている。
--
-- ## 作品と同じ寿命（確定26 / 3.7 の削除規約）
--
-- **`games` の行が消えるときは、この表の行も一緒に消す。** いまの実装に `games` を
-- 物理削除する経路は無く（5.3 の tombstone 化。`delete from games` は `src/` に 1 つも
-- 無い）、**したがってこの表の行も消えない**のが平常である。規約として書いておくのは、
-- 3.7 の掃除が作品行まで消す日に、**参照する側の表が置き去りになる形**を作らないため
-- である（確定26 が「参照する側の行が失われる」ことを #202 / #203 の事故として記録して
-- いる）。仕様は 3.7 の「共有された成果物の削除規約」へ書き足した。
--
-- **`on delete cascade` は書かない**（0009 と同じ。`games` の行は物理削除しないので
-- 発火せず、「消えるはず」という誤読だけが残る）。外部キーは張る——改名の対象は必ず
-- 実在する作品であり（`renameGame` は `games` を引いて書く）、**実在しない id が入る
-- 経路が無い**（0018 が `game_id` に張らなかった理由——申請の時点で id が実在しない
-- ことがありうる——は、こちらには当てはまらない）。
--
-- ## `id` を主キーにする（`(game_id, changed_at)` にしない）
--
-- **同じ秒に 2 回改名されうる。** 二重送信でも、素早い打ち直しでも起こる。複合主キーに
-- すると 2 回目が一意制約で落ち、**batch ごと巻き戻って改名そのものが失敗する**——
-- 履歴の都合で、作者の正当な操作を断ることになる。0009 の `(game_id, seq)` は表の中で
-- 番号を採るので同じ問題を持たないが、こちらは番号を採る理由が無い（順序は時刻で足りる）。
--
-- ## 索引を張る（0017 / 0026 の「張らない」とは条件が違う）
--
-- **`REVIEW_RENAMED_SQL` は作品 1 件ごとに `max(changed_at)` を引く相関副問い合わせで
-- ある。** 索引が無いと、審査キューの候補 1 件につきこの表の全走査が 1 回走る
-- （候補 × 行数）。0017 と 0026 が索引を避けたのは「読むのは全走査で足りる規模の一覧
-- 1 本だけ」だからで、**相関副問い合わせは掛け算になる**ぶん条件が違う。
--
-- **書き込みの増分は改名 1 回につき 1 行**（3.6）。改名は生成と違って例外的な操作で、
-- 生成のたびに走る経路（0017 が避けたもの）ではない。
--
-- ## 題名そのものを持つ（UGC である）
--
-- **旧題名と新題名の両方を持つ。** 片方だけでは「何がどう変わったか」が復元できず、
-- 8.4 の「記録を残す」に足りない。**どちらも UGC なので、画面へ出すときは
-- `escapeHtml` を通すこと**（`scripts/report-queue.sh` はそもそも題名を出さない）。
--
-- ## CHECK を 2 つ張る
--
-- **口（`normalizeTitle`）と表の両方で守る**（0026 の `reason` と同じ形）。
--
--   - **`new_title` は空にならない。** `normalizeTitle` は空を `無題の作品` へ倒すので
--     （`src/games.ts`）、空が入るのは正規化を通さない経路ができたときだけである
--   - **`changed_at` は 0 より大きい。** 0 は「時計が読めなかった」形であり、
--     **`REVIEW_RENAMED_SQL` がそれを「1970 年の改名」として扱う**——最後の改名の時刻が
--     0 になると、その作品に付いたすべての通報が「改名後の通報」に化ける
--
-- **この CHECK は、改名と履歴が 1 つの batch であることの検査にも使っている**
-- （`test/title-rename.test.ts` が `now = 0` で `renameGame` を呼び、**batch ごと
-- 巻き戻って題名も変わらない**ことを見る。0026 が空の理由で同じことをしている）。
--
-- ## 連番が 0027 である理由
--
-- 着手時に空いている最小の番号である。**`0026` は #361（`admin_actions`）が使用済み**
-- で、適用済みの番号へ後から足せない（0026 の末尾と同じ理由）。`migrations/` を数えて
-- max+1 を取ったのではなく、空いている番号を確かめて取った（0009 の衝突はそれで起きた）。

CREATE TABLE title_changes (
  id TEXT PRIMARY KEY,
  -- 改名された作品。**実在する作品しか入らない**（上記）。
  game_id TEXT NOT NULL REFERENCES games(id),
  -- 変える前の題名（UGC）。
  old_title TEXT NOT NULL,
  -- 変えた後の題名（UGC）。**空は入らない**（上記）。
  new_title TEXT NOT NULL CHECK (length(new_title) > 0),
  -- 改名した時刻（UNIX 秒。0001 の方針）。**0 以下は入らない**（上記）。
  changed_at INTEGER NOT NULL CHECK (changed_at > 0)
);

-- 「その作品の最後の改名はいつか」を引くための索引（上記）。**列の順序に意味がある**
-- ——`game_id` で絞ってから `changed_at` の最大を取るので、この並びでなければ
-- `max(changed_at)` が索引だけで済まない。
CREATE INDEX title_changes_game_changed_idx ON title_changes (game_id, changed_at);
