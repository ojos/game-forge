-- 「その作品を最後に `cleared` にしたのはいつか」を引くための索引（8.4 / #394）。
--
-- ## なぜ索引が要るのか（0026 の「張らない」とは条件が変わった）
--
-- **0026 は `admin_actions` に索引を張らなかった。** 読むのは履歴の画面（`/actions`）の
-- `order by created_at desc limit <固定件数>` 1 本だけで、**この表は運営が押した回数しか
-- 増えない**——全走査で足りる、という判断だった。
--
-- **#394 で読み方が 1 つ増えた。** `src/reports.ts` の `REVIEW_REPORTED_AFTER_CLEAR_SQL` は、
-- **`cleared` の作品 1 件ごとに** この表から `max(created_at)` を引く相関副問い合わせで
-- ある。索引が無いと 1 回ごとにこの表を全走査するので、読み取りは
-- **`cleared` の作品数 × 履歴の行数**になる。`cleared` 1 件につき履歴は少なくとも 1 行
-- あるので、**実質は `cleared` の作品数の 2 乗**である（0027 の `title_changes` が
-- 「相関副問い合わせは掛け算になる」として索引を張ったのと同じ条件）。
--
-- ## 実測（2026-09-12。手元の workerd の D1。`meta.rows_read` と壁時計）
--
-- `cleared` の作品を N 本、各作品に通報 1 件と履歴 3 行（`cleared` → `queued` → `cleared`）、
-- 10 本に 1 本は `cleared` の後にもう 1 件の通報、を仕込み、審査キューの節と
-- `scripts/report-queue.sh` と同じ形の文を 3 回ずつ流した。
--
--   | 索引 | N    | 履歴の雑音 | 審査キューの節（limit 50） | report-queue.sh の文       |
--   |------|------|-----------|---------------------------|---------------------------|
--   | 無し | 1000 | 0 行      | 1,651,499 行 / 66 ms      | 3,303,399 行 / 134 ms     |
--   | 無し | 2000 | 0 行      | 3,301,500 行 / 147 ms     | 13,206,799 行 / 564 ms    |
--   | 無し | 1000 | 20,000 行 | 12,651,499 行 / 373 ms    | 25,303,399 行 / 722 ms    |
--   | 有り | 1000 | 0 行      | 2,049 行 / 1.0 ms         | 4,499 行 / 1.3 ms         |
--   | 有り | 1000 | 20,000 行 | 2,049 行 / 0.7 ms         | 4,499 行 / 1.0 ms         |
--
-- **索引が有れば、読み取りは履歴の行数に依らない**（雑音 0 行と 20,000 行で同じ行数）。
-- 当たる作品が 1 本も無い最悪の場合（外側の `games` を末尾まで舐める）でも、N = 1000 で
-- 3,999 行、N = 4000 で 15,999 行——**作品 1 本あたり 4 行で一定**であり、#366 の条件
-- （同じ形で 1 本あたり 3 行）と桁が変わらない。**外側の `games` の走査が作品数に比例する
-- のは #366 より前からの性質**である（0017 の「索引を張らない」。張る契機も 0017 のとおり）。
--
-- **`EXPLAIN QUERY PLAN` の字面だけを証拠にしていない**（#370 で、索引の印が出ていても
-- 絞れていない場合があると分かった）。上の行数と時間が証拠で、計画は
-- `SEARCH a USING COVERING INDEX admin_actions_target_idx (target_kind=? AND target_id=? AND action=?)`
-- ——索引が無いときは `SEARCH a`（索引の名前が無い。表を舐めている）だった。
-- **同じ実測の中で、索引を落としたあとも計画の表示が索引を名指ししたままの場面があった**
-- （そのときの行数は索引の無い値だった）。計画の字面を証拠にしない理由がここにもある。
--
-- ## 列の順序
--
-- **等号で絞る 3 列を先に置き、`max` を取る `created_at` を最後に置く。** この並びなら
-- 絞った範囲の末尾が最大値で、表の行を読まずに索引だけで済む（上の `COVERING`）。
-- `created_at` を前に置くと `max` が索引の範囲の端にならない。
--
-- **`target_kind` を含める。** いまの実装で `review-cleared` を書くのは作品を対象にした
-- `setReviewState` だけだが、**表の CHECK は `action` と `target_kind` の組を縛っていない**
-- （0026）。条件が `target_kind = 'game'` を見る以上、索引もそれを持たないと、絞った
-- 行ごとに表を読みに行く。
--
-- ## 書き込みの増分
--
-- **履歴 1 行につき索引 1 行**（3.6）。この表は運営が画面を押した回数しか増えない
-- （0026）ので、生成や通報の経路の費用には乗らない。
--
-- ## 連番が 0029 である理由
--
-- **`0028` は並行するレーン（#388。作品の説明）が使う**と、着手前に割り当てた番号である
-- （`docs/handoff.md` 3 章の「取り込む側が着手前に割り当てる」。`migrations/` を数えて
-- max+1 を取っていない——0009 の衝突はそれで起きた）。**本番への適用は、このレーンでは
-- 行わない**（利用者の端末。`docs/admin-host.md` の #394 の手順）。
--
-- **適用し忘れても壊れない**——索引は条件の意味を変えないので、読み取りが上の「無し」の
-- 行へ戻るだけである（クローズドβの規模では体感に出ない）。**ただし 2 乗なので放置しない。**

CREATE INDEX admin_actions_target_idx
  ON admin_actions (target_kind, target_id, action, created_at);
