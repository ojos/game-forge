-- 公開時に撮る OGP 画像の状態を `games` へ足す（5.4 / 11.2 / #26）。
--
-- 5.4 は「**OGP 画像の生成は「公開」時まで遅延する**」と定め、11.2 は「**MVP は初回
-- フレームの静止画 1 枚**」と定める。この 2 つを満たすには、作品行が次の 3 つを
-- 覚えている必要がある。
--
--   1. 撮影を**始めたか**（＝二度撮らないための関門）
--   2. 撮影が**終わったか**（＝メタタグに URL を出してよいか）
--   3. 撮れた画像が **R2 のどこにあるか**
--
--
-- ## 状態を持たずに済ませられない理由
--
-- キーは作品 id から決まる（`ogp/<game_id>.png`。`src/ogp.ts`）ので、「R2 に在るかを
-- 毎回見る」形にすれば列を 1 つも足さずに済む——**ように見える。** 採らない理由は
-- 2 つある。
--
--   - **作品ページを 1 枚描くたびに R2 への往復が増える。** メタタグを出すかどうかの
--     判定は、作品ページの表示のたびに要る。D1 の 1 行はどのみち引いているので、
--     そこに 1 列足すほうが安い。
--   - **「まだ撮っていない」と「撮ろうとして失敗した」を区別できない。** 3.3 の生成が
--     `generation_state` で「走っている / 終わった / 失敗した」を持つのと同じ理由で、
--     **黙って成功も黙って失敗も作らない**（仕様 1.2.31「黙って成功を作らない」）。
--
--
-- ## `ogp_state` に CHECK を張る
--
-- 0007 が `generation_state` に CHECK を張り、`generation_error` には張らなかったのと
-- **同じ軸で決める。** こちらは遷移そのもの（＝データの整合性）であり、綴りが増減する
-- のは表示の都合ではなくデータの意味が変わるときである。
--
--   NULL        … まだ撮ろうとしていない（公開前、あるいは撮影の呼び出しが設定不足）
--   'capturing' … 撮影を始めた。**この行の撮影権は 1 つしか無い**
--   'ready'     … 撮れて R2 に入った（`ogp_key` が入っている）
--   'failed'    … 撮れなかった（もう `ogp_key` は入らない）
--
-- **既定は NULL にする。** 0007 の `generation_state` が `NOT NULL DEFAULT 'ready'` で
-- 既存行を「完成済み」に倒したのは、当時すでに完成している行しか無かったからである。
-- こちらは逆で、**既存行はすべて未公開（＝撮っていない）** なので、NULL がそのまま真になる。
--
--
-- ## `ogp_token_hash` は 0007 の `job_token_hash` と同じ役割である
--
-- 撮影の本体（headless chromium）は Worker の外——AWS Lambda——で走る。**外側から
-- D1 を書く経路が要る。** 0007 が示した答え（Cloudflare の API トークンを AWS へ
-- 置かず、**1 行だけを進められる使い捨てトークン**を使う）をそのまま当てる。
--
-- このトークンにできるのは「**この 1 行の OGP を ready か failed にすること**」だけで、
-- 他の作品にも他のテーブルにも届かない。平文は D1 に残らず、保存するのは SHA-256 だけ
-- である（`src/games.ts` の `hashJobToken` を共用する）。
--
-- **コールバックが 1 回効いたら NULL へ落とす。** これが撮影側の冪等性である——
-- Lambda の非同期呼び出しは同じイベントを複数回配信しうるが（AWS 明文）、
-- 2 通目のコールバックはトークンが消えているので弾かれる。
--
--
-- ## 索引を張らない
--
-- 0004 / 0006 / 0007 / 0008 は「**必要とする問い合わせが決まっているから張る**」と
-- いう 0001 の規約で索引を足してきた。**この 3 列を条件に引く問い合わせは 1 つも無い。**
-- 画像の配信（`/ogp/<game_id>.png`）も作品ページも、主キー（`games.id`）で 1 行を
-- 引いてからこれらの列を読む。**張れば書き込みのたびに索引が 1 行増えるだけになる。**
ALTER TABLE games ADD COLUMN ogp_key TEXT;

ALTER TABLE games ADD COLUMN ogp_state TEXT
  CHECK (ogp_state IS NULL OR ogp_state IN ('capturing', 'ready', 'failed'));

ALTER TABLE games ADD COLUMN ogp_token_hash TEXT;
