-- 3.8 の degrade の発火信号を、サーバ側へ置く（#140 / 確定24）。
--
-- ## なぜ表が要るのか
--
-- 3.8 は「停止時は生成 UI に『生成停止中』を表示し、プレイ側には一切影響を出さない」と
-- 定め、確定24 は停止事象を**関数の失敗・スロットリング・リージョン障害**と定義し直した。
-- **どれも 1 つの要求からは読み取れない。** #24 の実装は画面が自分の要求の 5xx を
-- 観測する近似で、次の 2 つの誤りが構造的に残っていた。
--
--   誤爆 … 5xx には D1 の不調も落ちてくる。ビルド経路が生きていても「生成停止中」を出す
--   見逃し … 他の利用者のビルドが軒並み失敗していることは、自分が投げるまで見えない
--
-- **どちらも「観測点が 1 要求しかない」ことから来ている。** 要求をまたいで数えられる
-- 場所が要る。それがこの表である。
--
--
-- ## 書き込みを増やさない形にしてある（3.6）
--
-- 3.6 は「リクエスト毎の書き込みを避ける」と定め、書き込みと読み取りで単価が 1,000 倍
-- 違うことを理由に挙げている。**この表は生成 1 回あたりの書き込みを 1 行も増やさない。**
--
--   - 行が入るのは**ビルド依頼そのものが失敗したとき**だけである。平常時は 0 行で、
--     成功した生成は 1 度もこの表へ触れない（書き込みも読み取りも起きない）。
--   - 復帰（成功時の消去）は `delete` である。**平常時は表が空なので 0 行の削除**に
--     なり、D1 が数える行書き込みは 0 のままである。この性質は
--     `test/build-health.test.ts` が `meta.rows_written` で機械照合する
--     （「増えないはず」を言葉で担保しない）。
--   - **索引を張らない。** 索引は 1 行の insert につき 1 行の書き込みを足す（3.6）。
--     この表は平常時 0 行・障害時でも窓のあいだの失敗件数（数件）しか持たないため、
--     全走査で足りる。**「将来使うかもしれない」で足さない**（0001 の方針）。
--
--
-- ## 列
--
-- **`game_id` を主キーにする。** 数えたいのは「失敗した**依頼**の数」であって、
-- ビルド関数を何回叩いたかではない。1 依頼のあいだにビルドは最大 9 回走りうるので
-- （5.2-7 の 3 試行 × 機械修正 ＋ #164 の呼び直し）、呼び出しを数えると
-- **1 人の要求だけで閾値へ届く。** 確定24 が言う停止事象は 1 要求からは読み取れない
-- ものであり、そこを崩すと誤爆の側へ倒れる。
--
-- 主キーにしておくと、Lambda の重複配信（AWS が明文で認めている。0007 参照）で
-- 同じ `finish` が 2 回届いても行は増えない。**数え方が配信の都合で狂わない。**
--
-- **`games(id)` への外部キーを張らない。** この表は**信号**であって作品の記録ではなく、
-- 復帰時に丸ごと捨てられることが要件である（上記）。参照制約は、その「いつでも捨てて
-- よい」性質に対して何も足さず、insert のたびに `games` の読み取りを増やす。
--
-- **利用者を持たない。** 停止しているかどうかは誰が投げたかに依らない（3.8 の degrade は
-- サービス全体の状態である）。持てば、信号を読むだけで「誰が何時に失敗したか」が
-- 引ける表になる。**要らない情報を持たない。**
CREATE TABLE build_health (
  -- 失敗した生成依頼（`games.id`）。1 依頼 1 行。
  game_id TEXT PRIMARY KEY,
  -- ビルド依頼の失敗を記録した時刻（UNIX 秒）。窓の判定に使う。
  failed_at INTEGER NOT NULL
);
