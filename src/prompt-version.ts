/**
 * システムプロンプトの版（#605）。
 *
 * **`generations.prompt_version` へ入れる値をここが持つ。** これが無いと、プロンプトを
 * 変えても「どの版が作った生成か」を後から分けられず、**前後比較ができない。** #597 が
 * まさにその状態で、基準線は取ったのに効果を言えないまま終わっている。
 *
 * ## なぜ本文のハッシュを実行時に計算しないのか
 *
 * **`src/system-prompt.ts` は時刻も乱数も暗号も読めない**（4.5 のキャッシュの前提。
 * 本文が呼び出しごとに変わるとキャッシュが常時ミスする。`test/system-prompt.test.ts` が
 * `Date` と `crypto.randomUUID` を呼べなくした状態で組み立てられることを見ている）。
 * ハッシュを実行時に計算すると、その禁止に近いものを生成の経路へ持ち込むことになる。
 *
 * **代わりに、整数の版と本文のハッシュを定数として持ち、テストが照合する。**
 * 本文を変えたら {@link PROMPT_TEXT_SHA256} が合わなくなり、**版を上げるまでテストが
 * 落ちる。** 実行時の計算は 1 度も起きない。
 *
 * これは shared-ai-rules 12 章の「一覧の複製は機械照合で担保する」と同じ形である——
 * 版という複製を置くが、**古くなったことを機械が判定する**ので、空更新では通らない。
 */

