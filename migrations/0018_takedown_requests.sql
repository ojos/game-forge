-- 権利者からの削除申請と、送信防止措置の記録（8.4 / 5.6 / #41）。
--
-- ## なぜ表が要るのか
--
-- 8.4 は「**送信防止措置の手順と記録を残す**（情報流通プラットフォーム対処法への対応）。
-- **削除申請フォームの設置だけでは足りない**」と定める。**申請を受けたことと、それに
-- 対して何をしたかの両方**が残らなければ、記録として意味を持たない。
--
-- ## 1 つの表で持つ
--
-- 申請と措置を別の表に割らない。**割ると「申請は在るが措置の行が無い」状態が、
-- 「まだ何もしていない」なのか「記録し忘れた」なのか区別できなくなる。** 同じ行へ
-- 追記していく形なら、`handled_at` が NULL であることが「未対応」の唯一の意味になる。
--
-- ## 追記のみにする
--
-- #41 の acceptance が「**追記のみの形式で保存される**」を求めている。**申請の内容
-- （`reporter_*` と `body`）は 1 度書いたら書き換えない。** 変わるのは措置の側
-- （`handled_at` / `action` / `note`）だけである。
--
-- **`delete` を掛ける経路をアプリに作らない。** `scripts/moderation-prune.sh` のような
-- 掃除は**この表に対しては用意しない**——8.4 が求めているのは記録を残すことであり、
-- 保持期間を切ることではない。
--
-- ## 申請者は非ログインである
--
-- 権利者はこのサービスの利用者とは限らない（むしろ通常は違う）。`users` を参照しない。
-- **連絡先は申請者が名乗った値であり、検証していない**（5.6 が `x_handle` について
-- 「未検証の自称値」と書いているのと同じ扱い）。

CREATE TABLE takedown_requests (
  id TEXT PRIMARY KEY,
  -- 対象の作品。**外部キーを張らない**——申請の時点で id が実在しない（打ち間違い・
  -- 既に消えている）ことがありうる。**受け取れなかった申請が記録に残らない**ほうが
  -- 8.4 に反する。
  game_id TEXT NOT NULL,
  -- 申請者が名乗った氏名・連絡先。**検証していない**（上記）。
  claimant_name TEXT NOT NULL,
  claimant_contact TEXT NOT NULL,
  -- 申請の本文（どの権利に基づき、何を求めるか）。
  body TEXT NOT NULL,
  received_at INTEGER NOT NULL,
  -- ここから下が送信防止措置の記録。**NULL は「まだ対応していない」**である。
  handled_at INTEGER,
  -- 採った措置。値の綴りは `src/takedown.ts` が持つ（ここへ書き写さない）。
  action TEXT,
  -- 判断の理由。運用が書く。
  note TEXT
);

-- **未対応のものを引くための索引は張らない。** 平常時この表はほとんど増えず
-- （削除申請は例外的な出来事である）、全走査で足りる。3.6 が索引の費用を挙げている
-- とおり、**「将来使うかもしれない」で足さない**（0001 の方針）。
