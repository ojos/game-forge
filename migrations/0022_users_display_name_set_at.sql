-- 利用者が表示名を自分で決めた時刻を `users` へ足す（5.1 / 5.9 / #341）。
--
-- ## なぜ列が要るのか
--
-- 表示名は v1.50 で**未ログインの閲覧者にも見える値**になった（作品ページ・作品カード・
-- 作者ページ。2.3）。いまはログインのたびに `src/auth/google.ts` が Google の表示名で
-- 上書きしているので、アプリ側で名前を変えられるようにしても**次のログインで戻る。**
-- 「利用者が決めたかどうか」を持たないと、上書きしてよいかをログインの経路が判断できない。
--
-- 意味は 2 値である。
--
--   - **NULL: Google の表示名に追随する**（ログインのたびに上書きする。いままでの振る舞い）
--   - **値あり: 利用者が決めた**（ログインで上書きしない。値は最後に変えた UNIX 秒）
--
--
-- ## 真偽値ではなく時刻で持つ
--
-- 5.9 は「**前回の変更から 60 秒以上空いた要求だけ書く**」と定める（連打で D1 の書き込みを
-- 増やさない。3.6）。**その判定に要るのは前回の時刻そのもの**であり、真偽値と時刻を
-- 別の列で持つと、片方だけが更新された行が「決めたのに時刻が無い」状態を作る。
-- 1 列にすれば、2 つの事実が食い違う余地が無い（`users.banned_at` と同じ形）。
--
--
-- ## 既存の行を埋めない
--
-- **新しい列を足したら、既存の行がその経路を 1 度も通っていないことを疑う**
-- （`docs/handoff.md` 1 章。#202 / #203）。ここで疑った結果は「埋めてはいけない」である。
-- 既存の利用者は**誰も自分で名前を決めていない**——いま入っている名前はすべて Google から
-- 写したものなので、**NULL（追随する）がその時点で真である値**になる。
-- **変えない限り、今までと同じ振る舞いになる**（5.9）。
--
--
-- ## 運営が名前を直すとき
--
-- 5.9 は「不適切な名前は運営が D1 を直接 UPDATE して戻す」と定める（管理 UI は持たない）。
-- **`display_name` だけを書き換えて、この列が NULL のままだと、次のログインで Google の
-- 名前に上書きされる。** 直した名前を残したいなら、この列にも時刻を入れること。
-- 逆に **Google の名前へ戻したいなら、この列を NULL にすれば次のログインで戻る。**
--
--
-- ## 索引を張らない
--
-- この列を条件にする問い合わせは、ログイン（`google_sub` の一意索引で 1 行を引く）と
-- 表示名の変更（主キーで 1 行を引く）だけで、**どちらも既に 1 行へ絞った後に読む。**
-- 張れば変更のたびに索引が 1 行増えるだけになる（3.6「書き込みの見積もりは索引込みで」）。
ALTER TABLE users ADD COLUMN display_name_set_at INTEGER;
