/**
 * 運営からのお知らせの記事（2.3.1 / #375）。**置き場はこのファイル（静的な定義）である。**
 *
 * ## なぜ D1 に置かないのか
 *
 * 1. **トップの読み取りが 1 行も増えない**（2.3.3 の条件 1）。D1 に置けば件数を固定して
 *    索引を張ることになり、トップが引く問い合わせが 1 本増える。静的な定義なら 0 本である
 * 2. **書き込みの画面を持たない**（#375 の scope.out。運営は端末から書ける）。D1 に置いても
 *    書く手段は端末からの SQL で、**ここを編集して配備するのと手数が変わらない**
 * 3. **マイグレーションが要らない**
 *
 * ## 代償: 更新には配備が要る
 *
 * **記事を足すにも直すにも、`main` へのマージと配備を待つ。** 障害のような急ぎの告知も
 * 配備待ちになる。**配備そのものが止まっている障害のあいだは、ここからは告知できない**
 * ——この欄を障害の唯一の告知手段として扱わないこと（仕様 2.3.1 の実装注記）。
 *
 * ## 記事を足すとき
 *
 * - **新しい記事を配列の先頭へ足す。** 並びは `publishedOn` の新しい順で、崩れていれば
 *   `test/news.test.ts` が落ちる（並べ直す処理を画面の側に持たない）
 * - **`body` の 1 段落目はトップにも出る。** その段落だけで意味が通るように書く
 * - **本文は素の文字列である。** HTML は書けない（画面が `escapeHtml` を通す）。
 *   **記事の中身から HTML を組み立てる経路を作らない**ためである
 * - **事実だけを書く。** 数字を書いたら、その正本（定数）との一致を `test/news.test.ts` へ足す
 *   （`.ai-playbook/shared-ai-rules.md` 12 章）。**記事は日付の付いた写しなので、正本が
 *   変わったら記事を直すか、新しい記事を足す**——テストが落ちるのはその合図である
 * - 直したときは `updatedOn` を付ける（一覧とトップの「最終更新日」に効く）
 */

