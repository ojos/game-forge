-- 「あなたの作品」一覧が自分の作品を新しい順に引くための索引（5.5 / #152）。
--
-- **#150 の補強である。** #150 は送信直後に作品の恒久的な URL を返すようにしたが、
-- 利用者がその URL を控え損ねる経路は普通にある（タブごと閉じた・別の端末で見たい・
-- しばらく経ってから思い出した）。**91 秒待った成果物へ戻る道が URL 1 本しかないのは
-- 細すぎる。** `games` は `author_id` を持っているので引けるが、**引くための索引が無い。**
--
--
-- ## 単独ではなく複合にする
--
-- 一覧が実際に投げる問い合わせは `author_id` の等価条件だけではない。
--
--     select ... from games
--      where author_id = ? and status <> 'removed'
--      order by created_at desc, id desc
--      limit ?
--
-- `author_id` だけの索引でも行は絞れるが、**並べ替えが残る。** SQLite は
-- ORDER BY を索引で満たせなければ一時 B-tree を作る（`USE TEMP B-TREE FOR ORDER BY`）。
-- そうなると `limit` があっても**その作者の全行を読んでから並べる**ことになり、
-- 一覧を開くたびに読み取り行数が作品数に比例して増える。3.6 は読み取りの単価が安いと
-- 言っているが、**「安いから何行読んでもよい」とは言っていない。**
--
-- 索引の列順を問い合わせの形（等価 → 並べ替え）に合わせておけば、読むのは
-- **上から `limit` 行だけ**になる。
--
--
-- ## DESC を索引に書く
--
-- SQLite は索引を逆向きにも走査できるため、`ORDER BY created_at DESC` の 1 列だけなら
-- 昇順の索引でも足りる。**足りなくなるのは 2 列目からである。** `created_at DESC, id DESC`
-- のように**全列が同じ向き**なら昇順索引の逆走査で満たせるが、この一致は列を 1 つ足した
-- 日に黙って崩れる。**索引の向きを問い合わせの向きに合わせて書いておく**ほうが、
-- 満たせているかどうかを読んで確かめられる。
--
-- 検査は `test/my-works.test.ts` が `EXPLAIN QUERY PLAN` で行う。**索引が「存在すること」
-- ではなく、この問い合わせが実際にそれを使い、一時 B-tree を作らないことを見る**
-- （shared-ai-rules 12 章。存在の検査は、索引を使えない形に問い合わせを書き換えても通る）。
--
--
-- ## `id` を 3 列目に入れる
--
-- `created_at` は UNIX 秒なので、**同じ秒に作られた 2 件の順序が決まらない。** 生成は
-- 1 日 12 回まで（確定25）なので実運用で衝突はまず起きないが、順序が決まらない一覧は
-- 「並びが変わった」と「作品が消えた」を利用者が区別できない形で見えることがある。
-- 主キーで割ることで並びが決定的になる。
--
-- 3 列目を足しても**書き込みの費用は変わらない**（3.6 が数えるのは行数であって列数では
-- ない）。`games` の insert 1 件につき索引が 1 行増える点は 2 列でも 3 列でも同じである。
--
--
-- ## 部分索引にしない
--
-- 0007 の `games_generation_state_idx` は部分索引（`WHERE generation_state IN (...)`）
-- である。あちらは対象が全体のごく一部（生成中の行）だから小さく保てた。**こちらは
-- 逆で、対象は全行である**（すべての作品は誰かの作品である）。`status <> 'removed'` を
-- 索引側の条件にする案もあるが、`removed` は 8.4 の削除申請と 5.3 の tombstone だけが
-- 作る稀な状態で、除いても索引はほとんど小さくならない。**条件を足した分だけ、
-- 問い合わせ側が同じ式を書き続けなければ索引が使われなくなる**という制約が増えるだけになる。
--
--
-- ## 費用
--
-- `games` への insert 1 件あたり索引の書き込みが 1 行増える。生成は月数百件の規模で
-- （3.7 / 確定25）、書き込みの無料枠 10 万行/日 に対して無視できる。0004 / 0006 / 0007 と
-- 同じく、**必要とする問い合わせが決まっているから張る**（0001 の冒頭が定める規約）。
CREATE INDEX games_author_id_created_at_idx
  ON games(author_id, created_at DESC, id DESC);
