-- ## `0015` の「利用者が書いた文字列そのものは入れない」を、この列についてだけ覆す
--
-- `0015` は「入れると 5.1 の入力が別の列へ複製される」として `ip_notice` に正式名しか入れなかった。
-- **今回は複製そのものが目的である**（利用者の決定。他の案は「推敲の指示だけ返す」「指示は返さない」）。
-- 代わりに、**消す約束をすべてこの列にも効かせる**。
--
--   - **作者本人にしか返さない**（`src/works-api.ts`。公開面・ソース閲覧・作者ページには出さない。1.2.54）
--   - **作品の削除で消える**（`src/game-deletion.ts`。行を消す枝では行ごと、行を残す枝では NULL へ戻す）
--   - **退会で消える**（`src/withdrawal.ts` の段3。台帳の `prompt` を空にするのと同じ文の並び）
