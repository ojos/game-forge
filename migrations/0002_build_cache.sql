-- ビルド結果キャッシュの索引（仕様 3.8「ビルド結果キャッシュ」/ #19）。
--
-- 3.8 は保存先を **関数の外（R2 の既存オブジェクトと D1 の索引）** と定めている。
-- Lambda に永続ボリュームが無く、`/tmp` は実行環境ごとに分かれるうえ 7.1 の掃除で
-- 毎回消えるためである。**このテーブルはその「索引」の側**であり、成果物そのものは
-- 持たない。持つのは「このソースは、この R2 のオブジェクトとしてビルド済みである」
-- という対応関係だけである。
--
-- **3.6 の書き込み無料枠を圧迫しない。** 書くのは 1 ビルド成功につき 1 行で、
-- `games` 行の作成と同じ桁である（月数百件規模）。読み取りは生成のたびに 1 行。
--
-- **`games` を参照しない。** 索引は「ソース → 成果物」の対応であって、作品の属性では
-- ない。同じソースから複数の作品行が生まれうる（別の利用者が同じプロンプトで同じ
-- コードに行き着く、フォークで実質同一のソースになる）ため、外部キーを張ると
-- 1 対 1 でない関係を 1 対 1 に見せることになる。
--
-- 時刻は 0001 と同じく **UNIX 秒の INTEGER** で持つ。

CREATE TABLE build_cache (
  -- 生成ソース（UTF-8）の SHA-256 を小文字 16 進で持つ。3.8 の「生成ソースの
  -- コンテンツハッシュ」そのもの。**ソース本文は持たない**（R2 側にある）。
  source_sha256 TEXT PRIMARY KEY,
  -- ビルドに使った Go の版。3.5 の `wasm_exec.js` 出し分けが `games.go_version` に
  -- 要求する値で、キャッシュヒットのときはここから取る（再ビルドしないため、
  -- 関数からは受け取れない）。
  go_version TEXT NOT NULL,
  -- R2 のキー。**このキーの命名は #21（3.3-6 / 3.3-8）が持つ。** 索引は与えられた
  -- ものを覚えるだけで、綴りを決めない。
  source_key TEXT NOT NULL,
  wasm_key TEXT NOT NULL,
  -- 成果物の申告値（関数が返す `wasm` / `compressed`）。ヒット時に再ビルドせずに
  -- `games` 行を作れるだけの情報を持たせる。
  wasm_bytes INTEGER NOT NULL,
  wasm_sha256 TEXT NOT NULL,
  compressed_bytes INTEGER NOT NULL,
  compressed_sha256 TEXT NOT NULL,
  -- 3.4-1 が R2 のオブジェクトメタデータへ求める値（`br`）。関数が名前ごと決めている
  -- ので、索引側で綴りを選び直さない。
  content_encoding TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

-- **索引にインデックスを足さない。** 引き方は `source_sha256` の等値 1 通りで、
-- それは主キーが担う。0001 の方針（必要とする問い合わせが決まっているものだけを
-- 張る）に従う。3.7 のゴミ掃除（M5-4）が created_at で走査する形になったら、
-- そのときに足す。
