-- 公開作品の一覧（#328 / M9-2 / 仕様 2.3.3 の条件 2）が引くための索引。
--
-- ## なぜ要るのか
--
-- `games` には索引が 5 本ある（`source_key` / `wasm_key` / `parent_id` /
-- `(author_id, created_at DESC, id DESC)` / `generation_state` の部分索引）が、
-- **そのどれも `status` や `published_at` を先頭に持たない。** この状態で
-- 「公開作品を新しい順に 20 件」を引くと全表走査になり、**読み取り行数が開設以来の
-- 全作品数に比例する。** 3.6 は読み取りの単価が安いと言っているが、比例して増える形は
-- 母数が増えるほど効いてくる（4.3 が `generations` の日次集計について警告しているのと
-- 同じ形である）。
--
-- 仕様 2.3.3 は、トップの D1 読み取りを解禁する 3 条件の 2 つ目としてこの索引を挙げる。
-- **条件のほうが本体である**——件数を固定し、索引を張り、Cache API を前段に置く。
--
-- ## 2 本張るのは、並べ替えが 2 軸だから
--
-- 仕様 2.3.4 が定める軸は `recent`（新着）と `forked`（改造された数）の 2 つだけである。
-- **軸ごとに索引が要る。** 片方だけ張ると、もう片方は全表走査のまま残り、
-- 「並べ替えを変えたら遅くなる」という**利用者からは理由の見えない差**になる。
--
-- 並べ替えの最後に `id` を置くのは、`published_at` も `fork_count` も**同じ値を持つ行が
-- 普通にある**ためである（`fork_count` は大半が 0 で、公開が同じ秒に 2 件起きることも
-- ありうる）。同値の順序が決まらないと、ページ送りで**同じ行が 2 頁に出たり 1 件も
-- 出なかったりする。** 0008 が `created_at` について同じ理由で `id` を足している。
--
-- ## 部分索引にしない
--
-- 0007 の `generation_state` は部分索引だが、あちらは「生成中の行は全体のごく一部」
-- という前提が成り立つ。**公開作品はそうではない**（増え続ける側である）。
-- 加えて `status = ?` は値を束縛して渡すため、`WHERE status = 'published'` を条件に持つ
-- 部分索引が使われる保証がない。**先頭列に `status` を置いた通常の索引にする。**
--
-- ## 費用
--
-- `games` への insert 1 件あたり、索引の書き込みが 2 行増える。生成は月数百件の規模で
-- （3.7 / 確定25）、書き込みの無料枠 10 万行/日 に対して無視できる。
-- **必要とする問い合わせが決まっているから張る**（0001 の冒頭が定める規約）。

-- 新着順（`sort=recent`）。
CREATE INDEX games_status_published_at_idx
  ON games(status, published_at DESC, id DESC);

-- 改造された数の順（`sort=forked`）。同数のときは新しい順に落とす。
CREATE INDEX games_status_fork_count_idx
  ON games(status, fork_count DESC, published_at DESC, id DESC);
