-- ## 値の形と NULL の意味
--
-- - **組の JSON 配列**（例: `[["ArrowUp","KeyW","Space"]]`）。組の中は `KeyboardEvent.code` を重複なしの昇順で持ち、
--   キーが 2 つ以上の組だけを残す。**`[]` は「拾ったが、同じ条件式で読むキーの組は無い」。**
-- - **NULL は「組がまだ記録されていない」行である。** 規則の版 2 以下の書き込みで作った行がこれに当たり、**0043 を当てる前の
--   行だけでなく、当てた後に #543 の実装が入るまでの書き込み（今の UPSERT は、この列を指定しない）で作った行も含む。**
--   仕様 3.9.6 で、今の規則 5 のとおり方向をボタンに回す。埋め戻しは `rule_version` が古い行を拾い直すので、どちらの NULL も同じく埋まる。
