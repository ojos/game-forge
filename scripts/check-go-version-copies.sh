#!/usr/bin/env bash
# check-go-version-copies.sh — Go の版の写しを正本（ARG GO_VERSION）と機械照合する（#141）
#
# 位置づけ:
#   判定はこのスクリプトが持ち、scripts/acceptance.sh は呼ぶだけ。
#   scripts/check-control-chars.sh / scripts/check-deps-installed.sh と同じ形にそろえる。
#
# なぜ機構で押さえるか:
#   **#101 の時点で 4 か所が 1.26.5 のまま取り残されていた**（terraform の scan_on_push の
#   注記 / deploy-compiler.yml の --platform の注記 / check-isolated-build.sh のホストの Go を
#   判定する段の注記 / docs/build-function.md の構成表）。いずれも 1 行のコメントだが、
#   事実と食い違っていた。**写しは「揃え忘れることがある」のではなく「必ず古くなる」。**
#   #101 はこの 4 か所を「版を書かずに `ARG GO_VERSION` を指す」形へ改めたが、
#   **値を書かないわけにいかない場所は残っている**（確定12 の行 / 3.5 の採用バージョン /
#   3.8 のベースイメージ）。そこは機械で見るしかない。
#   shared-ai-rules 12 章「一覧の複製は機械照合で担保する」の適用である。
#
# 正本:
#   docker/isolated-build/Dockerfile の `ARG GO_VERSION=<X.Y.Z>`。1 行だけ存在すること、
#   値が 3 成分の版であることまで見る（正本が曖昧なら照合そのものが成立しない）。
#
# ── この検査のいちばんの勘所: 「記録」と「写し」をどう見分けるか ──────────────
#
# 仕様書 3.5 の更新手順 7 は **「実測の記録は書き換えない」** と定めている。
# リポジトリには「2026-08-28 に Go 1.26.5 で測った」「当時のピン留めは 1.26.5 だった」
# といった**過去の事象**が版番号つきで多数書かれており、**これらを正本へ揃えると
# 記録のほうが嘘になる。** つまり除外を表現できないと、この検査は運用できない。
#
# 一方で **除外の指定そのものが写しになってはいけない**（#141）。次の形はいずれも
# 採らない。どれも「正本が動いたときに、別の場所を人が直す」ことを要求するからである。
#
#   - 版番号の免責リスト（例: 「1.26.5 は記録なので見逃す」）。**最悪の形である。**
#     正本が 1.26.8 へ動いた瞬間に、今度は 1.26.7 を足しに行かねばならない。
#   - ファイル名・行番号の除外リスト。行番号は 1 行の挿入で崩れ、ファイル名は
#     「そのファイルに新しく書かれた写し」を丸ごと見逃す。
#   - 「記録」側へ新しい印を打って回る形。記録は**書かれ続ける**（実測も変更履歴も
#     一度書けば永久に残る）ので、印の付け漏れが増え続ける側に賭けることになる。
#
# **採ったのは「写しの側が、自分の正本の在り処を名乗っている」ことを印にする形である。**
#
#   判定単位は **1 行**。同じ行に次の 3 つが揃っているとき、その行を「写し」とみなす。
#     (1) 版番号（`X.Y.Z`）
#     (2) `ARG GO_VERSION` への言及
#     (3) 「正本」の語
#   写しとみなした行は、**書かれている版番号のどれかが正本と一致していなければ落ちる。**
#
# この印が古くならない理由:
#   **印は版番号を含まない。ファイル名も行番号も含まない。** 正本が動いても印は動かない。
#   そして印は、この検査のために発明した新しい構文ではない。**3.5 の更新手順 6 が
#   写しの置き場に対して既に要求している文**（「値の正本は `docker/isolated-build/
#   Dockerfile` の `ARG GO_VERSION`」）そのものである。3.5 は
#   **「この 2 つは見分けが付くように書く」**（写しと記録）と書いており、
#   **機械は人が読むのと同じ見分けを読んでいる。**
#
# 何を対象外にするか（＝除外の表現。除外リストは存在しない）:
#   - **印の無い行はすべて対象外。** 実測の記録、変更履歴（1.2.NN）、踏んだ事故の記録、
#     テストの固定値、R2 キーの例、`go env GOVERSION` の出力例は、いずれも自分の正本を
#     `ARG GO_VERSION` だと名乗らない。名乗る理由が無い。**現行の申告ではないからである。**
#   - **印はあるが版番号の無い行も対象外。** これは #101 が 4 か所へ施した
#     「版を書かずに `ARG GO_VERSION` を指す」形そのもので、**望ましい書き方である。**
#     ここに版を書き戻した瞬間、その行は写しになり、この検査の対象に入る。
#     すなわち **#101 で踏んだ退行は、踏み直した瞬間に落ちる。**
#
# 判定単位を「行」にした理由（段落ではなく）:
#   段落単位にすると**既存の記録を巻き込んで偽陽性を出す。** 実例が 2 つある。
#     - docs/product-spec.md の変更履歴の節は、「版の正本は … `ARG GO_VERSION`」の
#       次の行で「4 か所とも当時の版のまま取り残されていた」と**記録**を書いている。
#     - docs/build-function.md は、「この出力例は Go 1.26.5 時点の記録です」の次の行で
#       「`ARG GO_VERSION` への参照へ置き換えていないのは…」と**理由**を書いている。
#   どちらも段落単位なら 1.26.5 を写しと誤認し、**記録を書き換えろと迫る。**
#   それは 3.5 の更新手順 7 に真っ向から反する。**偽陽性の向きが致命的なので、
#   狭いほうの単位を採る。**
#
# 承知のうえで受け入れる限界:
#   - **印を書かずに新しい写しを増やすと、この検査からは見えない。** 既定は「対象外」で、
#     写しの側が名乗ることで対象に入る形だからである。**記録側へ印を打つ形（既定を
#     「対象」にする形）を採らなかったのは、上記のとおり記録が無限に増え続けるためで、
#     その形こそ「古くなる除外リスト」になる。** 埋め合わせとして、写しが 1 件も
#     見つからない場合を失敗にする（下記）。3.5 の更新手順 6 に、写しには正本の在り処を
#     同じ行に書く旨を明記してある。
#   - **1 行に「古い写し」と「新しい写し」が同居すると通る。** 写しの行が正本を 1 つでも
#     含めば合格とするためである。すべての版番号の一致を求める形は採れない。
#     確定12 の行は**同じ行で 1.27.0（次の系列への移行契機）に触れており**、
#     それは写しではないからである。
#   - **印のある行に、版以外の 3 成分の数を書くと落ちる。** 節番号（`1.2.38`）が
#     版番号と同じ形をしているためで、形だけでは区別できない。**この検査は現に
#     自分自身のこのコメントで落ちた**（初回実行時。`1.2.38` を書いていた）。
#     Go の版に `1\.[0-9][0-9]` のような仮定を置けば消せるが、それは Go の採番規則を
#     このスクリプトへ書き写すことなので採らない。**印のある行は、正本の版だけを
#     書く行にする**（落ちたときの直しかたは失敗メッセージが出す）。
#   - Go 以外の版（Ebitengine、`golang.org/x/image`）は見ない（#141 の scope.out）。
#
# 踏んだ事故（2026-08-29 / #141 のマージ後に main の CI を赤にした）:
#   **手元（mawk）で緑、CI（gawk）で偽陽性**という形で落ちた。原因は 2 つあり、
#   **どちらか片方だけでは起きない。**
#
#     (1) **`-v` は値のエスケープを解釈する。** POSIX の awk は `-v x=...` の値を
#         文字列リテラルと同じ規則で処理する。`\.` は awk にとって未知のエスケープで、
#         **gawk はこれを素の `.`（任意の 1 文字）へ潰す**（警告を出す）。mawk は
#         バックスラッシュを残すため、手元では正しいまま動いていた。
#     (2) **分類器へ grep の `パス:行番号:本文` をそのまま渡していた。** 判定したいのは
#         本文だけなのに、**パスと行番号まで走査対象に入れていた。**
#
#   結果、`docs/build-function.md:417:3.5 の手順に従います。…` という**参照形の行**が、
#   **行番号と節番号をまたいだ `417:3.5` を「版番号」として拾われ**、写しと誤判定された。
#   その行に版番号は 1 つも書かれていない。
#
#   直しかたは 2 つとも塞ぐこと。
#     (1) **正規表現のドットは `[.]` と書く。** ブラケットの中のドットは BRE でも ERE でも
#         awk でも常にリテラルで、**エスケープの解釈差が原理的に起きない。** あわせて
#         パターンは `-v` ではなく **ENVIRON 経由**で渡す（ENVIRON はエスケープを解釈しない）。
#         `-F.` も単一文字 FS の扱いが実装で割れるため `-F'[.]'` と書く。
#     (2) **判定は本文だけを見る。** パスと行番号は表示のためだけに持ち、走査から外す。
#
#   **自己診断がこれを捕まえられなかったことが、本当の欠陥である。** 当時の合成入力は
#   参照形の行に**数字を 1 つも含めておらず**、ドットが緩んでも当たりようがなかった。
#   いまは「参照形」「節番号」「日付」「サイズ」「版番号を含むパス」を合成入力へ入れ、
#   **`パス:行番号:` を付けた形**で通している（下記 self_check）。実装差でドットが緩めば、
#   走査へ入る前に自己診断が落ちる。

# 移植性の約束（上記の事故を受けて洗い直した。同じ種類の穴を残さない）:
#   この検査は sed(BRE) / grep(ERE) / awk(ERE) の 3 つの正規表現方言をまたぐ。
#   **3 つすべてで同じ意味になる書き方しか置かない**、を約束にする。
#
#     - **正規表現のドットは必ず `[.]`。** `\.` は書かない（実装差の入口）。
#     - **パターンを awk へ渡すのは ENVIRON 経由。** `-v` と `-F` は値をエスケープ解釈する。
#       `-F` に単一のドットを渡す形（`-F.`）も、単一文字 FS の扱いが割れるので `-F'[.]'` と書く。
#       `-F'\t'` だけは例外で、`\t` は**どの実装でも定義されている**エスケープなので使ってよい。
#     - **awk のプログラム本体に書く正規表現リテラルは安全。** 伝達経路を通らないため。
#     - **GNU 拡張に寄りかからない。** `sed` の `\t` や `\+`、`grep -P` は使わない。
#       `grep -I`（バイナリを飛ばす）だけは POSIX 外だが、無い実装では grep がエラーを返し、
#       それは標準エラーの非空として**失敗**に倒れる（黙って通らない）ので許容する。
#     - **判定に使う文字列は本文だけ。** パス・行番号・整形用の前置きを混ぜない。
#
# 検査が成立していないことを合格にしない:
#   git 管理外での実行、追跡ファイル 0 件、grep 自体の失敗、正本が読めない・複数ある、
#   **写しが 1 件も見つからない**、のいずれも「写しが正しい」ことを意味しない。すべて失敗。
#   加えて起動時に**分類器そのものを自己診断する**（食い違う写しで必ず当たること、
#   記録と参照形で当たらないこと）。分類器が何にも当たらない状態は常に緑を返すため、
#   赤にならない限り誰も気づけない。
#
# 費用:
#   追跡ファイルを 1 回 grep するだけ。2 段目（版番号の抽出）は 1 段目に当たった
#   十数行しか走らない。実測はスクリプト末尾のコメントに置いた。
#
# 終了コード:
#   0 = GO_VERSION_PASS
#   1 = GO_VERSION_FAIL（写しが正本と食い違う、または検査が成立しなかった）
set -euo pipefail

# [0-9] の範囲指定と、UTF-8 の「正本」をバイト列として素直に扱うためロケールを固定する
# （check-control-chars.sh / check-no-secrets.sh と同じ理由）。
export LC_ALL=C

# 検査はプロジェクトルート基準で行う。scripts/ の 1 階層上がルート。
# 任意の作業ディレクトリから起動しても結果が不変になるよう、起動時 CWD に依存しない。
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$(dirname "$HERE")"

fail() {
  printf '[go-version] %s\n' "$1" >&2
  echo "GO_VERSION_FAIL"
  exit 1
}

DOCKERFILE="docker/isolated-build/Dockerfile"

# 版番号の形。3 成分に限る。`1.6 GB` や `3.5`（節番号）を拾わないための下限であり、
# `1.2.38`（変更履歴の節番号）のような 3 成分は形だけでは除けないが、**印のある行しか
# 見ない**ので実害が出ない（節番号の行が自分の正本を ARG GO_VERSION だと名乗ることは無い）。
#
# **ドットは `\.` ではなく `[.]` と書く。** ブラケットの中のドットは BRE でも ERE でも
# awk でも常にリテラルで、**実装ごとのエスケープ解釈の差が原理的に起きない**（上記「踏んだ
# 事故」。`\.` は gawk が素の `.` へ潰し、任意の 1 文字になった）。このパターンは sed の BRE と
# awk の ERE の両方で使い回すので、**両方で同じ意味になる書き方しか置かない。**
VER_RE='[0-9][0-9]*[.][0-9][0-9]*[.][0-9][0-9]*'

# ── 正本の読み取り ───────────────────────────────────────────────────────────

[[ -f "$DOCKERFILE" ]] \
  || fail "正本のファイルがありません: ${DOCKERFILE}。照合できないため失敗させます。"

canon_lines="$(grep -cE "^[[:space:]]*ARG[[:space:]]+GO_VERSION=" "$DOCKERFILE" || true)"
[[ "$canon_lines" == "1" ]] \
  || fail "${DOCKERFILE} の \`ARG GO_VERSION=<版>\` が 1 行ではありません（${canon_lines} 行）。正本が一意でないため失敗させます。"

CANON="$(sed -n "s/^[[:space:]]*ARG[[:space:]][[:space:]]*GO_VERSION=\\(${VER_RE}\\)[[:space:]]*\$/\\1/p" "$DOCKERFILE")"
[[ -n "$CANON" ]] \
  || fail "${DOCKERFILE} の \`ARG GO_VERSION\` から X.Y.Z 形式の版を読めません。正本が読めないため失敗させます。"

echo "[go-version] 正本: ${DOCKERFILE} の ARG GO_VERSION=${CANON}"

# ── 写しの分類器 ─────────────────────────────────────────────────────────────
#
# 標準入力から grep の `パス:行番号:本文` を読み、1 行ごとに判定を付けて
# `<判定><TAB><元の行>` を出す。判定は次の 3 つ。
#
#   COPY_OK    … 写しであり、正本と一致している
#   COPY_STALE … 写しであり、正本と食い違っている（＝落とす対象）
#   NOT_COPY   … 写しではない（記録・参照形・無印の行）
#
# **判定するのは本文だけである。** パスと行番号は表示のためだけに持ち、走査へ入れない。
# 混ぜると、**行番号や版番号入りのパスが「その行に書かれた版」として拾われる**
# （冒頭「踏んだ事故」。`…:417:3.5 …` が `417:3.5` という版に見えた）。
#
# 自己診断と本走査で同じ経路を通すために関数へ切り出す。**判定の定義はここ 1 か所**で、
# 呼ぶ側は判定名で振り分けるだけにする（分類の条件を 2 か所へ書けば、それ自体が写しになる）。
#
# パターンは `-v` ではなく **ENVIRON 経由**で渡す。`-v` は値をエスケープ解釈するため、
# 正規表現をそこへ通すと実装ごとの差が入り込む（冒頭「踏んだ事故」）。ENVIRON は解釈しない。
classify() {
  GO_VER_RE="$VER_RE" GO_CANON="$1" awk '
    BEGIN {
      ver_re    = ENVIRON["GO_VER_RE"]
      canon     = ENVIRON["GO_CANON"]
      # grep -nH が付ける `パス:行番号:` の形。
      prefix_re = "^[^:]*:[0-9][0-9]*:"
    }
    {
      # 本文だけを取り出す。取り出せない行は黙って通さない（検査が成立していない）。
      if (!match($0, prefix_re)) { print "NO_PREFIX\t" $0; next }
      body = substr($0, RLENGTH + 1)

      # 印: 同じ行に「ARG GO_VERSION」と「正本」があること。
      if (index(body, "ARG GO_VERSION") == 0 || index(body, "正本") == 0) {
        print "NOT_COPY\t" $0; next
      }

      # 本文に現れる版番号をすべて拾い、1 つでも正本と一致すれば合格。
      rest = body; found = 0; ok = 0
      while (match(rest, ver_re)) {
        found = 1
        if (substr(rest, RSTART, RLENGTH) == canon) { ok = 1 }
        rest = substr(rest, RSTART + RLENGTH)
      }

      # 版番号が無い行は「参照へ置き換えた形」（#101 が 4 か所へ施した望ましい書き方）。
      if (!found) { print "NOT_COPY\t"   $0; next }
      if (ok)     { print "COPY_OK\t"    $0; next }
                    print "COPY_STALE\t" $0
    }
  '
}

# ── 自己診断 ─────────────────────────────────────────────────────────────────
#
# 合成した入力を分類器へ通し、**判定が期待どおりであること**を確かめる。分類器が
# 何にも当たらない（常に緑）、または何にでも当たる（常に赤）壊れかたは、走査を回す前に
# ここで落とす。
#
# **入力は grep の出力と同じ `パス:行番号:本文` の形で書く。** 本走査と違う形を通すと、
# 前置きの扱いを間違えたときに自己診断がそれを見逃す（**現に見逃した**。冒頭「踏んだ事故」）。
#
# **版番号は正本から組み立てる。** 自己診断の中へ版を書き写すと、それ自体が古くなる写しになる。
#
# 数字の入れかたが要点である。参照形・節番号・日付・サイズ・版番号入りのパスを混ぜてある。
# **ドットが実装差で緩めば（任意の 1 文字になれば）、これらが版番号に見えて判定が変わる。**
self_stale="$(printf '%s' "$CANON" | awk -F'[.]' '{ print $1 "." $2 "." ($3 + 1) }')"
[[ -n "$self_stale" && "$self_stale" != "$CANON" ]] \
  || fail "自己診断用の版を組み立てられません（正本 ${CANON}）。検査が成立していないため失敗させます。"

self_cases="$(
  printf 'COPY_OK\tdocs/spec.md:1551:**採用バージョン: Go %s**（確定12）。値の正本は `docker/isolated-build/Dockerfile` の `ARG GO_VERSION`。\n' "$CANON"
  printf 'COPY_STALE\tdocs/spec.md:1552:**採用バージョン: Go %s**（確定12）。値の正本は `docker/isolated-build/Dockerfile` の `ARG GO_VERSION`。\n' "$self_stale"
  printf 'NOT_COPY\tdocs/spec.md:2058:実測（2026-08-28 / Go %s / #100）。測った版のまま残す。\n' "$self_stale"
  printf 'NOT_COPY\tdocs/build-function.md:417:3.5 の手順に従います。**版の正本は `docker/isolated-build/Dockerfile` の `ARG GO_VERSION`**\n'
  printf 'NOT_COPY\tdocs/build-function.md:15:| イメージ | 約 1.6 GB。**版の正本は `docker/isolated-build/Dockerfile` の `ARG GO_VERSION`**\n'
  printf 'NOT_COPY\tterraform/build-function.tf:268: * 2026-08-28 の注記。正本は `docker/isolated-build/Dockerfile` の `ARG GO_VERSION`）、\n'
  printf 'NOT_COPY\tdocs/go-%s-notes.md:12:正本は `docker/isolated-build/Dockerfile` の `ARG GO_VERSION`（版はここへ書かない）。\n' "$self_stale"
)"

self_failed=0
while IFS="$(printf '\t')" read -r want line; do
  [[ -n "$want" ]] || continue
  got="$(printf '%s\n' "$line" | classify "$CANON" | cut -f1)"
  if [[ "$got" != "$want" ]]; then
    printf '[go-version] 自己診断: 期待 %s / 実際 %s\n' "$want" "$got" >&2
    printf '[go-version]     %s\n' "$line" >&2
    self_failed=1
  fi
done <<SELF_EOF
$self_cases
SELF_EOF

[[ "$self_failed" -eq 0 ]] \
  || fail "自己診断に失敗しました。分類器が期待どおりに動いていないため、走査へ進まず失敗させます（awk の方言差を疑うこと。冒頭「踏んだ事故」）。"

# ── 実装側 3 点の一致 ────────────────────────────────────────────────────────
#
# ベースイメージのタグと 2 つの go.mod の一致は**イメージのビルドが機械照合する**
# （Dockerfile。版がずれたイメージは存在できない）。ここで同じことを見るのは、
# **その照合が docker のビルドを回さないと出ない**ためである。ループの反復ごとに
# docker build は回らないので、0.0X 秒で同じずれを落とす層をローカルへ置く。
# 担保が二重になるのではなく、**気づく時刻が早くなる。**
for gomod in docker/isolated-build/template/go.mod docker/isolated-build/handler/go.mod; do
  [[ -f "$gomod" ]] || fail "${gomod} がありません。実装側の版を照合できないため失敗させます。"
  got="$(sed -n "s/^go[[:space:]][[:space:]]*\\(${VER_RE}\\)[[:space:]]*\$/\\1/p" "$gomod")"
  [[ -n "$got" ]] \
    || fail "${gomod} の \`go\` ディレクティブから X.Y.Z 形式の版を読めません。照合できないため失敗させます。"
  [[ "$got" == "$CANON" ]] \
    || fail "${gomod} の go ディレクティブが正本と食い違います: ${got}（正本 ${CANON}）。3.5 の更新手順 3。"
done
echo "[go-version] 実装側 3 点一致: Dockerfile / template/go.mod / handler/go.mod = ${CANON}"

# ── 追跡ファイルの走査 ───────────────────────────────────────────────────────

WORK="$(mktemp -d "${TMPDIR:-/tmp}/go-version.XXXXXX")" || { echo "[go-version] 一時ディレクトリを作成できません。" >&2; echo "GO_VERSION_FAIL"; exit 1; }
trap 'rm -rf "$WORK"' EXIT

TRACKED="$WORK/tracked.z"
TARGETS="$WORK/targets.z"
HITS="$WORK/hits.txt"
GREP_ERR="$WORK/grep.err"

git rev-parse --is-inside-work-tree >/dev/null 2>&1 \
  || fail "git の作業ツリーではありません。追跡ファイルを列挙できないため失敗させます。"

# 列挙は NUL 区切り。パス名に改行を含むファイルでも 1 レコードのまま崩れない
# （check-control-chars.sh と同じ扱い）。
git ls-files -z > "$TRACKED" || fail "git ls-files に失敗しました。追跡ファイルを列挙できません。"

tracked_count=0
target_count=0
while IFS= read -r -d '' path; do
  tracked_count=$((tracked_count + 1))
  # シンボリックリンクは開かない（リンク先の実体を読んでしまい判定が別物になる）。
  [[ -L "$path" ]] && continue
  # 実体の無いもの（削除済み・サブモジュール）は走査対象が無い。
  [[ -f "$path" ]] || continue
  target_count=$((target_count + 1))
  printf '%s\0' "$path"
done < "$TRACKED" > "$TARGETS"

[[ "$tracked_count" -gt 0 ]] \
  || fail "追跡ファイルが 1 件もありません。検査していないことと、写しが正しいことは別なので失敗させます。"
[[ "$target_count" -gt 0 ]] \
  || fail "走査できる追跡ファイルが 1 件もありません。検査が成立していないため失敗させます。"

# 1 段目: `ARG GO_VERSION` を含む行だけを 1 回の走査で拾う。**印の片割れである。**
# 残り 2 つ（「正本」と版番号）は、拾った十数行に対してだけ判定する（2 段目）。
#
# -I  … バイナリは走査しない。ここで探すのは ASCII の定型句なので、バイナリに当たる
#        ことは実際上ありえず、当たったとしても行として読めない。
#        （check-control-chars.sh が -a でバイナリ判定を捨てているのと向きが逆なのは、
#        あちらの探し物が「NUL そのもの」だからである。）
# -H  … 1 ファイルだけが渡った回でもパスを出す（xargs の分割回数に結果を依存させない）。
# --  … 以降を操作対象として扱う。先頭が - のパス名をオプションと誤解させない。
grep_status=0
xargs -0 grep -nHI -e 'ARG GO_VERSION' -- < "$TARGETS" > "$HITS" 2> "$GREP_ERR" || grep_status=$?

if [[ -s "$GREP_ERR" ]]; then
  printf '[go-version] 走査中にエラーが出ました。検査が成立していないため失敗させます:\n' >&2
  sed 's/^/[go-version]     /' "$GREP_ERR" >&2
  echo "GO_VERSION_FAIL"
  exit 1
fi
# 0 = 全件で該当あり / 123 = どこかの grep が「該当なし」を返した。どちらも正常。
if [[ "$grep_status" -ne 0 && "$grep_status" -ne 123 ]]; then
  fail "走査が異常終了しました（xargs 終了コード ${grep_status}）。検査が成立していないため失敗させます。"
fi

# 2 段目: 1 段目の当たりを分類器へ通す。**判定の定義は classify の中だけにある。**
# ここで条件をもう一度書くと、それ自体が写しになって片方だけ古くなる。
verdicts="$(classify "$CANON" < "$HITS" || true)"

# 前置き（`パス:行番号:`）を外せなかった行。パス名にコロンが入ると起こりうる。
# **本文だけを判定するという前提が崩れているので、黙って通さない。**
no_prefix="$(printf '%s\n' "$verdicts" | awk -F'\t' '$1 == "NO_PREFIX" { print substr($0, index($0, "\t") + 1) }')"
if [[ -n "$no_prefix" ]]; then
  printf '[go-version] 走査結果から `パス:行番号:` を外せない行があります。本文だけを判定できないため失敗させます:\n' >&2
  printf '%s\n' "$no_prefix" | sed 's/^/[go-version]     /' | cut -c1-200 >&2
  echo "GO_VERSION_FAIL"
  exit 1
fi

# 表示は「最初の TAB 以降すべて」を取る。`$2` だと、元の行が TAB を含むときに
# そこで切れて表示が壊れる（判定には影響しないが、直す場所が読めなくなる）。
stale="$(printf '%s\n' "$verdicts" | awk -F'\t' '$1 == "COPY_STALE" { print substr($0, index($0, "\t") + 1) }')"
copy_count="$(printf '%s\n' "$verdicts" \
  | awk -F'\t' '$1 == "COPY_OK" || $1 == "COPY_STALE" { n++ } END { print n + 0 }')"

# 写しが 1 件も無い状態を合格にしない。写しの置き場は 3.5 の更新手順 6 が
# 「値を書かないわけにいかない」と認めた箇所であり、**0 になるのは、写しが
# 消えたのではなく印が消えた**（＝この検査から見えなくなった）ときである。
# **3 件を期待しない。** 件数を書けばそれ自体が古くなる写しになる（#141 の前提）。
[[ "$copy_count" -gt 0 ]] \
  || fail "正本を名乗る写しが 1 件も見つかりません。写しには同じ行へ「値の正本は \`ARG GO_VERSION\`」と書きます（3.5 の更新手順 6）。検査が成立していないため失敗させます。"

if [[ -n "$stale" ]]; then
  printf '[go-version] 正本と食い違う写しがあります（正本 %s）:\n' "$CANON" >&2
  printf '%s\n' "$stale" | sed 's/^/[go-version]     /' | cut -c1-200 >&2
  printf '[go-version] 揃えかたは docs/product-spec.md 3.5 の更新手順 6 にあります。\n' >&2
  printf '[go-version] **過去の事象を書いた箇所なら揃えてはいけません**（更新手順 7）。\n' >&2
  printf '[go-version] その場合は、版番号と「正本」「ARG GO_VERSION」が同じ行に並ばないよう書き直してください。\n' >&2
  echo "GO_VERSION_FAIL"
  exit 1
fi

printf '[go-version] 写し %s 件が正本と一致（追跡 %s 件を走査）\n' "$copy_count" "$target_count"
echo "GO_VERSION_PASS"

