-- 整理パス（確定18 の条件 2〜4 / 5.3 / M5-2 / #33）を通って作られた作品を記録する。
--
-- 5.3 は 4 条件のあとに「**整理したことは作者に開示する。黙って別物を出すのは
-- 体験として悪い**」と定める（6.2 と同じ原則）。開示するには、その作品のソースが
-- 整理パスの出力であることを残しておかなければならない。
--
-- **後から埋め戻せない列である。** 「このソースは整理を通ったか」は、通した瞬間に
-- しか観測できない。完成後のソースを見ても分からず、`generations` の行にも残らない
-- （台帳が持つのは利用者のプロンプトで、整理の指示は `src/generate.ts` の包み層の
-- 中だけに在る）。**記録しなければ、その事実は永久に失われる。**
--
-- **既存行が NULL であることは正しい。** #202 / #203 は「実装より前に完成した行は、
-- その実装の経路を 1 度も通っていない」ことで元の版を失った。ここでも既存行は
-- 整理パスを 1 度も通っていないが、**この列の NULL はまさに「通っていない」を
-- 意味する**ので、埋め戻す UPDATE は要らない（0012 が `capturing` の行を埋めたのとは
-- 事情が違う。あちらは「新しい列が無い状態で既に進行中だった行」があった）。
-- 適用時に埋めるべき行は 0 行である。
--
-- 値は要求した時刻（UNIX 秒）。**真偽値にしない**——10.2 が整理パスの発生率を数える
-- ときに、いつ起きたかが要る。
alter table games add column tidy_requested_at integer;
