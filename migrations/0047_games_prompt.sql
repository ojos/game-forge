-- ## なぜ列が要るのか
--
-- #694 は、作者本人が自作の作品の「自分が書いた指示」を機械が読める口で読めるようにする
-- （内蔵チャット #695 と MCP #696 の土台）。**ところが最初の指示はどこにも作品と結び付いて
