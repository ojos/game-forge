-- 費用台帳の月次集計用インデックス（4.3 層 1 / #22）。
--
-- **列は足さない。** `generations` は 0001 で 5.1 のとおり作られており、`model` も
-- `usage` 4 種も `cost_jpy` も `succeeded` も揃っている。本 migration が足すのは
-- インデックス 1 本だけである。
--
-- 0001 は「インデックスは、必要とする問い合わせが決まっているものだけを張る。
-- 追加は、それを要する問い合わせが来た時点で行う」と定めている。**その問い合わせが
-- 来た。** 4.3 の月次上限は「推定値ではなく実測累計で判定する」ため、
-- `src/cost-ledger.ts` の `monthlyCostTotals` が
--
--   select sum(cost_jpy), count(*) from generations
--    where created_at >= ? and created_at < ?
--
-- を引く。これは 3.3-2（#23 / M3-2）の判定に入るため、**生成のたびに 1 回走る。**
--
-- **D1 は読み取りも従量である**（3.6）。インデックスが無いとこの問い合わせは全表走査に
-- なり、読み取り行数が「当月の行数」ではなく「開設以来の行数」に比例して増え続ける。
-- 4.3 の想定（Sonnet 4.6 で月およそ 840 本）では、1 年後には 1 回の判定が当月分の
-- 十数倍の行を読むことになる。走査量が月次で頭打ちになるのはインデックスがある場合だけである。
--
-- **`(created_at)` の単列にする。** `(created_at, cost_jpy)` にすれば集計を
-- index-only にできるが、集計する列が 1 つ増えた日に**黙って**カバーでなくなる。
-- 効きが読めない最適化より、範囲で絞れることを確実にするほうを採る。
--
-- **利用者別の索引は張らない。** 日次クォータ（確定25 / 1 人 1 日 12 回）の判定は
-- #23 の範囲で、そちらが `(user_id, created_at)` を要する。**要る側が張る**のが
-- 0001 の方針であり、使われない索引を先に置くと書き込みコストだけが確実に増える。
CREATE INDEX generations_created_at_idx ON generations(created_at);
