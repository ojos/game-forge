-- 作品の論理解像度（仕様 3.9.4 の「作品のおすすめの向きで開き、あとで入れ替えられる」/ #514 / M14-6）。
--
-- **全画面の覆いを、作品のおすすめの向き（横長なら横向き、縦長なら縦向き）で開くための土台である。** 向きは
-- `Layout` が返す論理解像度の幅と高さで決まる。Ebitengine はこの値を DOM に出さず、canvas の大きさは画面の大きさなので、
-- **ページはソースを見ないと作品の向きを知れない。** そのため、ソースから拾って保存する。
--
-- ## 0040 の表に列を足す（別の表にしない）
--
-- **0042（`held_codes`）・0043（`alias_groups`）と同じ理由である**——引き方（ソースの R2 キーの等値）も、書く時点（完成の直後）も、
-- 埋め戻しも同じで、`rule_version` 1 つで鮮度を表せる。表の名前は「作品が読むキー」だが、ソースから静的に拾う事実を
-- 1 行に集める置き場所として使う。
--
-- ## 値と NULL の意味
--
-- - **`layout_width` / `layout_height` は、`Layout` の return から宣言の単位で解いた整数**（例: 320 と 240）。
-- - **NULL は「解像度が分からない」行である。** 2 通りある:
--   - 規則の版 4 以上の行で NULL: 拾えなかった（式・関数呼び出し・複数回の宣言など。仕様 3.9.4）
--   - 規則の版 3 以下の行: まだ拾っていない。**0044 を当てる前の行だけでなく、当てた後に #514 の実装が入るまでの書き込み
--     （今の UPSERT はこの列を指定しない）で作った行も含む**
-- - **どちらの NULL でも、ページは向きの操作をしない**（固定も、ボタンも、案内も出さない）。埋め戻しは `rule_version` が古い行を
--   拾い直すので、後者の NULL は埋まる。
-- - 2 つの列は、両方に値があるか、両方 NULL のどちらかにする（片方だけの値は書かない。実装が守る）。
--
-- **このマイグレーションだけを先にマージする**（#514 の実装より前。#536 / #545 と同じ形）。今の作品ページはこの列を読まないので、
-- 列が増えても振る舞いは変わらない。この列を読む実装を、本番に列が無いまま出すと作品ページの問い合わせが失敗する。

-- 論理解像度の幅と高さ。NULL は解像度が分からない（拾えなかった / まだ拾っていない）。
ALTER TABLE source_input_keys ADD COLUMN layout_width INTEGER;
ALTER TABLE source_input_keys ADD COLUMN layout_height INTEGER;
