-- 作品のソースが読むキーの集合（仕様 3.9.5 / #493 / M14-4）。
--
-- **仮想パッド（3.9.6 / M14-5）に出すボタンを、作品ごとに決めるための土台である。** 保存するのは
-- 「ソースが読むキーの全集合」で、**どれをボタンにするかは保存しない**（ページ側の規則。3.9.6）。
-- 表示の規則を後で変えても、埋め戻しが要らないようにするためである。
--
-- ## ソースの R2 キーで引く（`games` の列にしない）
--
-- 1. **R2 のソースは内容のハッシュで名付けられ、作品をまたいで共有される**（確定26）。同じソースなら
--    読むキーも同じである。
-- 2. **推敲（5.7）と「版に戻す」は `games.source_key` を差し替える。** ソースに紐づけておけば、戻したときに
--    何も書かなくてよい。`games` の列にすると、差し替える 3 か所すべてで書き直しが要り、1 か所の書き忘れで
--    古いキーのパッドが出る。
-- 3. **行が無いことと、キーを読まないことを区別できる。** 行が無い＝まだ拾っていない。`[]`＝拾ったが
--    キーを読まない。
--
-- **`build_cache`（0002）の列にしない。** あちらは 3.8 の索引で、成果物の掃除（3.7）で消えうる。
-- キャッシュのヒットの有無とも関係が無い。
--
-- ## 外部キーを張らない
--
-- **`build_cache` と同じ理由である**——`games` とも `game_revisions` とも 1 対 1 でない（同じソースを
-- 複数の作品と版が指し、tombstone で `games.source_key` が NULL になっても版の表からは指され続ける）。
-- 外部キーを張ると、1 対 1 でない関係を 1 対 1 に見せることになる。
--
-- ## 消さない
--
-- **3.7 の掃除でこの表の行を消さない。** 1 行は数十バイトで、引くのは生きている `source_key` からだけ
-- なので、参照されない行は害にならない。
--
-- ## 書く場所（`src/source-input-keys.ts`）
--
-- - **完成を確定させた直後に、エッジが R2 のソースを読んで拾う**（完成のコールバックと同期実行の 2 か所）。
--   **行が既にあり `rule_version` が今の版なら R2 を読まない。**
-- - **書き込みは `insert ... on conflict(source_key) do update ... where excluded.rule_version >
--   source_input_keys.rule_version` の 1 文である。** 新しい版だけが上書きし、並行した 2 回の完成でも壊れない。
-- - **既存の作品は `scripts/input-keys-backfill.mjs` が埋め戻す**（欠けの点検を兼ねる。`docs/usage-report.md`）。
--
-- D1 の書き込みは新しいソース 1 つにつき 1 行で、`build_cache` と同じ桁である（3.6）。
-- 時刻は 0001 と同じく **UNIX 秒の INTEGER** で持つ。

CREATE TABLE source_input_keys (
  -- R2 のキー。`games.source_key` / `game_revisions.source_key` と同じ綴り。
  source_key TEXT PRIMARY KEY,
  -- `KeyboardEvent.code` の JSON 配列（重複なし・昇順）。`[]` は「拾ったが、キーを読まない」。
  codes TEXT NOT NULL,
  -- 抽出の規則の版（`src/input-keys.ts` の `INPUT_KEYS_RULE_VERSION`）。
  rule_version INTEGER NOT NULL,
  -- 拾った時刻（UNIX 秒）。
  extracted_at INTEGER NOT NULL
);

-- **索引を足さない。** 引き方は `source_key` の等値 1 通りで、それは主キーが担う（0002 と同じ方針）。
