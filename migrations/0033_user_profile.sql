-- 作者のプロフィール（自己紹介と外部リンク）と、その変更の履歴（5.1 / 5.6 / 5.10 / #379 / M12-11）。
--
-- ## 列を 3 つ足す
--
--   - `bio` … 自己紹介（自由文。**改行を持つ**）。空文字が「書いていない」
--   - `profile_links` … 外部リンク（**最大 3 本**）を JSON の文字列の配列で持つ。`'[]'` が「無い」
--   - `profile_set_at` … 自己紹介かリンクを最後に変えた時刻（UNIX 秒）。NULL は「1 度も変えていない」
--
-- ### 空を NULL にしない（`NOT NULL DEFAULT`）
--
-- **「書いていない」を 1 つの綴りにする。** NULL と空文字の 2 つを許すと、変更の判定
-- （`bio <> ?`）が NULL で真にならず、**空の自己紹介を書いた要求が 0 行の更新で終わる**
-- （NULL との比較は常に NULL）。既存の利用者は DEFAULT で空から始まり、**変えない限り
-- 作者ページの見た目は今までと同じである。**
--
-- ### リンクを別の表にしない（1 列の JSON にする）
--
-- **読むのは作者ページの主キー 1 行と `/account` の本人の 1 行だけで、リンクで引く問い合わせが
-- 無い。** 別の表にすると、作者ページの表示で読み取りが 1 回増え、変更は「消して入れ直す」
-- 複数の文になる（履歴との 1 つの batch が長くなる）。本数は 3 本で固定の上限なので、
-- 1 列に収まる。**中身の形（`https:` の URL の配列）はアプリが保存の前に検査し、表示の直前にも
-- 同じ関数でもう一度検査する**（`src/profile.ts`）。**CHECK で `json_valid` を張らない**——
-- 張っても守れるのは JSON であることだけで、`javascript:` は JSON として正しい。守る場所を
-- 表示の直前に 1 つ置く（D1 を直接 UPDATE した値でも同じ関数を通る）。
--
-- ### 間隔の判定に使う時刻を 1 列にする
--
-- **自己紹介とリンクは 1 つのフォームで送る**（`/account`）。60 秒の間隔を `users` の行の
-- 時刻で WHERE に置く（`display_name_set_at` / `description_set_at` と同じ形）。履歴の表から
-- 引くと、同じ batch で先に積んだ履歴の行に UPDATE の側が当たって必ず 0 行になる（0028 と
-- 同じ理由）。
--
-- ## `x_handle` には触らない
--
-- 5.6 の v1.57 注記は「`x_handle` そのものの扱いは M12-11 が決める」と書いた。**決定は
-- 「触らない」である**（列を消さず、外部リンクへ移しもしない）。書く経路も読む画面も 1 つも
-- 無く、値は未検証の自称値として 0001 から残っているだけである。**消すと戻せず**、移すと
-- 本人が申告していない URL を作者ページのリンクにすることになる（5.6 が避けている形）。
--
-- ## 変更の履歴を追記だけで持つ（`profile_changes`。#405 の申し送り）
--
-- **通報は作品の単位で、作者ページは通報の対象ではない**（8.4）。**それでも持つ。** 5.6 が
-- 外部リンクで受けた懸念は「なりすまし」で、その証拠の置き場所がリンクそのものである
-- ——他人の SNS を自分の作者ページに貼った作者が、通報されたあとでリンクを消すと、
-- 運営に見えるのは消したあとの作者ページだけになる（#405 が表示名について書いたのと同じ形）。
--
-- - **形は `display_name_changes`（0030）と同じ**（`old_*` / `new_*` / `changed_at`）。1 回の変更で
--   自己紹介とリンクの両方を 1 行に持つ（1 つのフォームで送る値だから）
-- - **更新と 1 つの `D1.batch` で書き、履歴を先に置く**（旧い値は UPDATE の前の行からしか取れない）。
--   **履歴の WHERE は UPDATE の WHERE と同じ綴り**にしてあり、**間隔で断った変更・何も変わらない
--   入れ直しでは履歴も 0 行になる。** 履歴の insert が落ちれば batch ごと巻き戻り、
--   プロフィールも変わらない
-- - **更新も削除もしない**（アプリにこの表を UPDATE / DELETE する経路を作らない）
--
-- ### 「書き始めた時刻」の表は持たない（0030 と違う）
--
-- **この migration が、値の列と履歴の表を同時に作る。** 列ができる前にプロフィールは存在せず、
-- 列を書く経路はアプリの 1 か所だけで、そこは必ず履歴を同じ batch で積む。**したがって、ある
-- 利用者に履歴が 1 行も無いことは「1 度も変えていない（空のまま）」を意味し、いまの値は常に
-- 履歴から復元できる。** 0030 は表示名が 0030 より前から変わりえたので基準の時刻が要ったが、
-- ここにはその「記録されていない過去」が無い。**適用からアプリの配備までの間も、古いコードは
-- この列を書かない**ので、記録されない変更は起きない。
--
-- ### 運営が D1 を直接 UPDATE してプロフィールを直すとき
--
-- **その UPDATE は履歴を書かない。** 直すときは、`display_name_changes` と同じく**値を先に直し、
-- 直った行についてだけ履歴を 1 行積む**こと（端末からの複数の文が 1 つのトランザクションに
-- なることを前提にしない）。保証できるのはアプリの経路までである（0026 / 0030 と同じ但し書き）。
--
-- ## 利用者と同じ寿命
--
-- **`users` の行を消すときは、この表の行を先に消す**（外部キー）。いまのアプリで `users` を
-- 消すのは、招待を消費できなかった直後の作りかけの行だけで（`src/auth/google.ts`）、その行は
-- まだプロフィールの変更を通っていない。**`on delete cascade` は書かない**（0027 / 0030 と同じ）。
--
-- ## `id` を主キーにする・索引を張る
--
-- 0030 と同じ理由である（同じ秒の 2 度目が一意制約で落ちると batch ごと巻き戻る／「その利用者の、
-- ある時刻の前後で最も近い変更」を範囲の端で引けるようにする）。**書き込みの増分は、変更 1 回に
-- つき `users` の 1 行と、履歴と索引の 2 行**（3.6。60 秒に 1 回なので 1 人が 1 日張り付いても
-- 4,320 行・無料枠の 4.3%）。
--
-- ## CHECK は時刻の 1 つだけ
--
-- **`changed_at` は 0 より大きい**（0027 / 0030 と同じ理由）。長さの CHECK は張らない——上限は
-- アプリの検査（`src/profile.ts`）が持ち、**運営が直した値の形の都合で履歴の insert を落とさない。**
--
-- ## 連番について
--
-- 並行するレーン（#376）が `0032` を使う。**マージの順によって番号を振り直すことがある**ので、
-- コードとテストと文書にはこの番号を書かない（ファイル名だけが番号を持つ）。

ALTER TABLE users ADD COLUMN bio TEXT NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN profile_links TEXT NOT NULL DEFAULT '[]';
ALTER TABLE users ADD COLUMN profile_set_at INTEGER;

CREATE TABLE profile_changes (
  id TEXT PRIMARY KEY,
  -- 変えた利用者。**実在する利用者しか入らない**（書く経路は `users` を引いて書く）。
  user_id TEXT NOT NULL REFERENCES users(id),
  -- 変える前と後の自己紹介（空文字は「書いていない」）。
  old_bio TEXT NOT NULL,
  new_bio TEXT NOT NULL,
  -- 変える前と後の外部リンク（`users.profile_links` と同じ JSON の配列）。
  old_links TEXT NOT NULL,
  new_links TEXT NOT NULL,
  -- 変えた時刻（UNIX 秒。0001 の方針）。**0 以下は入らない**（上記）。
  changed_at INTEGER NOT NULL CHECK (changed_at > 0)
);

-- 「その利用者の、ある時刻の前後で最も近い変更」を引くための索引（0027 / 0028 / 0030 と同じ並び）。
CREATE INDEX profile_changes_user_changed_idx ON profile_changes (user_id, changed_at);
