#!/usr/bin/env bash
# lib/tf-dir.sh — 宣言（terraform/）を読む場所を確定させる、唯一の場所（#318）
#
# 読み込むと `TF_DIR` が使える。差し替えは環境変数 `ACCEPTANCE_TF_DIR` で行う
# （#297 / PR #313）。**既定値 `terraform` の綴りは、このファイルにしか無い。**
#
# ══════════════════════════════════════════════════════════════════════════════
# なぜ 1 ファイルへ寄せるのか
# ══════════════════════════════════════════════════════════════════════════════
#
# **読む側が 2 本になったからである。** #313 の時点では `acceptance-remote.sh` だけが
# 差し替えを見ており、既定値は同ファイルの冒頭 1 か所で確定していた。#318 で
# `check-r2-lifecycle.sh` も差し替えを見ることになったので、**そこへ既定値を書き写すと
# 綴りが 2 か所に散る。** 散った既定値は、片方だけを直した日に「既定で読む場所が入口ごとに
# 違う」状態を作る——これは #313 の第二意見レビューが、同一ファイル内の参照側について
# 指摘したのとまったく同じ形である（`${TF_DIR:-terraform}` と書き分けない）。
#
# **写しは必ず腐る**（`.ai-playbook/shared-ai-rules.md` 12 章）。置く前に寄せる。
# `scripts/lib/dev-fixture.sh` と同じ理由で、同じ場所へ置く。
#
# ══════════════════════════════════════════════════════════════════════════════
# 2 つの入口で、既定値が 1 か所に留まる形
# ══════════════════════════════════════════════════════════════════════════════
#
#   bash scripts/acceptance-remote.sh          外部層の全体。冒頭でここを読む。
#   bash scripts/check-r2-lifecycle.sh         単独でも回す。冒頭でここを読む。
#
# `acceptance-remote.sh` は `check-r2-lifecycle.sh` を**子プロセスとして**呼ぶ。
# **値を渡し直す配線は要らない。** `ACCEPTANCE_TF_DIR` は起動時の環境変数として親へ
# 渡されており、環境はそのまま子へ継がれるためである。子は親と同じこのファイルを読み、
# 同じ既定値へ落ちる。**渡し直す行を足すと、そこがもう一つの「既定値の書き分け」に
# なりうる**（親が別の経路で TF_DIR を決めた日に、渡す値と子の既定値が食い違う）ので
# 足さない。
#
# **相対パスの既定値なので、読む側はリポジトリルートへ cd してから読み込むこと。**
# どちらの入口も冒頭でルートへ移っており、`terraform` はそのルート基準で解決される。
#
# ══════════════════════════════════════════════════════════════════════════════
# 差し替えの名前を `TF_DIR` そのものにしない
# ══════════════════════════════════════════════════════════════════════════════
#
# 他の用途で `TF_DIR` が輸出されていたときに、`terraform plan: no drift` を含むゲート
# 全体が黙って別の宣言を見ることになる（PR #313）。**外から効かせる名前は
# `ACCEPTANCE_TF_DIR` だけ**にして、`TF_DIR` は読み込んだ側の内部名に留める。
#
# ══════════════════════════════════════════════════════════════════════════════
# ここへ寄せないもの
# ══════════════════════════════════════════════════════════════════════════════
#
# **`scripts/check-tf-output-refs.sh` は `ACCEPTANCE_TF_DIR` を見ない（見てはいけない）。**
# あちらは「このリポジトリが追跡している宣言」と、検査スクリプトが書いた output 名との
# 突き合わせで、ローカル層の検査である。差し替えた写しを見せると、**写しの側に合わせて
# 緑になる**——見るべき対象そのものが違う。用途が違うものを名前の一致だけで寄せない。
#
# 使い方（`HERE` は scripts/ の絶対パス。リポジトリルートへ cd した後に読むこと）:
#   # shellcheck source=scripts/lib/tf-dir.sh
#   . "$HERE/lib/tf-dir.sh"

# 読み込んだ側で上書きされないようにする（`check-r2-lifecycle.sh` が #318 以前から
# 持っていた保護をそのまま引き継ぐ）。読み込みは各入口で 1 回だけである。
# shellcheck disable=SC2034  # 読み込んだ側が使う
readonly TF_DIR="${ACCEPTANCE_TF_DIR:-terraform}"
