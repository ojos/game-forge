-- 運営の管理画面へ入れる利用者を表す列を `users` へ足す（#356 / 仕様 2.4.2）。
--
-- **`admin.game-forge.ojos.jp` に入れるのはこの列が 1 の利用者だけである。** 権限が無い
-- 要求には 404 を返す（403 は画面の存在を教える。2.4.2）。
--
--
-- ## なぜ `is_operator` に流用しないのか（#334 の決定を保つ）
--
-- **`is_operator`（0021）は表示だけの列であり、権限を与えない。** 仕様 2.4.2 はこれを
-- 覆さないと明記している。理由は 1 つである——**一体にすると、後から分けられない。**
--
-- 「作品ページにバッジを出したい人」と「他人のアカウントを止められる人」は別の集合で
-- ある。先に分けておけば、**運営名義で作品を出す人を増やしても権限は増えない。**
-- 逆に 1 列で兼ねると、バッジを付けるという表示上の判断が、そのまま BAN の権限を配る
-- 操作になる。**分け直すには、どの行がどちらの意図で立てられたのかを事後に判別する
-- 必要があり、それは記録に残っていない。**
--
--
-- ## なぜ導出しないのか
--
-- 0021 と同じ検討の結論であり、答えも同じである。**他のどの列からも導けない。**
-- `display_name` はログインのたびに Google の値で上書きされ（`src/auth/google.ts` の
-- `refreshExistingUser`）、5.9 以降は利用者自身も変えられる。`email` は同一性の判定に
-- 使わない値で（0001 の `google_sub` の注記）、しかもアドレスをコードへ書くと変えた日に
-- 黙って外れる。`id` / `google_sub` を設定へ書き写すと、写しは必ず腐る
-- （`.ai-playbook/shared-ai-rules.md` 12 章）。
--
-- **`is_operator` から導くこともしない**（上記のとおり別の集合である）。
--
--
-- ## NOT NULL + DEFAULT 0 にできる理由
--
-- 0021 と同じ判断である。**既存の行はすべて管理者ではない**——管理者は、この列が入った
-- あとで人が 1 行だけ立てる（下記）。したがって 0 での埋め戻しは既定値の都合ではなく
-- **事実として正しく**、既存の利用者の振る舞いはこの列が入っても 1 ビットも変わらない。
--
-- **既定が 0 であることが、ログインで作られる行の安全性そのものである。**
-- `src/auth/google.ts` の `createUser` は列を名指しして INSERT し、この列を書かない。
-- 既定が 1 だったり NULL 許容だったりすると、**新しく登録した人が管理画面へ入れる。**
-- `test/schema-admin.test.ts` がこの既定を機械照合する。
--
--
-- ## CHECK を張る
--
-- **この列を書くのは人の手である**（下記。画面から管理者を増やす経路は作らない）。
-- `set is_admin = 'yes'` や `= 2` のような綴り違いを、書いた瞬間に弾く。0021 と同じ形で、
-- 真偽の 2 値なので取りうる値は増えない。
--
-- 権限の判定は `= 1` を「管理者である」と読む（`src/admin/guard.ts`）。CHECK があるので、
-- 0 と 1 以外の値を「立っている」か「いない」かのどちらへ倒すかを決めずに済む
-- ——**認可の判定でそれを決め損なうと、想定外の値が権限を通す側へ倒れうる。**
--
--
-- ## 立て方は直接 UPDATE である（画面から増やす経路は作らない。2.4.2）
--
-- **BAN（`users.banned_at`）と運営フラグ（`is_operator`）と同じ運用**で、前例が 2 つある。
-- 手順は `docs/admin-host.md` にある。
--
--   UPDATE users SET is_admin = 1 WHERE google_sub = '<運営の google_sub>';
--
-- **増やせる画面は、乗っ取られたときに権限を配る道具になる**（2.4.2）。最初の 1 人を
-- 立てる経路が人の手であることは、この列の運用上の弱点ではなく、**画面を持たないことの
-- 代償として引き受けたもの**である。
--
-- **機械照合は置けない。** これは D1 の行データなので、本番でフラグが失われても
-- （行の作り直し・誤った UPDATE・復元）**検査はすべて緑のまま通る。** テストが確かめて
-- いるのは列の形と認可の分岐であって、本番の行に 1 が立っていることではない
-- （0021 と同じ限界。`docs/admin-host.md` の「限界」）。
--
--
-- ## 索引を張らない
--
-- **この列で絞り込む経路が無い。** 読むのは管理画面の入口が利用者を主キーで引くときだけ
-- で（`src/admin/guard.ts`）、`users` の主キーで 1 行取ったあとにこの列を見る。
-- 「管理者の一覧を出す」画面は無い（2.4.3 が「管理者を増やすこと」を置かないと決めた）。
-- **「将来使うかもしれない」で足さない**（0001 の方針）。
--
-- 0020 / 0023 が部分索引を張ったのは、**その列で絞り込む問い合わせが実在した**ためである
-- （BAN の同期・公式サンプルの抽出）。ここには無い。
--
--
-- ## 連番が 0025 である理由
--
-- 取り込む側が着手前に割り当てた番号である（`docs/handoff.md` 3 章。`0024` は #330 で
-- 2026-09-12 に本番へ適用済み）。`migrations/` を数えて max+1 を取っていない
-- （0009 の衝突はそれで起きた）。
--
-- **`admin_actions`（2.4.4 の操作履歴）はここへ足さない。** M10-3 が `0026` で足す
-- ——**適用済みの番号へ後から足せない**ため、1 つの issue が使う番号は 1 つに保つ。
ALTER TABLE users ADD COLUMN is_admin INTEGER NOT NULL DEFAULT 0
  CHECK (is_admin IN (0, 1));
