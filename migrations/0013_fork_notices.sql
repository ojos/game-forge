-- 改造通知メールを「1 フォークにつき 1 通」に絞るための記録（5.5 / 2.2-6 / #36）。
--
-- ## なぜ表が要るのか
--
-- 5.5 は「自分の作品が改造されたら作者にメールを 1 通送る」と定めている。契機は
-- **フォークの公開**（`src/publish.ts`）で、公開そのものは条件付き UPDATE が冪等に
-- してある（`publishGame` の `status = 'draft'`。0 行更新なら 2 通目は起きない）。
--
-- **それでも記録を持つのは、「送ったかどうか」を publish の成否から独立させるため
-- である。** 公開の成否は `games.status` が持ち、通知の成否はここが持つ。混ぜると、
-- 通知の経路を 1 本足した日（撮り直し・再公開・運用の手作業）に、抑止が黙って消える。
--
-- ## 送る前に握る（cost-alert と同じ形）
--
-- `INSERT`（主キー衝突で 0 行）で握ってから送る。**「引いて、無ければ送る」に
-- しない**——同じフォークに対する 2 つの要求がほぼ同時に来ると、両方が「無い」を
-- 読んで 2 通出る（`src/mail/cost-alert.ts` の R2 の条件付き書き込みと同じ判断で、
-- ここでは主キーがその役をする）。
--
-- ## 既存のフォークへ通知を撒かない
--
-- **新しい表を足したら、既存の行がその経路を 1 度も通っていないことを疑う**
-- （`docs/handoff.md` 1 章。#202 / #203 で本番の作品を 2 件壊した形である）。
--
-- この表を書くのは公開の経路だけなので、**適用の時点で既に公開されているフォークは
-- 永遠に行を持たない。** ここで「行が無い＝まだ送っていない」と読む設計を選ぶと、
-- **過去のフォーク全部へ通知を撒く**ことになる。本番には 3 世代の系統が 1 本あり
-- （`docs/handoff.md` 1 章）、**公開済みのフォークが 2 件**ある。
--
-- 2 つの手当てを両方入れる。
--
--   1. **経路が「行の有無」を掃かない。** 送るのは「いま公開が成立した」ときだけで、
--      未送信のフォークを探して回る経路を作らない（`src/mail/fork-notice.ts`）。
--      `publishGame` は `status = 'draft'` を条件に持つので、**既に公開済みの行は
--      二度とこの経路へ入らない。**
--   2. **それでも、適用の時点で公開済みのフォークをこの表へ埋める**（下の INSERT）。
--      1 だけに頼ると、あとから「未送信を拾う」運用スクリプトを書いた人が、
--      **空の表を「1 通も送っていない」と読める。** 0012 が `capturing` の行を
--      `published_at` で埋めたのと同じ考え方で、**その時点で真である値**を入れる
--      ——「この行は通知の判断を済ませてある（送らない）」が真である。
--
-- `removed`（8.4 の審査で落ちた作品）も埋める。**一度は公開された行**なので、
-- 状態が戻ることがあっても通知の対象にはならない。
--
-- ## 索引を張らない
--
-- 0010 の `build_health` と同じ判断である。引き方は主キー 1 本（`game_id`）だけで、
-- SQLite が主キーのために作る索引で足りる。**索引は 1 行の insert につき 1 行の
-- 書き込みを足す**（3.6。D1 は書き込みも従量である）。

CREATE TABLE fork_notices (
  -- **フォーク（子作品）の id が主キーである。** 数えるのは「改造 1 件につき 1 通」
  -- であって、親ごとでも作者ごとでもない。親を主キーにすると 2 人目の改造者の
  -- 通知が消え、作者を主キーにすると 2 作目の改造の通知が消える。
  game_id TEXT PRIMARY KEY REFERENCES games(id),
  -- 送信の可否を判断して行を握った時刻（UNIX 秒。0001 の規約）。
  claimed_at INTEGER NOT NULL,
  -- 結末。**`claimed` のまま残った行は、握ったあと送信の前後で落ちたものである。**
  -- 送り直しはしない（公開は 1 作品につき 1 回で、再試行の契機が無い）ので、
  -- これは運用があとから読むための記録であって、判定には使わない。
  outcome TEXT NOT NULL CHECK (outcome IN ('claimed', 'sent', 'send-failed', 'backfilled'))
);

-- 適用の時点で既に公開されているフォークを「判断済み」として埋める（上記 2）。
--
-- **`published_at` が NULL の行は `created_at` で埋める。** 0001 以前の行にしか
-- 起こらないが、**存在しないことに賭けて NULL を残さない**（0012 と同じ判断）。
-- ここは NOT NULL の列なので、NULL を残すと適用そのものが落ちる。
INSERT INTO fork_notices (game_id, claimed_at, outcome)
SELECT id, coalesce(published_at, created_at), 'backfilled'
  FROM games
 WHERE parent_id IS NOT NULL AND status IN ('published', 'removed');
