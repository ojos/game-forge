-- OGP の撮影を始めた時刻を `games` へ足す（5.4 / 11.2 / #235）。
--
-- ## なぜ列が要るのか
--
-- 0009 は `ogp_state`（`capturing` / `ready` / `failed`）を足したが、**`capturing` へ
-- 入った時刻を持っていない。** そのため「撮影が中断したまま残っている」ことを
-- **機械で言えない**——`capturing` の行を見ても、いま走っているのか、関数ごと落ちて
-- 二度と進まないのかが区別できない（`docs/ogp-capture.md` 7 章 / #235）。
--
-- 撮影関数は失敗しても必ずコールバックを送る（`docker/ogp-shot/index.mjs`）ので、
-- **残るのは「送る余地が無かった」場合だけ**である。
--
--   - Lambda のタイムアウト（60 秒）で切られた
--   - メモリ不足などでプロセスごと死んだ
--   - コールバックの送信中に切られた
--
-- **この 3 つでは D1 に痕跡が残らない。** 経過時間だけが手掛かりになる。
--
--
-- ## `published_at` で代用しない
--
-- 初回の撮影は公開の直後に始まるので、`published_at` は claim の時刻とほぼ同じである
-- ——**1 回目までは代用できる。** 代用できないのは 2 回目からで、撮り直しても
-- `published_at` は動かないから、**撮り直した直後の行がまた「期限切れ」に見える。**
-- 撮り直しの経路（#235）はそのまま無限に撮り直す口になる（1 枚 約 0.1 円）。
--
-- **「いつ公開したか」と「いつ撮り始めたか」は別の事実である。** 前者を後者として
-- 読むと、後者が動いたときに追随できない。
--
--
-- ## 既に `capturing` の行を、この場で埋める
--
-- **新しい列を足したら、既存の行がその経路を 1 度も通っていないことを疑う**
-- （`docs/handoff.md` 1 章。#202 / #203 で本番の作品を 2 件壊した形である）。
-- この列を書くのは `claimOgpCapture`（`src/ogp.ts`）だけなので、**マイグレーションの
-- 時点で `capturing` だった行は、永遠に NULL のまま残る。**
--
-- NULL の行は `ogp_started_at <= ?` に当たらない。つまり **検出の対象から静かに
-- 漏れる**——回収の経路を作ったのに、いちばん回収したい行が見えない。
--
-- `published_at` で埋める（0007 が `generation_state` を `DEFAULT 'ready'` で
-- 埋めたのと同じ考え方で、**その時点で真である値**を入れる）。`published_at` が
-- NULL の行は 0 へ倒す——`capturing` は `status='published'` を条件に claim されるので
-- （`src/ogp.ts`）そういう行は本来存在しないが、**存在しないことに賭けて NULL を
-- 残さない。** 0 は「無限に古い」＝ただちに期限切れであり、**見落とすより安全な側**
-- である（撮り直しは 1 枚 約 0.1 円、生成の 3 桁下）。
--
-- **適用時点の本番には `capturing` の行が 1 件も無い**（公開 5 枚はすべて `ready`。
-- `docs/ogp-capture.md` 9 章）。この UPDATE は 0 行を更新して終わる見込みだが、
-- **0 行だから書かなくてよい理由にはならない**——このマイグレーションが流れるのは
-- 本番だけではない。
--
--
-- ## 索引を張らない
--
-- 0009 と同じ判断である。`capturing` の行は、いま本番に 0 件・多くても数件で、
-- 検出は運用のスクリプト（`scripts/ogp-stale-report.sh`）が**人が叩いたときだけ**
-- 引く。**張れば公開のたびに索引が 1 行増えるだけになる。**
ALTER TABLE games ADD COLUMN ogp_started_at INTEGER;

UPDATE games
   SET ogp_started_at = coalesce(published_at, 0)
 WHERE ogp_state = 'capturing' AND ogp_started_at IS NULL;
