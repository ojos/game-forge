-- 利用者が「運営」であることを表す列を `users` へ足す（#334）。
--
-- コールドスタート用サンプル（#43）の所有者を、利用者の作品と画面上で区別できるように
-- する。**所有そのものは実装を要さない**——専用の Google アカウントで登録すれば、
-- `games.author_id` はそのまま運営を指す。この列が足すのは「それが運営であると読める」
-- ことだけである。**表示だけの列であり、権限・日次枠・審査の免除には使わない。**
--
--
-- ## なぜ列で持つのか（名前で判定しない）
--
-- **表示名で判定する実装は、次のログインで壊れる。** `display_name` は Google の表示名で
-- ログインのたびに上書きされる（`src/auth/google.ts` の
-- `update users set email = ?, display_name = ?`）。「運営」という文字列を見る実装も、
-- D1 を直接書き換えて名前を変える運用も、この上書きに耐えない。
--
-- **表示名を利用者が変えられるようになると、誰でも「運営」と名乗れる**（仕様 5.9 /
-- #341）。そうなると名前はなおさら判定の材料にならない。**運営であることはこの列で
-- 見分ける。**
--
--
-- ## なぜ導出しないのか
--
-- BAN は「招待枠の停止」に列を足さず、**招待した相手が BAN されているかどうかから
-- 導いた**（`docs/usage-report.md`「BAN と招待枠」。別の列で持つと、BAN を取り消した
-- ときに戻し忘れる余地ができる）。**ここはその逆の判断である。**
--
-- 運営であることは**他のどの列からも導けない。**
--
--   - `display_name` … 上のとおり、利用者（と Google）が変える値である
--   - `email` … 同一性の判定に使わない値である（0001 の `google_sub` の注記）。
--     しかも運営のアドレスをコードへ書くと、アドレスを変えた日に黙って外れる
--   - `invited_by` … 運営も招待コードで登録する（クローズドβ）。招待の連鎖は
--     運営かどうかを表さない
--   - `id` / `google_sub` … 値をコードや設定へ書き写すことになる。本番の行の値を
--     写すと、写しは必ず腐る（shared-ai-rules 12 章）
--
-- **導けないものは持つしかない。** 「なぜ導出しなかったか」をここへ書いておかないと、
-- 次に読む人が BAN の前例を見て同じ検討をやり直す。
--
--
-- ## NOT NULL + DEFAULT 0 にできる理由
--
-- 0007 / 0009（`revise_count`）と同じ判断である。**既存の行はすべて運営ではない**
-- ——運営用のアカウントは、この列が入ったあとで人が 1 行だけ立てる（下記）。
-- したがって 0 での埋め戻しは既定値の都合ではなく**事実として正しく**、既存 18 件の
-- 作品の表示はこの列が入っても 1 バイトも変わらない。
--
-- NULL を許すと「NULL は運営でないのか、分からないのか」を読む側が毎回決めることになる。
-- 0011 の `effort` と違い、ここには「記録していなかった」状態が無い。
--
--
-- ## CHECK を張る
--
-- **この列を書くのは人の手である**（`docs/operator-account.md`。管理 UI は持たない）。
-- `set is_operator = 'yes'` や `= 2` のような綴り違いを、書いた瞬間に弾く。
-- 0011 が CHECK を避けたのは「取りうる値がアプリの語彙で、増減する」からだが、
-- ここは真偽の 2 値で増えない（`generations.succeeded` と同じ形）。
--
-- 画面は `= 1` を「運営である」と読む（`src/work-page.ts`）。CHECK があるので、
-- 0 と 1 以外の値を「立っている」か「いない」かのどちらへ倒すかを決めずに済む。
--
--
-- ## 立て方は直接 UPDATE である
--
-- **BAN（`users.banned_at`）と同じ運用**で、前例がある。手順は
-- `docs/operator-account.md` にある。
--
-- **機械照合は置けない。** これは D1 の行データなので、本番でフラグが失われても
-- （行の作り直し・誤った UPDATE・復元）**検査はすべて緑のまま通る。** テストが確かめて
-- いるのは列の形と画面の分岐であって、本番の行に 1 が立っていることではない。
--
--
-- ## 索引を張らない
--
-- この列で絞り込む経路は無い。読むのは作品ページが作者を主キーで結合するときだけである
-- （`src/work-page.ts`）。**「将来使うかもしれない」で足さない**（0001 の方針）。
--
--
-- ## 連番が 0021 である理由
--
-- 取り込む側が着手前に割り当てた番号である（`docs/handoff.md` 3 章。`0020` は M9-7、
-- `0022` は M9-6）。`migrations/` を数えて max+1 を取っていない。
ALTER TABLE users ADD COLUMN is_operator INTEGER NOT NULL DEFAULT 0
  CHECK (is_operator IN (0, 1));
