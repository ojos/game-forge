#!/usr/bin/env bash
# check-table-breaks.sh — Markdown の表の途中へ段落が差し込まれ、続く行が表として
# 描画されなくなっていないかを機械で見る（#317）
#
# ══════════════════════════════════════════════════════════════════════════════
# なぜ機構で押さえるか
# ══════════════════════════════════════════════════════════════════════════════
#
# **2026-09-04、3 つのセッションが `docs/handoff.md` を同時に触り、実際に踏んだ**
# （#308 で Copilot に指摘された）。表の途中へ段落を差し込むと、**続く行は表では
# なくなる**——GFM の表は「見出し行＋区切り行」で始まる 1 つのブロックなので、
# 間に段落が入るとそこで表が終わり、残りの行は `| a | b |` という**ただの文字列の
# 段落**として描画される。
#
# **git も、既存のどの検査も捕まえない。** 差分としては正しい行の追加であり、
# 綴りも壊れていない。壊れているのは**ブロックの境界**だけで、これは描画するまで
# 見えない。そして `docs/handoff.md` は**次の人が最初に読む文書**である。そこが
# 崩れると、崩れた先の情報がまるごと読まれなくなる。
#
# 目で見て気づけるなら人のレビューでよい。**描画しないと見えないものは、読んでも
# 気づけない。** `.ai-playbook/shared-ai-rules.md` 12 章「呼びかけで担保しない」に
# 照らして機構へ移す。ここで見るのは「気をつけたか」ではなく「崩れているか」なので、
# 儀式では通過できない。
#
# ══════════════════════════════════════════════════════════════════════════════
# 何をもって「崩れている」とするか
# ══════════════════════════════════════════════════════════════════════════════
#
# **空行の直後にある `|` で始まる行を、表の先頭とみなす。** 表の先頭であるなら、
# **次の行は区切り行（`|---|---|` 等）でなければならない。** そうでないものを数え、
# 0 件であることを見る。
#
#   | a | b |     ← 空行の直後。次が区切り行なので、これは正しい表の始まり
#   |---|---|
#   | 1 | 2 |
#
#   （段落が差し込まれた）
#
#   | 3 | 4 |     ← 空行の直後だが、次が区切り行ではない → **崩れている**
#   | 5 | 6 |
#
# 表の残骸が 1 行だけ（次が空行や本文）の場合も同じ判定で当たる。区切り行だけが
# 取り残された形（見出し行と区切り行の間に段落が入った場合）も、`|` で始まる行と
# して同じ経路で当たる。
#
# ── blockquote の中も対象にする ──────────────────────────────────────────────
#
# **`> |` で始まる表も同じように崩れる。** 引用の中でも GFM の表はブロックとして
# 解釈されるため、性質はまったく同じである。#296 の作業で実際に対象へ含めて回して
# おり、`docs/product-spec.md` には引用内の表が現に 2 つある（2043 行付近 / 2777 行
# 付近）。行頭の `>` を（入れ子も含めて）取り除いてから判定する。引用の中の空行は
# `>` だけの行なので、取り除いた結果が空になることで自然に空行として扱われる。
#
# ══════════════════════════════════════════════════════════════════════════════
# 何を見ないか（意図的に範囲外。この検査が見ていると誤解しないために明記する）
# ══════════════════════════════════════════════════════════════════════════════
#
# - **コードブロック（``` / ~~~ で囲まれた範囲）の中は見ない。** そこに書かれた `|` は
#   表ではなく**出力例の文字**であり、区切り行を足して直すことができない（直したら
#   実際の出力ではなくなる）。**直せない指摘を出す検査は、そのうち丸ごと外される。**
#
#   **ただし、いま除外しなくても偽陽性は出ない。実測した。** 追跡文書のコードブロック内に
#   `|` 始まりの行は 9 行あるが、**そのうち「直前が空行」のものは 0 行**で、除外の有無で
#   件数は 0 件のまま変わらなかった（フェンス追跡を無効にした対照を回して確認）。
#   **それでも除外を入れるのは、条件が「たまたま」だからである**——出力例の中に空行が
#   1 つ入った瞬間に当たり始める。`docs/handoff.md` だけでフェンスの行が 22 本あり、
#   実行結果の貼り直しは日常的に起きる。次の形は、除外が無ければ実際に当たる（実測）:
#
#     ```
#     $ report
#                       ← 出力に含まれる空行
#     | 品質 | 時間 |    ← 除外が無いと、ここが「表の先頭」に見える
#     | q9 | 5,359 ms |
#     ```
# - **区切り行の桁数は数えない。** GFM は見出し行と区切り行の桁数一致を要求するが、
#   ここでは「区切り行の形をしているか」までしか見ない。桁数のずれは**描画は
#   されるが列がずれる**という別の崩れ方で、この検査の関心事（続く行が表でなくなる）
#   とは別である。要るなら別の検査として足すこと。
# - **先頭に `|` を持たない表は見ない**（`a | b` / `--|--` の形）。GFM では書けるが、
#   このリポジトリの追跡文書に 1 つも無く、判定を広げると本文中の `|` を含む段落を
#   拾い始める。**偽陽性を出さないほうを採る。**
# - **Markdown 全般の lint はしない**（#317 scope.out）。汎用 linter の導入は影響
#   範囲が変更行数に比例せず、別の判断が要る。**この 1 形だけを見る。**
#
# 承知のうえで受け入れた寛容さ:
#   - 字下げ 4 文字以上の `|` 行も表の行として扱う。Markdown では字下げコードブロック
#     になりうる形だが、**このリポジトリには箇条書きの中に字下げされた実在の表がある**
#     （`docs/product-spec.md` 2351 行付近）。一方、字下げコードブロックは 1 つも無く、
#     コード例はすべてフェンスで書かれている。**実在するほうを拾う。**
#   - `---` のように桁が 1 つしかない行も区切り行とみなす。水平線と区別できないが、
#     **区切り行と読めるものを広く通す向き**なので、偽陽性は増えない。
#
# ══════════════════════════════════════════════════════════════════════════════
# 決めた 3 点とその理由（#317 の constraints）
# ══════════════════════════════════════════════════════════════════════════════
#
# ── 1. 対象範囲: **追跡している Markdown 全部**（`docs/` だけでも `handoff.md` だけでもない）
#
# 踏んだのは `docs/handoff.md` だが、**崩れ方は文書に固有ではない。** 表を持つ文書
# なら等しく起きる。`docs/product-spec.md` は `|` 始まりの行を 599 本持ち、
# `docs/orchestrator.md` は 31 本持つ。**踏んだ 1 本だけを見る検査は、次に踏む文書を
# 見ていない。**
#
# **一覧をここへ書き並べない。** 書き並べると、文書を 1 本足した日から検査だけが
# 古い一覧を見続ける（`.ai-playbook/shared-ai-rules.md` 12 章「一覧の複製は機械照合
# で担保する」）。`git ls-files` から受け取れば、足した文書はその日から対象になる。
#
# `README.md` / `CLAUDE.md` / `.github/` / `.ai-playbook/` / `terraform/README.md` /
# `third_party/` も含める。**追跡されている＝共有される＝誰かが読む**からで、読まれる
# 文書が崩れることに違いは無い。走査は 42 ファイル 1.1MB で 0.039 秒なので（下記
# 「速度」）、範囲を絞って得られるものが無い。
#
# ── 2. 単一入口へ入れる: **`scripts/acceptance.sh` の衛生検査の並びへ置く**
#
# **入れる。** `scripts/check-page-width.sh` を `scripts/verify.sh` から外してあるのは
# **ブラウザの実行ファイルを前提にするため**で、道具の有無でループの接地信号が止まる
# と実装が正しいのにループが止まるからである（あちらの冒頭）。**この検査は条件が違う**
# ——bash と awk と git しか要らず、ネットワークも認証も外部の道具も要らない。
# `.github/project-ai-rules.md`「受け入れ検証の二層」でいうローカル層にそのまま収まる。
#
# **そして、外すと意味を失う種類の検査である。** 踏んだのは 3 つのセッションが同じ
# 文書を同時に触った日で、**そのとき誰も手で叩かなかった**から通り抜けた。思い出して
# 叩く運用は破綻する（`.github/project-ai-rules.md`「単一入口」）。
#
# `scripts/verify.sh` から直接呼ばず `scripts/acceptance.sh` へ置くのは、verify.sh が
# 直接呼ぶのを機密混入という別格の関心事に限っているためである
# （`scripts/check-control-chars.sh` と同じ扱い）。並びは制御文字検査の直後、
# 言語のマニフェストに依存しない衛生検査の層に置く。
#
# ── 3. 既存文書の扱い: **許容した既存分は無い（実測 0 件）**
#
# 入れた時点で追跡している Markdown 42 ファイルすべてが 0 件だった。**したがって
# 除外規定も猶予も設けていない。** 既存文書の書き直しも発生していない（#317 の
# scope.out に触れていない）。
#
# **将来 0 件でなくなったときは直すこと。** ここへ除外を足す前に考えること: この
# 検査が当たるのは「読み手に表として見えていない箇所」であり、**除外するとは、
# 崩れたままにすると決めることである。** 表として見せる意図が無いのなら、
# それは表ではないので `|` で書かない形（コードブロックか箇条書き）へ直すのが素直で
# ある。除外を足すなら、**その文書のその箇所をなぜ崩れたままにするのかをここへ書く。**
#
# ══════════════════════════════════════════════════════════════════════════════
# 検査が成立していないことを合格にしない
# ══════════════════════════════════════════════════════════════════════════════
#
# git 管理外での実行、git コマンドの失敗、対象ファイル 0 件は、いずれも「表が崩れて
# いない」ことを意味しない。空の出力を「該当なし」と読むと、検査していないのに合格に
# なる。すべて失敗として扱う。
#
# 加えて、**正しい表を 1 つも見つけられなかった場合も失敗させる。** 判定の要である
# フェンス追跡や引用符の除去が壊れると、すべての行がコードブロック扱いになるなどして
# **常に緑を返す検査**になる。そうなったことは赤にならない限り誰も気づけないので、
# 「正しい表を数えられているか」を成立条件として持つ。
#
# さらに**起動時に検査機構そのものを自己診断する**。崩れた表を必ず検出すること、
# および正しい表・引用内の表・コードブロック内の `|` を誤検出しないことを、合成した
# 入力で毎回確かめる。
#
# 速度:
#   追跡 Markdown 42 ファイル / 1,117,656 バイト / 14,231 行の走査で 0.039 秒（実測。
#   同じ環境で scripts/check-control-chars.sh が 0.045 秒）。同じ桁に収まっている。
#   ファイルごとに awk を 1 回起こすので、費用はファイル数にほぼ比例する。目に見えて
#   遅くなったら、awk を 1 回にまとめる（FILENAME ごとの状態を持たせる）のが素直である。
#
# 使い方:
#   bash scripts/check-table-breaks.sh
#
# 終了コード:
#   0 = TABLE_BREAKS_PASS
#   1 = TABLE_BREAKS_FAIL（表が崩れている、または検査が成立しなかった）
set -euo pipefail

# 正規表現の照合順をバイト順に固定する
# （scripts/check-control-chars.sh / check-no-secrets.sh と同じ理由）。
export LC_ALL=C

# 検査はプロジェクトルート基準で行う。scripts/ の 1 階層上がルート。
# 任意の作業ディレクトリから起動しても結果が不変になるよう、起動時 CWD に依存しない。
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$(dirname "$HERE")"

fail() {
  printf '[table-breaks] %s\n' "$1" >&2
  echo "TABLE_BREAKS_FAIL"
  exit 1
}

# ── 判定本体 ─────────────────────────────────────────────────────────────────
#
# 1 ファイルを丸ごと読み、2 段で見る。
#   1 段目: 全行を分類する（フェンスの内外・空行・区切り行・表の行）。フェンスの
#           開閉は順に見ないと決まらないので、必ず先頭から通す。
#   2 段目: 分類の並びだけを見て判定する。次の行の分類が要るため、1 段目とは分ける。
#
# 出力は種別付きの行（HIT / NEXT / UNCLOSED / STAT）で、集計は呼び出し側が行う。
#
# awk は mawk（Debian 既定）を前提に、POSIX の範囲だけで書く
# （gensub 等の gawk 拡張は使わない。scripts/check-shell-portability.sh の表と同じ考え方）。
AWK_PROG='
# 行頭の空白と blockquote の `>`（入れ子を含む）を取り除く。
function strip_quote(line,   s) {
  s = line
  sub(/^[ \t]+/, "", s)
  while (s ~ /^>/) {
    sub(/^>/, "", s)
    sub(/^[ \t]+/, "", s)
  }
  return s
}

# 区切り行（`|---|---|` / `| :--- | ---: |` / `---`）の形をしているか。
# `-` を 1 つ以上含むことを併せて見る（空行が範囲指定の隙間で当たらないように）。
function is_delim(s) {
  if (s !~ /-/) return 0
  return s ~ /^\|?[ \t]*:?-+:?[ \t]*(\|[ \t]*:?-+:?[ \t]*)*\|?[ \t]*$/
}

# フェンス（``` / ~~~）の記号の連なりの長さ。フェンスでなければ 0。
function fence_len(s,   c, n) {
  c = substr(s, 1, 1)
  if (c != "`" && c != "~") return 0
  n = 0
  while (substr(s, n + 1, 1) == c) n++
  if (n < 3) return 0
  return n
}

BEGIN { n = 0 }
{ raw[++n] = $0 }

END {
  # ── 1 段目: 分類 ──────────────────────────────────────────────────────────
  #
  # cls[i]: "CODE"（フェンスの行、およびその中身）/ "BLANK" / "ROW"（`|` 始まり）/ "TEXT"
  # delim[i]: その行が区切り行の形をしているか（フェンスの外だけで意味を持つ）
  infence = 0
  fch = ""
  flen = 0
  for (i = 1; i <= n; i++) {
    s = strip_quote(raw[i])
    delim[i] = 0
    fl = fence_len(s)
    if (fl > 0) {
      c = substr(s, 1, 1)
      if (!infence) {
        infence = 1; fch = c; flen = fl
      } else if (c == fch && fl >= flen) {
        # 閉じるフェンスは記号の後ろに空白しか置けない（開くほうは情報文字列を取れる）。
        rest = substr(s, fl + 1)
        if (rest ~ /^[ \t]*$/) { infence = 0; fch = ""; flen = 0 }
      }
      cls[i] = "CODE"
      continue
    }
    if (infence) { cls[i] = "CODE"; continue }
    if (s == "") { cls[i] = "BLANK"; continue }
    delim[i] = is_delim(s)
    if (substr(s, 1, 1) == "|") { cls[i] = "ROW"; continue }
    cls[i] = "TEXT"
  }

  # フェンスが閉じないまま終わった場合、そこから後ろを全部コードとして黙らせている。
  # 検査が届かなかった範囲があることを呼び出し側へ伝える（緑にしない材料になる）。
  if (infence) printf "UNCLOSED\t%s\n", FILENAME

  # ── 2 段目: 判定 ──────────────────────────────────────────────────────────
  #
  # 空行の直後にある `|` 始まりの行を表の先頭とみなし、次の行が区切り行かを見る。
  # 直前が無い（ファイル先頭）場合も「空行の直後」と同じに扱う——先頭に置かれた表も
  # 区切り行を必要とすることに変わりはない。
  tables = 0
  hits = 0
  for (i = 1; i <= n; i++) {
    if (cls[i] != "ROW") continue
    if (i > 1 && cls[i - 1] != "BLANK") continue
    if (i < n && delim[i + 1]) { tables++; continue }
    hits++
    printf "HIT\t%s\t%d\t%s\n", FILENAME, i, raw[i]
    if (i < n) printf "NEXT\t%s\t%d\t%s\n", FILENAME, i + 1, raw[i + 1]
    else printf "NEXT\t%s\t%d\t（ファイル末尾）\n", FILENAME, i
  }
  printf "STAT\t%s\t%d\t%d\t%d\n", FILENAME, n, tables, hits
}
'

# 1 ファイルを走査し、種別付きの行を標準出力へ返す。
scan_one() {
  awk "$AWK_PROG" "$1"
}

# ── 自己診断 ─────────────────────────────────────────────────────────────────
#
# 両方向を見る。当たること（偽陰性＝常に緑になる壊れ方）と、当たらないこと（偽陽性）。
# awk が早期終了しても影響しないよう、標準入力ではなくプロセス置換のファイルで渡す。

# (1) 表の途中へ段落が差し込まれた形は、必ず当たること。
selftest_broken="$(scan_one <(printf '| a | b |\n|---|---|\n| 1 | 2 |\n\n差し込まれた段落。\n\n| 3 | 4 |\n| 5 | 6 |\n') || true)"
case "$selftest_broken" in
  *HIT*) ;;
  *) fail "自己診断に失敗しました: 段落が差し込まれた表を検出できません。検査が成立していないため失敗させます。" ;;
esac

# (2) 正しい表・引用内の表・コードブロック内の `|`・表の直後に空行を挟んだ段落は、
#     いずれも当たらないこと。**この 4 つが #317 で挙がった偽陽性の候補である。**
selftest_clean="$(scan_one <(printf '| a | b |\n|---|---|\n| 1 | 2 |\n\n表の直後の段落。\n\n> | c | d |\n> |---|---|\n> | 3 | 4 |\n\n```\n| これは出力例 |\n| 区切り行を持たない |\n```\n\n本文。\n') || true)"
case "$selftest_clean" in
  *HIT*) fail "自己診断に失敗しました: 正しい表（引用内・コードブロック内を含む）を誤検出します。検査が成立していないため失敗させます。" ;;
esac
# STAT の tables=2（本文の表と引用内の表）/ hits=0 まで見る。「当たらない」だけだと、
# 全部をコード扱いする壊れ方（常に緑）を見逃す。
case "$selftest_clean" in
  *"	2	0") ;;
  *) fail "自己診断に失敗しました: 正しい表を 2 つ数えられません。フェンスや引用の扱いが壊れています。" ;;
esac

# ── 検査対象の列挙 ───────────────────────────────────────────────────────────

git rev-parse --is-inside-work-tree >/dev/null 2>&1 \
  || fail "git の作業ツリーではありません。対象文書を列挙できないため失敗させます。"

# 列挙は NUL 区切り。パス名に改行を含むファイルでも 1 レコードのまま崩れずに読める
# （scripts/check-control-chars.sh と同じ扱い）。
targets=()
while IFS= read -r -d '' path; do
  # 実体が無いもの（削除済み・サブモジュール）とシンボリックリンクは走査しない。
  [[ -L "$path" ]] && continue
  [[ -f "$path" ]] || continue
  targets+=("$path")
done < <(git ls-files -z '*.md' '*.markdown')

[[ "${#targets[@]}" -gt 0 ]] \
  || fail "追跡している Markdown が 1 件もありません。検査していないことと、表が崩れていないことは別なので失敗させます。"

# ── 走査 ─────────────────────────────────────────────────────────────────────

total_lines=0
total_tables=0
total_hits=0
unclosed=0

for path in "${targets[@]}"; do
  while IFS=$'\t' read -r kind f a b c; do
    case "$kind" in
      HIT)
        printf '[table-breaks] %s:%s: 表の先頭に見えますが、次の行が区切り行ではありません。\n' "$f" "$a" >&2
        printf '[table-breaks]     %s\n' "$b" >&2
        ;;
      NEXT)
        printf '[table-breaks]   次の行 %s: %s\n' "$a" "$b" >&2
        ;;
      UNCLOSED)
        printf '[table-breaks] %s: コードブロックが閉じていません。閉じ忘れた位置から先は走査できていません。\n' "$f" >&2
        unclosed=$((unclosed + 1))
        ;;
      STAT)
        total_lines=$((total_lines + a))
        total_tables=$((total_tables + b))
        total_hits=$((total_hits + c))
        ;;
    esac
  done < <(scan_one "$path")
done

# ── 結果 ─────────────────────────────────────────────────────────────────────

printf '[table-breaks] %s ファイル / %s 行を走査し、正しい表を %s 個数えました。\n' \
  "${#targets[@]}" "$total_lines" "$total_tables"

# 正しい表を 1 つも数えられないのは、判定が壊れている（全部コード扱いなど）ことの
# 現れである。0 件を「崩れていない」と読ませない（冒頭「検査が成立していないことを
# 合格にしない」）。
[[ "$total_tables" -gt 0 ]] \
  || fail "正しい表を 1 つも数えられませんでした。判定が壊れている可能性があるため失敗させます。"

# 閉じないコードブロックは、その先を丸ごと走査対象から落とす。表の崩れとしては
# 報告しないが、**見ていない範囲がある**まま緑にはしない。
if [[ "$unclosed" -gt 0 ]]; then
  printf '[table-breaks] コードブロックが閉じていない文書が %s 件あります。閉じてください。\n' "$unclosed" >&2
  echo "TABLE_BREAKS_FAIL"
  exit 1
fi

if [[ "$total_hits" -gt 0 ]]; then
  printf '[table-breaks] 表として描画されない `|` の並びを %s 件検出しました。\n' "$total_hits" >&2
  printf '[table-breaks] 表の途中へ段落を差し込むと、そこで表は終わり、続く行はただの段落になります。\n' >&2
  printf '[table-breaks] 対処: 差し込んだ段落を表の前か後ろへ移す。表を分けたいなら、\n' >&2
  printf '[table-breaks]       後半にも見出し行と区切り行（|---|---|）を書く。\n' >&2
  echo "TABLE_BREAKS_FAIL"
  exit 1
fi

echo "TABLE_BREAKS_PASS"
exit 0
