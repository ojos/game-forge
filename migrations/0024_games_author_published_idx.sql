-- 作者ページ（#330 / M9-4 / 仕様 2.3.1・2.3.3・5.8）が引くための部分索引。
--
-- ## 何を引くのか
--
-- 作者ページは 1 人の作者について 2 つの問い合わせを出す（`src/users-page.ts`）。
--
--   1. **その人の公開作品を、公開の新しい順に 1 頁ぶん**（`authorWorksSql`。20 件＋1）
--   2. **被いいね数**——その人の公開作品の `like_count` の合計（`likesReceivedSql`）
--
-- どちらも `author_id` で絞り、**8.4 の審査で新規露出を止めた作品と `draft` を引く時点で
-- 除く**（`src/reports.ts` の `reviewVisibleSql`）。
--
--
-- ## 既にある 2 本では足りない
--
-- | 索引 | 足りない理由 |
-- |---|---|
-- | `0008` の `games_author_id_created_at_idx`（`author_id, created_at DESC, id DESC`） | **公開状態と審査の条件を含まない。** 作者の下書きと審査で止まった作品が `author_id` の下に並ぶので、20 件を集めるまでに挟まった数だけ余分に読む |
-- | `0023` の `games_official_samples_idx`（同じ列順の部分索引） | **並びが `created_at` である。** 作者ページは**公開日時の順**に並べる（下の節）ので、この索引の上では並べ替えのための一時 B-tree が入り、**LIMIT を掛ける前にその作者の公開作品を全件読む**（`src/home-feed.ts` が実測した形そのもの） |
--
-- **`0023` を張り替えるのではなく、もう 1 本足す。** 軸が違えば索引も別に要る
-- （`0019` が「並べ替えの軸ぶんを張る」と書いたのと同じ判断）。張り替えると、
-- トップの公式サンプルの節が一時 B-tree を踏む側へ移るだけである。
--
--
-- ## 並びは公開日時の順である（`created_at` ではない）
--
-- **`0023` とここで判断が分かれている。理由は「カードが何を出すか」である。**
--
-- 公式サンプルの節は**運営が選んだ固定の集合**（#43 の 10 本）で、並びの軸が「生成」か
-- 「公開」かは利用者の判断に効かない（`src/home-feed.ts`）。**作者ページは違う。**
-- カードは `games.published_at` を文字で出す（仕様 2.3.6）ので、**並びが生成日時だと、
-- 画面に見えている日時の順に並んでいない一覧**になる。生成してすぐ公開しない作品が
-- 1 本あれば起きる。
--
-- **索引を 1 本足せば、その食い違いを作らずに読み取りの上限を固定できる**
-- （`created_at` を採る理由は「索引が無いこと」だったので、張れば消える）。
--
--
-- ## 読み取りの上限（仕様 2.3.3 の条件 1）
--
-- - **一覧は 1 頁 21 行で固定される。** 索引の列順が `order by` そのものなので、
--   一時 B-tree も、捨てるために読む行も出ない
-- - **被いいね数は、その作者の公開作品の数に比例する。** これは仕様 5.8 が明示的に
--   選んだ形である（「作者 1 人の作品数に比例する読み取りで、`(author_id, …)` の索引が
--   効く」）。**母数（公開作品の総数）には比例しない**ので、条件 1 の趣旨は保たれている。
--   利用者の側に非正規化列を足さないのは 5.8 の決定である
--
-- **`like_count` を索引へ載せない。** 載せれば合計が covering index で済む（表の行を
-- 1 つも読まない）が、**いいねの同期が 5 分おきに書く列**である（`0020`）。載せた分だけ
-- 同期 1 回の書き込みが増え、3.6 の見積もり（変わった作品 1 本につき 2 行）が変わる。
-- **5 分おきに増える書き込みと、作者ページを開いたときだけ増える読み取りを交換しない。**
--
--
-- ## 綴りは `reviewVisibleSql()` と揃える
--
-- 条件は `src/reports.ts` の `reviewVisibleSql()` が返す文字列と**同じ綴り**にしてある。
-- SQLite は問い合わせの条件が索引の条件を含むと示せたときだけ部分索引を使うので、
-- **綴りがずれると黙って使われなくなる**（そして `0008` の索引へ落ちるだけなので、
-- 結果は正しいまま読み取りだけが増える——**いちばん気づきにくい壊れ方である**）。
-- **`test/schema-author-page.test.ts` がこの一致と実行計画を機械で確かめる。**
--
--
-- ## 費用
--
-- 書き込みが増えるのは、**作品が公開・非公開になるときだけ**である（部分索引の条件を
-- 満たす行の出入り）。公開は月数十件の規模で（3.7 / 確定25 の生成枠から導かれる上限）、
-- 書き込みの無料枠 10 万行/日 に対して無視できる。**`like_count` の同期では 1 行も
-- 増えない**（上のとおり載せていない）。
--
--
-- ## 連番が 0024 である理由
--
-- 取り込む側が割り当てた番号である（`docs/handoff.md` 3 章）。**`migrations/` を数えて
-- max+1 を取っていない**（`0009` の衝突はそれで起きた）。

CREATE INDEX games_author_published_at_idx
  ON games(author_id, published_at DESC, id DESC)
  WHERE status = 'published' AND (review_state is null or review_state = 'cleared');
