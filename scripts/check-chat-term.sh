#!/usr/bin/env bash
# check-chat-term.sh — 画面と文書の用語が「チャット」へ揃っていること（#740 / 仕様 5.16「用語」）
#
# ## なぜ要るのか
#
# **利用者に見える語を「チャット」へ統一した**（利用者の決定。確定31 が「フォーク」
# 「リフォージ」で行ったのと同じ揃え方である）。**揃え直しは 1 回で終わるが、揃った状態は
# 終わらない**——次に画面へ 1 文を足す人は、古い語で書いた文章（仕様書の過去の記述・
# 過去の issue・この機能を最初に作った PR）を読みながら書く。**呼びかけでは戻る。**
#
# ## 何を見るか——文字列だけを選り分けない
#
# **`src/` と `workers/` を丸ごと見る。** 画面へ出る文字列だけを静的に選り分ける形にすると、
# **選り分けの穴がそのまま検査の穴になる**（テンプレート文字列・分類名から引く表・
# スクリプトの中の文言は、どれも「文字列リテラル」の見分け方が違う）。
# **コメントまで見るのは、揃えたい語がコメントから本文へ写されるためでもある。**
#
# **仕様書は節名だけを見る。** 仕様書側で揃える対象は **5.16 の節名**だけである
# （仕様 5.16「用語」の表の「仕様」の行）。**本文は過去の記述を書き換えない**
# ——このリポジトリは決定の経緯を上書きしないので、4.3 / 5.7 / 12 章の注記も、
# 確定の表も、`## 版の履歴` も、**書かれた時点の語のまま残る。** 数えれば必ず落ちる。
#
# **`docs/` のほかの文書も見ない。** `docs/takedown.md` の「アカウントを消したいという
# 問い合わせ」のように、**この機能とは別の意味で同じ語を使っている文がある**
# （揃えると引用や運用手順のほうが壊れる）。
#
# ## 検査が自分で落ちない形
#
# **探す語をこのファイルへ書かない**（`printf` の 8 進で組み立てる）。書くと、
# **説明文のせいで検査自身が引っかかる**——#726 で似た形を踏んでいる。
#
# 使い方:
#   bash scripts/check-chat-term.sh
#
# 終了コード: 0 = 合格（標準出力 CHAT_TERM_PASS）/ 非0 = 不合格
#
# **GNU 拡張を使わない**（利用者の端末は macOS / bash 3.2）。
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$(dirname "$HERE")"

# 揃える前の語。**綴りをそのまま書かない**（上記「検査が自分で落ちない形」）。
OLD_TERM="$(printf '\347\233\270\350\253\207')"
# 揃えた後の語（節名の照合に使う）。
NEW_TERM="$(printf '\343\203\201\343\203\243\343\203\203\343\203\210')"

SPEC="docs/product-spec.md"

fail() {
  printf '[chat-term] %s\n' "$*" >&2
  exit 1
}

# ── 画面（`src/` と `workers/`）─────────────────────────────────────────────
#
# **追跡しているファイルだけを見る**（手元の作業ファイルは対象にしない）。git の作業ツリー
# でない・対象が 1 件も無いときは**合格にしない**——見ていないことと、無いことは別である
# （`scripts/check-no-secrets.sh` と同じ判断）。
git rev-parse --is-inside-work-tree >/dev/null 2>&1 ||
  fail "git の作業ツリーではありません。検査が成立しないため失敗させます。"

targets="$(git ls-files 'src/*' 'workers/*')"
count="$(printf '%s\n' "$targets" | grep -c . || true)"
[[ "$count" -gt 0 ]] ||
  fail "src/ と workers/ に追跡ファイルがありません。検査が成立しないため失敗させます。"

found=0
while IFS= read -r file; do
  [[ -n "$file" ]] || continue
  if grep -n "$OLD_TERM" "$file" >/dev/null 2>&1; then
    found=1
    grep -n "$OLD_TERM" "$file" | sed "s|^|    $file:|" >&2
  fi
done <<EOF
$targets
EOF

if [[ "$found" -ne 0 ]]; then
  echo "[chat-term] 上の行が、揃える前の語のまま残っています（仕様 5.16「用語」）。" >&2
  fail "画面の用語が「${NEW_TERM}」へ揃っていません。"
fi

# ── 仕様（5.16 の節名）───────────────────────────────────────────────────
[[ -f "$SPEC" ]] || fail "$SPEC がありません。検査が成立しないため失敗させます。"

HEADING="$(grep -n '^### 5\.16 ' "$SPEC" | head -1)"
[[ -n "$HEADING" ]] ||
  fail "$SPEC に 5.16 の見出しがありません（節の番号が変わったなら、この検査も追随させてください）。"

# **取り消し線の中は見ない。** 節名は改名の経緯を `~~旧名~~` の形で残すので、そこまで
# 数えると「改名したことを書いた」ことで落ちる（過去の記述を書き換えないのと同じ線）。
HEADING_NOW="$(printf '%s\n' "$HEADING" | sed 's/~~[^~]*~~//g')"

case "$HEADING_NOW" in
  *"$OLD_TERM"*)
    printf '    %s\n' "$HEADING" >&2
    fail "5.16 の節名が揃っていません（仕様 5.16「用語」の表の「仕様」の行）。"
    ;;
esac
case "$HEADING_NOW" in
  *"$NEW_TERM"*) ;;
  *)
    printf '    %s\n' "$HEADING" >&2
    fail "5.16 の節名に「${NEW_TERM}」がありません。"
    ;;
esac

echo "CHAT_TERM_PASS"
