-- 著名 IP 名を置き換えたことを、作者へ開示するための列を `games` へ足す（6.2 / #39）。
--
-- ## なぜ列が要るのか
--
-- 6.2 は「**置換したことをユーザーに開示する。黙って別物を出すのは体験として悪い**」と
-- 定める。しかし**開示を出せる場所が無かった。**
--
--   - 生成ページは 202 を受けた瞬間に `/works/<id>` へ遷移する
--     （`src/generate-page.ts`）。応答本文に載せても捨てられる
--   - `games` はプロンプトを持たない（持つのは `title` だけ）
--   - `generations.prompt` は**結合できない**。確定27 が `generations.game_id` を
--     結ばないと決めており、常に NULL であることが正常である
--   - `game_revisions.prompt` は **`seq = 1`（初回生成）が NULL** である
--
-- **どこにも残っていないので、置換の事実だけをここへ残す。**
--
-- ## 何を入れるか
--
-- **こちらの一覧が持つ正式名の並び**（`src/ip-terms.ts` の `label`）を繋いだものを入れる。
-- **利用者が書いた文字列そのものは入れない。** 入れると 5.1 の入力が別の列へ複製され、
-- 8.2 が「持ち出さない」と決めているものが増える。
--
-- **区切り文字の正本は `src/ip-substitution.ts` の `IP_NOTICE_SEPARATOR` である。**
-- ここへ値を書き写さない（確定24 がタイムアウトの値で採ったのと同じ規約）。読み書きは
-- `ipNoticeOf` と `parseIpNotice` を通し、**手で組み立てない**——区切りを取り違えると
-- 1 件が 2 件に割れる。**正式名に区切りが混ざらないことは `test/ip-substitution.test.ts`
-- が一覧そのものに対して機械照合する。**
--
-- 印字できない文字を選んでいるのは、正式名に現れないことを保証するためである
-- （読点やカンマは名前に現れうる）。**この列は画面へそのまま出るものではない**ので、
-- 読みやすさより「割れないこと」を優先する。
--
-- NULL は「当たらなかった」である。空文字列を使わないのは、`null` と `''` の
-- 2 通りが「当たらなかった」を意味する状態を作らないためである。
--
-- ## NOT NULL にしない
--
-- **既存の行はすべて NULL になる。** 置換されたかどうかは、その行が作られた時点の
-- プロンプトにしか書かれておらず、いまから遡って判定する材料が無い（上記）。
-- 既定値で埋めると「当たらなかった」と区別が付かなくなる——**「調べていない」と
-- 「調べて当たらなかった」は別である**（`docs/handoff.md` 2 章）。
--
-- ## 索引を張らない
--
-- 索引は 1 行の insert につき 1 行の書き込みを足す（3.6）。この列で絞り込む経路は
-- 無く、読むのは作品ページが 1 行を引くときだけである（既に主キーで引いている）。
-- **「将来使うかもしれない」で足さない**（0001 の方針）。

