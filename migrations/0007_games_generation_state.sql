-- 生成の進行状態を `games` へ持たせる（3.3 / 5.4 / #150）。
--
-- **これは「作品行を LLM 呼び出しより前に作る」ための土台である。** #150 は、送信した
-- 瞬間に恒久的な URL を渡してタブを閉じられるようにすることを目標にしている。行を先に
-- 作る以上、**成果物がまだ無い行**が D1 に存在する時間帯ができるので、その状態を
-- 表現する場所が要る。
--
--
-- ## `games.status` を作り直さない（#150 で決めた）
--
-- `status` は `CHECK (status IN ('draft','published','removed'))` である。生成中の状態を
-- ここへ足すには CHECK の作り直し＝テーブル再構築（SQLite の 12 手順）が要る。**採らない。**
-- 理由は「12 手順が高い」ことではなく、次の 2 つである。
--
-- 1. **再構築しても、防ぎたいものが防げない。** 配信側（`src/sandbox-delivery.ts`）の
--    `/p/` は `where preview_key = ? and status <> 'removed'` で引く。`status` へ
--    `'generating'` を足しても**その条件に一致し続ける**ため、生成中の行は結局
--    配信経路へ入ってくる。再構築の危険（`games` は `parent_id` の自己参照を持ち、
--    `generations` と `reports` から参照されている）に対して、買えるものが無い。
-- 2. **軸が違う。** `status` は 5.4 の**公開状態**（下書き・公開・削除）である。
--    「成果物が揃ったか」は別の軸で、1 列へ畳むと、両方の読み手が片方をもう片方から
--    推測することになる。
--
-- **生成中も `status` は `draft` のままである。** 5.4 の「生成直後は draft」は変わらない。
--
--
-- ## NOT NULL + DEFAULT にする（0006 とここが違う）
--
-- 0006（`preview_key`）は NOT NULL を諦めた。「このキーは行ごとに違う乱数でなければ
-- 意味がない」ため、定数の既定値を置けなかったからである。**こちらは置ける。**
--
-- **既存の行はすべて完成済みである。** 旧`createDraftGame` は 3.3 の**最後の段**で
-- 呼ばれており、行があること自体が「成果物が揃っている」ことを意味していた。
-- したがって `'ready'` での埋め戻しは、既定値の都合ではなく**事実として正しい**。
--
-- NULL 許容にすると「NULL は未設定か、完成か」を読む側が毎回決めることになる。
-- 埋め戻せる以上、その曖昧さを残す理由が無い。
--
-- SQLite の ALTER TABLE ADD COLUMN が NOT NULL + DEFAULT + CHECK を受け付けること、
-- および既存行が既定値で埋まることは実測で確認した（#150）。
--
--
-- ## 0006 の「アプリ側は必ず書く」を、ここで上書きする
--
-- **`migrations/0006_games_preview_key.sql` は「アプリ側は必ず書く（`createDraftGame`）。
-- 列としての NULL 許容は、既に存在する行のためだけに開いている」と書いた。
-- #150 でこの不変条件を意図的に緩める。**
--
--   新しい不変条件: `preview_key` が非 NULL であることと、
--                   `generation_state = 'ready'` であることは同値である。
--
-- **これは #150 が見つけた「生成中の行が 500 に化ける」問題への答えである。**
-- 配信側（`src/sandbox-delivery.ts`。#28）は「D1 に行があるのに R2 に実体が無い場合は
-- 404 ではなく 500」と決めており、3.7 の隙間を「消えた作品」に見せないためのその判断は
-- 正しい。しかし**生成中の行がそこへ入ると、正常な待ち時間が障害に見える。**
--
-- 具体的には、成果物の無い行が配信側へ届くと 2 つ壊れる。
--
--   - `/p/<key>/`         … ローダー文書は R2 を見ずに 200 を返し、その後 `game.wasm` が 404 になる
--   - `/p/<key>/wasm_exec.js` … `go_version` が空だと `wasmExecKey` が null を返し、**500** になる
--
-- **`preview_key` を完成時まで書かなければ、どちらも起きない。** `resolveGame` は
-- `where preview_key = ?` で引くので、**キーの無い行はこの経路から原理的に引けない。**
-- `status='draft'` である以上 `/g/`（`status='published'` のみ）からも引けない。
-- すなわち**生成中の行は、配信側のどの分岐にも到達しない。**
--
-- 到達しない設計にするほうが、配信側へ「生成中を除外する条件」を足して回るより堅い
-- （足す形は、条件を書き忘れた経路が生まれても動作では気づけない）。**配信側の SQL は
-- 1 文字も変えていない。**
--
--
-- ## 状態の遷移
--
--     pending ──claim──► running ──┬──► ready   （成果物が揃った。preview_key もここで入る）
--        │                          └──► failed  （もう成果物は来ない）
--        └──（イベントが届かなかった）──► pending のまま
--
-- **`pending` と `running` を分ける理由は、AWS Lambda の非同期呼び出しにある**（#150）。
-- Lambda は「関数がエラーを返さなくても同じイベントを複数回配信しうる」（キューが結果
-- 整合であるため。AWS 明文）。`MaximumRetryAttempts=0` の設定だけでは重複を防げない。
--
-- **重複を止めるのは設定ではなく、この列に対する条件付き UPDATE である。**
--
--     update games set generation_state='running'
--      where id=? and generation_state='pending' and job_token_hash=?
--
-- 0 行更新なら、そのジョブは既に誰かが握っている。ジョブ側は LLM を呼ばずに降りる。
-- **設定は誰かが変えれば消えるが、条件付き UPDATE はデータ側にあるので消えない。**
-- 1 回の送信につき LLM が 1 回しか走らないことは、ここでしか担保できない
-- （約 16 円 / 回、かつ日次枠は台帳の行数で数える。確定25 / 4.3）。
--
-- 副産物として、`pending` のまま動かない行（イベントが送られずに削除された場合。
-- これも AWS が明文で認めている）と、正常に走っている行を区別して表示できる。
--
--
-- ## 失敗した行は 3.7 の掃除にそのまま乗る
--
-- **新しい掃除の規約を作らない。** 失敗した行も `status='draft'` のままであり、公開
-- されないまま 14 日で自動削除される（3.7 / 確定13）。`status` を触らない選択が、
-- ここでも効いている。
ALTER TABLE games ADD COLUMN generation_state TEXT NOT NULL DEFAULT 'ready'
  CHECK (generation_state IN ('pending', 'running', 'ready', 'failed'));

-- 失敗の分類名（8.3）。**固定の語彙だけを入れる。**
--
-- 生成物やモデル由来の文字列をここへ入れない。この列は作品ページ（`/works/<id>`）が
-- 「どの固定文言を出すか」を選ぶ鍵として読むだけで、値そのものは画面へ出ない
-- （`src/generate-page.ts` の 8.3 の方針と同じ）。値の一覧はコード側が持つ
-- （`src/games.ts` の `GENERATION_ERROR_CODES`）。
--
-- CHECK を張らないのは、分類名がアプリの語彙であり、増減のたびにマイグレーションを
-- 足す形にすると**表示の都合でスキーマが動く**ためである。`generation_state` のほうは
-- 遷移そのもの（＝データの整合性）なので CHECK を張る。区別の軸はここにある。
ALTER TABLE games ADD COLUMN generation_error TEXT;

-- ジョブごとの使い捨てトークンの SHA-256（小文字 16 進 64 桁）。
--
-- **共有シークレットを置かないための列である**（#150 / 7.3 / 9.2）。生成の本体が
-- Worker の外（Lambda）へ出ると、その外側から D1 を更新する経路が要る。選択肢は 2 つ
-- あった。
--
--   (a) Cloudflare の API トークンを AWS 側へ置き、D1 の REST API を直接叩く
--   (b) Worker のコールバック経路を叩く
--
-- **(a) を採らない。** D1 の編集権限はアカウント単位で、そのトークンは本番を含む
-- **すべての D1 データベースの読み書きと削除**ができる。「1 行を更新したい」に対して
-- 代償が大きすぎる。
--
-- (b) でも、長命の共有シークレットを 1 本置く形は避けられる。**Worker が行を作るときに
-- 乱数を 1 本引き、そのハッシュだけをここへ保存し、平文は呼び出しのペイロードにだけ
-- 載せる。** このトークンにできるのは「この 1 行を完成または失敗させること」だけで、
-- 他の作品にも他のテーブルにも届かない。寿命は 1 ジョブである。
--
-- **平文を保存しない**のは、D1 が漏れたときにトークンがそのまま使える状態を作らない
-- ため。照合はハッシュ同士で行う（`src/games.ts` の `hashJobToken`）。
--
-- 完了（`ready` / `failed`）と同時に NULL へ落とす。**使い捨てである。**
ALTER TABLE games ADD COLUMN job_token_hash TEXT;

-- ジョブが実際に走り始めた時刻（UNIX 秒）。`claim` で入る。
--
-- `created_at`（行を作った時刻）との差が、非同期呼び出しがキューで待った時間になる。
-- **2 つ持つのは、利用者に出す文言を分けるためである**（#150）。
--
--   - `pending` のまま長い … ジョブが始まっていない（基盤側の問題）
--   - `running` のまま長い … 走っているが終わらない、あるいは実行環境が落ちた
--
-- 同期実行（既定）では、行の作成と `claim` がほぼ同時なので差はほぼ 0 になる。
ALTER TABLE games ADD COLUMN generation_started_at INTEGER;

-- 生成中の行を引くための索引。
--
-- **必要とする問い合わせが決まっているから張る**（0004 / 0006 と同じ判断）。
-- 3.7 の掃除と運用の確認が「まだ終わっていない行」を引く。`status` と違って
-- 生成中の行は全体のごく一部なので、部分索引にして小さく保つ。
CREATE INDEX games_generation_state_idx ON games(generation_state)
  WHERE generation_state IN ('pending', 'running');
