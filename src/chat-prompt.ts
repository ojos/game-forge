/**
 * チャットのシステムプロンプト（#695 / M18-2。仕様 5.16「話題の制限」）。
 *
 * ## 6.1 の写しではない
 *
 * **6.1（`src/system-prompt.ts`）はモデルに Go を書かせるための制約で、こちらは人が
 * 指示文を書くのを手伝わせるための制約である。** 読み手も出力も違うので、本文を共有しない。
 * **共有すると、6.1 を直すたびにチャットの口調まで動く**——そしてチャットは「コードを返さない」と
 * 決めた側である（5.7 の線）。
 *
 * **ただし、勧める形は 6.1 で作れるものに収める。** 作れないものを勧めると、作者はその
 * 指示文で生成して失敗する。ここへ書き写すのは**作者が指示文を書くときに効く制約だけ**で、
 * Go の書き方（`state_count` の数え方など）は書かない。
 *
 * ## 話題は 2 枚で縛る
 *
 * **1 枚目は 8.2 の Guardrail**（`src/chat/handler.ts` が LLM を呼ぶ前に掛ける）。
 * **2 枚目がこの本文である。** Guardrail は暴力・性的表現などのカテゴリを見るもので、
 * 「ゲーム作りと関係のない雑談」は通す。**用途を縛るのはこちらの仕事である。**
 *
 * ## 版を持つ
 *
 * 台帳の `prompt_version` へ入る（`migrations/0046_source_quality.sql` と同じ列）。
 * **本文を変えたら上げる**——1 往復の費用も返ってくる形も本文で変わるので、
 * あとから「どの版のチャットだったか」を引けないと、実測が比べられない。
 *
 * | 版 | 何を変えたか |
 * |---|---|
 * | 1 | #695 で作った |
 * | 2 | #727 でフォークのチャットと、文脈の扱いを足した |
 * | 3 | #742 で「下書きを 1 度出したら、毎回【指示文】の全文を出す」を足した |
 *
 * ## 版 3——毎回、下書きの全文を出させる（#742）
 *
 * **1 回の要求に載るのは直近 3 往復だけである**（`src/chat-payload.ts` の `CHAT_SEND_WINDOW_TURNS`）。
 * **窓から落ちた往復の内容は、最新の返答が持つ下書きが引き継ぐ**——差分だけの返し方（「さきほどの
 * 指示文に〜を足します」）を許すと、**差分の元になった下書きが窓から落ちた時点で、話の中身が消える。**
 * **この版の 1 文が、窓の前提そのものである。** 出力は 1 通 400〜500 トークンに増えるが、
 * 要約による圧縮（別の LLM 呼び出し）より安い（#742 の intake）。
 */
import type { GenerationModel, SystemBlock } from './generation-models.js';
import { supportsPromptCaching } from './generation-models.js';

