-- 招待の発行時刻（8.1 / #355 / #396。M11-2）。
--
-- ## なぜ要るのか
--
-- **招待枠を「総数 3 本・戻らない」から「3 本まで溜まり、使うと 30 日ごとに 1 本ずつ戻る」へ
-- 変えた**（仕様 8.1 v1.55）。残高は**発行履歴から毎回計算する**（残高の列も定期処理も
-- 持たない。`src/invite-balance.ts`）。時間で判定する以上、**いつ発行したか**が要るが、
-- `invites` には発行時刻の列が無かった（0001 は `code` / `issued_by` / `used_by` /
-- `used_at` / `expires_at` だけ）。
--
-- ## 既存の行は 0（UNIX 紀元）で埋まる。**これが埋め戻しである**
--
-- `ADD COLUMN ... NOT NULL DEFAULT 0` は、既存の行を既定値で埋める。**0 は「列ができる前に
-- 発行された（十分に古い）」を表す。** 仕様 8.1 は既存行を「移行時点より 30 日以上前」として
-- 埋めると定めているが、**30 日前ちょうどでは足りない**——3 本使い切った人の 3 本が同じ
-- 30 日前に並ぶと、移行直後に戻っているのは 1 本だけになる。**3 本すべてが戻っているには
-- 90 日以上前が要り、0 はそれを満たす**（移行時点で全員が 3 本から始まる。`test/invite-balance.test.ts`
-- と `test/invites.test.ts` が固定する）。
--
-- **`used_at` で埋める形は採らない**（8.1。PR #357 の Copilot の指摘）——使われた時刻であって
-- 発行した時刻ではなく、最近使われた行が「最近の発行」として数えられ、移行直後の残高が
-- 3 本に満たなくなる。
--
-- **UPDATE を書かないのは、既定値が同じことをするからである。** 別に `update invites set
-- issued_at = ...` を置くと、「列を足す」と「埋める」の間に発行された行（本番へ当ててから
-- 配り終えるまでの窓）まで古い時刻で上書きしうる。既定値なら、列ができた瞬間の行だけが埋まる。
--
-- ## 新しい行は、発行の口が必ず時刻を書く
--
-- **既定値 0 は新しい行にも効く。** 時刻を書き忘れた INSERT は「十分に古い発行」になり、
-- **その 1 本は枠を減らさない。** 招待の行を作るのは `issueInvite`（`src/invites.ts`）
-- 1 か所だけで、そこが `issued_at` を必ず書く（`test/invites.test.ts` が発行時刻の記録を
-- 固定する）。**`invites` へ INSERT する経路を足すときは、この列を書くこと。**
--
-- 既定値を持たない形（`NOT NULL` だけ）は SQLite の `ADD COLUMN` では作れない。表を作り直せば
-- 作れるが、そのために `invites`（`users.invited_by` の系統と一体の表）を作り直す形にしない。
--
-- **CHECK（`issued_at > 0` など）は張らない。** 既存の行を 0 で埋める以上、張れない。
--
-- ## 索引は足さない
--
-- 残高の計算は「その人の発行時刻の並び」を引く（`where issued_by = ?`）。0001 の
-- `invites_issued_by_idx` で行は絞れ、1 人の招待は多くても数十行である（8.1）。**並べ替えは
-- アプリ側で行う**ので、`(issued_by, issued_at)` の索引は要らない（0001 の方針——要する
-- 問い合わせが来るまで張らない）。
--
-- ## 連番が 0034 である理由
--
-- 着手時に空いている最小の番号である。**`0032` は #379（`user_profile`）、`0033` は #376
-- （`games_tags`）が取った**（どちらも M12。別セッションと番号を確かめ合った。2026-09-13）。

ALTER TABLE invites ADD COLUMN issued_at INTEGER NOT NULL DEFAULT 0;
