/**
 * ソースサイズ上限（**64KB**。#284 で 30KB から引き上げた）の境界と、そこでの
 * 振る舞いの判定（確定18 / 5.3 / 6.1 / M5-2 / #33）。
 *
 * # なぜ判定を独立したモジュールにするのか
 *
 * **上限そのものは `src/system-prompt.ts` の `MAX_SOURCE_BYTES` が正本である**
 * （6.1 がプロンプトへ数値を書き込むので、値はあそこに在るのが自然である）。
 * ここが持つのは**値ではなく境界の読み方**——「何バイトから警告するか」「超過を
 * どう数えるか」「作者の同意が要るのはどの帯か」——であり、値と読み方は別々に変わる。
 *
 * 読み方が 2 か所に散ると、片方だけが `>` と `>=` を取り違えたときに**どちらも
 * 落ちない**（shared-ai-rules 12 章）。実際 `src/source-store.ts` は同じ比較を 2 回
 * 書いており、そこもこのモジュールへ寄せた。
 *
 * # 確定18 の 4 条件
 *
 * 5.3 は上限超過時に「作者の選択で LLM に整理させる」と定め、4 条件を課している。
 *
 * | # | 条件 | どこ |
 * |---|---|---|
 * | 1 | 上限の 80%（**64KB の 80% ＝ 52,428 バイト**。#284 まで 24KB）を超えていたら**入力段階で事前警告する** | {@link decideForkSizeAction} の `warn`（#255） |
 * | 2 | 整理は自動実行せず**作者が明示的に選ぶ** | {@link decideForkSizeAction} の `offer-tidy` / `tidy`（`src/fork.ts` が画面にする） |
 * | 3 | **整理は 1 回まで。** 整理後も超えたら拒否 | `src/source-inspection.ts` の生成後サイズ検査（**検査段の拒否は 5.2-5 と同じくリトライへ回らない**） |
 * | 4 | 整理パスのコンパイル失敗で**自動リトライしない。元へ戻して拒否** | {@link TIDY_ATTEMPTS}（`src/generate.ts` が試行の上限にする） |
 *
 * ## 整理パスは、この 2 つを開けて初めて通った（#33）
 *
 * 1. **エッジは Bedrock を呼べない**（`BEDROCK_AWS_*` は #160 で削除済み）。整理は
 *    全文再出力の LLM 呼び出しなので、**オーケストレータ Lambda の中でしか走らない。**
 * 2. **オーケストレータへ渡す本文が、上限超のソースを断っていた。** 上限を守るための
 *    検査が、5.3 が定めた逃げ道の入口をふさいでいた。**整理パスに限って**開けたのが
 *    `src/orchestrator/payload.ts` の版 3 である。**無条件には緩めない**——緩めると
 *    上限そのものが消える。
 *
 * # 拒否だけにしてはいけない（5.3 の意図）
 *
 * 5.3 は「拒否のみは採らない」理由を、10.3 の撤退条件（「3 世代以上の系統が 1 本も
 * 出ていない」）に置いている。**システムが構造的に世代数を制限すると、自分で立てた
 * 撤退条件を自分の実装で不成立にしうる。** したがって条件 1 の事前警告は
 * 「フォークをやめさせる」ためのものではない——**枠を余分に使う可能性を、使う前に
 * 知らせる**ためのものである。文言と選択肢を作るときにここを取り違えないこと。
 */
import { MAX_SOURCE_BYTES } from './system-prompt.js';

export { MAX_SOURCE_BYTES };

/**
 * 事前警告を出す割合（確定18 の条件 1）。
 *
 * **5.3 が「上限の 80%」と、値と導出の両方を書いている。** 値を直接書かず割合から
 * 導くのは、上限が動いた日に警告だけが取り残されないためである
 * （`test/source-size.test.ts` が現在値と一致することを見る）。
 *
 * **#284 でその「上限が動いた日」が実際に来た**（30KB → 64KB）。導出があったので
 * この定数は 1 文字も変わらず、閾値は 24,576 → **52,428** バイトへ自動で追随した。
 */
export const SOURCE_SIZE_WARNING_RATIO = 0.8;

/**
 * 上限から事前警告の閾値を導く。
 *
 * **切り下げる。** バイト数は整数であり、しかも**作者の画面へそのまま出る値**である
 * （`src/fork.ts` の警告画面）。`* 0.8` は二進小数なので、上限によっては
 * `25395.2` のような端数を作る——30,720 では割り切れていたが、**上限が動いた日に
 * 画面へ小数が出る**（#255 のレビュー指摘。指摘そのものは正しく、ただし挙げられた
 * 例（当時の現在値が端数になる）は外れていた）。
 *
 * **#284 でその日が来た。** 65,536 × 0.8 は二進小数で 52,428.800000000003 になり、
 * **切り下げが実際に効いている**（52,428）。指摘は現在値で正しくなった。
 *
 * **端数は警告を早める側へ倒す。** 条件 1 は「知らせる」ためのもので、1 バイト早く
 * 知らせても失うものが無い。
 *
 * @param limitBytes 上限のバイト数
 * @returns 警告を始めるバイト数（**これを超えたら**警告する）
 */
export function warningBytesFor(limitBytes: number): number {
  return Math.floor(limitBytes * SOURCE_SIZE_WARNING_RATIO);
}

/** 事前警告を出すバイト数（**これを超えたら**警告する。**52,428**＝上限の 80%）。 */
export const SOURCE_SIZE_WARNING_BYTES = warningBytesFor(MAX_SOURCE_BYTES);

/**
 * ソースのバイト数を測る。
 *
 * **文字数ではなくバイト数である。** 上限の出どころ（6.1 のプロンプト、
 * `src/orchestrator/payload.ts` のペイロード上限）がどちらもバイトで、日本語の
 * コメントが入ると 1 文字 3 バイトになる。
 *
 * @param source Go のソース
 * @returns UTF-8 でのバイト数
 */
export function measureSourceBytes(source: string): number {
  return new TextEncoder().encode(source).length;
}

/**
 * サイズの帯。
 *
 * - `within` … 52,428 バイト以下。何も言わない
 * - `near-limit` … 52,428 バイト超 64KB 以下。**改造はできるが、事前警告する**（条件 1）
 * - `over-limit` … 64KB 超。**そのままでは改造できない**
 */
export type SourceSizeVerdict = 'within' | 'near-limit' | 'over-limit';

/**
 * バイト数を帯へ落とす。
 *
 * **境界はどちらも「超えたら」である**（`>`。`>=` ではない）。5.3 は上限を
 * 「上限以内に収める」、警告を「上限の 80% を超えていたら」と書いており、**ちょうどの
 * 値はどちらも収まっている側**である。`src/source-store.ts` が上限ちょうどのソースを
 * 読むこと（`test/source-store.test.ts`）と、同じ 1 つの判断になる。
 *
 * @param bytes 測ったバイト数
 * @returns 帯
 */
export function classifySourceBytes(bytes: number): SourceSizeVerdict {
  if (bytes > MAX_SOURCE_BYTES) {
    return 'over-limit';
  }
  if (bytes > SOURCE_SIZE_WARNING_BYTES) {
    return 'near-limit';
  }
  return 'within';
}

/**
 * 整理パスが入力として受け取れる最大バイト数（上限の 2 倍）。
 *
 * **無条件に上限を外さない**ための天井である。理由は 2 つある。
 *
 * 1. **「整理」ではなくなる。** 上限の 2 倍を超えるソースを上限へ収めるには半分以上を
 *    捨てることになり、それは整理ではなく作り直しである。5.3 が「整理でゲームの挙動が
 *    変わるリスクは機械検証できない」と認めたうえで作者を唯一のフィルタに据えている
 *    以上、**フィルタが働く見込みのある範囲に留める。**
 * 2. **入力費用と、運ぶ本文の大きさ。** 非同期呼び出しのペイロード上限は 256 KB。
 *    **#284 で 2 倍が 60 KB から 128 KB になり、ここの余裕は目に見えて減った**——
 *    プロンプト（最大 8 KB）を足して 136 KB で、**「桁が 1 つ違う」とはもう言えない**
 *    （残り約 120 KB。JSON の改行エスケープぶんも食う）。**次に上限を上げるときは、
 *    この 2 倍という導出そのものを見直すこと。** 費用の側でも、128 KB は実測
 *    2.0 バイト/token で約 64,000 トークンとなり、キャッシュ書き込みだけで 36 円ほどに
 *    なる（**見積もりであって実測ではない。** 4.2 / 1.2.43 から逆算した単価による）。
 */
export const TIDY_MAX_SOURCE_BYTES = MAX_SOURCE_BYTES * 2;

/**
 * 作者が事前警告に対して示した同意（確定18 の条件 1・2）。
 *
 * - `none` … まだ何も示していない（最初の要求）
 * - `proceed` … 警告を読んだうえで「このまま改造する」を選んだ（条件 1）
 * - `tidy` … 上限超の親に対して「整理して続ける」を選んだ（**条件 2**）
 *
 * **`proceed` と `tidy` を 1 つに畳まない。** 前者は枠を 1 回、後者は枠を 1 回使ったうえで
 * **ソースが作者の知らないうちに書き換わる**（5.3 は「整理したことは作者に開示する」と
 * 定めている）。同じ値にすると、警告の画面で押した「このまま改造する」が、別の帯では
 * 整理への同意として読まれる。
 */
export type SizeConsent = 'none' | 'proceed' | 'tidy';

/**
 * フォークの入力段階での振る舞い（確定18 の条件 1・2）。
 *
 * - `proceed` … そのまま改造してよい
 * - `warn` … **事前警告して、作者の同意を取る**（条件 1。枠はまだ使わない）
 * - `offer-tidy` … 上限超。**整理するかどうかを作者に問う**（条件 2。枠はまだ使わない）
 * - `tidy` … 作者が整理を選んだ。**整理パスで改造を始める**（枠を 1 回使う）
 * - `refuse` … 整理しても収まる見込みが無い。断る
 */
export type ForkSizeAction = 'proceed' | 'warn' | 'offer-tidy' | 'tidy' | 'refuse';

/**
 * 親ソースの大きさから、フォークの入力段階の振る舞いを決める（確定18 の条件 1）。
 *
 * **帯ごとに、効く同意が違う。**
 *
 * | 帯 | 同意なし | `proceed` | `tidy` |
 * |---|---|---|---|
 * | `within` | `proceed` | `proceed` | `proceed` |
 * | `near-limit` | **`warn`**（条件 1） | `proceed` | `proceed` |
 * | `over-limit` | **`offer-tidy`**（条件 2） | **`offer-tidy`** | **`tidy`** |
 * | 整理の上限超 | `refuse` | `refuse` | `refuse` |
 *
 * **`over-limit` で `proceed` を `tidy` として読まない。** 条件 2 は「作者が明示的に
 * 選ぶ」ことを求めており、事前警告（条件 1）で押した「このまま改造する」を整理への
 * 同意として流用すると、**作者が押していない操作で枠が減り、ソースが書き換わる。**
 *
 * **整理しても収まる見込みが無い大きさは断る**（{@link TIDY_MAX_SOURCE_BYTES}）。
 * 問うだけ問って必ず失敗する選択肢を出すと、条件 2 が守ろうとした「知らないうちに
 * 枠を使わせない」が、知ったうえで確実に捨てさせる形へ裏返る。
 *
 * **警告も問いも 1 度でよい。** 同意を持って戻ってきた要求を再び止めると、作者は
 * 同じ画面を往復するだけで先へ進めない。
 *
 * @param input 測ったバイト数と、作者が示した同意
 * @returns 入力段階の振る舞い
 */
export function decideForkSizeAction(input: {
  readonly bytes: number;
  readonly consent: SizeConsent;
}): ForkSizeAction {
  if (input.bytes > TIDY_MAX_SOURCE_BYTES) {
    return 'refuse';
  }
  const verdict = classifySourceBytes(input.bytes);
  if (verdict === 'over-limit') {
    return input.consent === 'tidy' ? 'tidy' : 'offer-tidy';
  }
  if (verdict === 'near-limit' && input.consent === 'none') {
    return 'warn';
  }
  return 'proceed';
}

/**
 * 1 回の整理パスで許す LLM 呼び出しの回数（**確定18 の条件 3・4**）。
 *
 * **1 である。** 条件 3 は「整理は 1 回まで」、条件 4 は「整理パスがコンパイルに失敗しても
 * 自動リトライしない」と定める。どちらも**同じ 1 つの数**に落ちる——5.2-7 の
 * `MAX_GENERATION_ATTEMPTS`（#284 以降は 2）をこの経路にだけ 1 へ差し替えれば、
 * 両方が同時に成り立つ。
 *
 * **理由は費用である。** 条件 4 の理由欄が「リトライが乗ると枠を余分に消費する
 * （#284 まで最悪 3 回分、いまは 2 回分）。失敗の連鎖を切る」と書いている。整理パスは入力も出力も通常の生成より大きく、
 * **1 回あたりの見積もりが 26〜41 円**（`docs/product-spec.md` 5.3 の #33 注記。
 * **上限が 64KB になった分、この帯も上がる**）なので、複数回に回すと 1 度の操作で
 * 100 円前後を失う。
 */
export const TIDY_ATTEMPTS = 1;

/**
 * この生成が整理パスかどうかを判定する（確定18）。
 *
 * # なぜ項目ではなく大きさで見分けるのか
 *
 * **整理パスの定義そのものが「元ソースが上限を超えていること」だからである**
 * （5.3 の見出しは「上限を超えたときの挙動」であって、作者が押したボタンの名前では
 * ない）。作者の同意は**その経路へ入ってよいかの許可**であり、`src/fork.ts` と
 * `src/orchestrator/payload.ts` の版 3 が二重に持っている。ここが決めるのは
 * **入ったあとの振る舞い**なので、条件そのものを見る。
 *
 * **項目で運べない事情もある。** 非同期経路では `src/orchestrator/handler.ts` が
 * ペイロードから `GenerationJob` を組み直しており（本 issue の所有外）、そこを通らない
 * 項目は**エッジでは効いてオーケストレータでは黙って消える。** 消えたことに気づける
 * 検査が無い項目を作るより、**両側で同じ 1 つの事実を測る**ほうが壊れにくい
 * （所有を足せるなら明示の項目のほうがよい。#33 の報告に書いた）。
 *
 * @param request 生成のリクエスト
 * @returns 整理パスなら true
 */
export function isTidyPass(request: { readonly baseSource?: string }): boolean {
  return (
    request.baseSource !== undefined &&
    classifySourceBytes(measureSourceBytes(request.baseSource)) === 'over-limit'
  );
}

/**
 * 整理パスの指示を、利用者のプロンプトへ織り込む（5.3「LLM に整理させる」）。
 *
 * **利用者のプロンプトを消さない。** 何を作るのかは変わらず、足すのは「元が上限を
 * 超えているので、収まるように整理してから直す」ことだけである。差し替えると、
 * 収まっても別のゲームができる（`src/build-retry.ts` の `composeRetryPrompt` と同じ判断）。
 *
 * **台帳へは織り込む前のプロンプトが残る。** 呼ぶ側（`src/generate.ts` の
 * `withTidyInstruction`）が包み層の中だけで差し替えるので、`generations.prompt`（5.1）は
 * 利用者の入力のままである。
 *
 * **システムプロンプト（6.1）は触らない。** 4.5 の区切りは `system` の末尾にあり、
 * ここが変えるのは `messages` 側だけなので、**整理パスでもプレフィックスのキャッシュは
 * そのまま効く。**
 *
 * @param prompt 利用者が入力した差分プロンプト
 * @param bytes 元ソースの実際のバイト数
 * @returns 整理パスへ送るプロンプト
 */
export function composeTidyPrompt(prompt: string, bytes: number): string {
  return [
    prompt,
    '',
    `元のソースは ${bytes} バイトあり、上限の ${MAX_SOURCE_BYTES} バイトを超えています。`,
    `上の指示を反映したうえで、全体を ${MAX_SOURCE_BYTES} バイト以内に収めてください。`,
    '収めるために、重なっている処理を 1 つにまとめ、使っていない変数と関数を削り、',
    '長い初期化データは計算で作れる形へ置き換えます。',
    'それでも収まらないときは、遊びの中心から遠い要素のほうを削ります。',
    '遊べる状態（操作でき、得点か勝敗がある）は必ず保ちます。',
  ].join('\n');
}
