-- **仮想パッドで、すでにボタンに出るキーと同じ働きの方向をボタンに出さないための土台である。** 例: ピヨピヨジャンプは
-- `inpututil.IsKeyJustPressed(ebiten.KeySpace) || inpututil.IsKeyJustPressed(ebiten.KeyUp) || …` で跳ぶので、Space の
-- ボタンがあれば ↑ のボタンは要らない。一方、ケロケロ舌合戦の ↑↓ は Space と別の条件式で読む（上段・下段）ので残す。
-- **同じ働きかどうかは条件式を見ないと分からない**ので、ソースから組を拾って保存する。
