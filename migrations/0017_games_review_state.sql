-- 通報が閾値に達した作品を審査待ちにする（8.4 / #40）。
--
-- ## なぜ列が要るのか
--
-- 8.4 は「**閾値到達時は『自動非表示』ではなく『審査キューへ投入』**」と定める。
-- **投入されたことと、審査が済んだことを、通報の件数からは区別できない。**
-- 件数だけで判定すると、**一度見て問題無しとした作品が、通報が消えない限り永遠に
-- キューへ居座る。**
--
-- ## 新規露出だけを止める
--
-- 8.4 は「代替として、**新規露出のみ停止し既存 URL は生かす**運用も可」としている。
-- `status` を動かさないのはそのためである——`published` のままなら
-- `/g/<game_id>/` は生き、共有済みの URL が切れない。**止まるのは 5.5 の
-- 「このゲームからの改造」の一覧に出ることだけ**である。
--
-- **`status='removed'`（tombstone）とは別物である。** あちらは作者が取り下げた状態で
-- （M5-4）、こちらは運用が保留した状態である。混ぜると「誰が決めたのか」が消える。
--
-- ## 値
--
--   NULL      … 通報の閾値に達していない（既定。**大多数の行がこれである**）
--   'queued'  … 審査待ち。新規露出を止める
--   'cleared' … 見た結果、問題なし。露出を戻す。**再び閾値に達しても戻さない**
--                （同じ通報で何度もキューへ戻ると、審査が終わらない）
--
-- **'removed' をここに置かない。** 運用が消すと決めたときは `status` を動かす
-- （`src/work-page.ts` の取り下げと同じ経路）。**状態を 2 か所で持たない。**
--
-- ## 索引を張らない
--
-- 索引は 1 行の insert につき 1 行の書き込みを足す（3.6）。**この列は生成のたびに
-- 書かれる**（`insertPendingGame` が NULL を入れる）ので、索引はそのまま生成 1 回
-- あたりの費用になる。読むのは審査キューの一覧（運用が数日に 1 度叩く）と、
-- 5.5 の子の一覧である。**全走査で足りる規模でしか呼ばれない。**

