-- `effort` の A/B 計測（4.2 / M3-4 / #25）が要る 1 列。
--
-- ## なぜ列が要るのか
--
-- #25 の受け入れ条件は「**`effort` の割り当てと結果が費用台帳から追える**」ことである。
-- 群そのものは `generations.model` にも入る（群は登録簿の要素として表しており、
-- `sonnet-4-6-high` / `sonnet-4-6-medium` が鍵になる。`src/generation-models.ts` の
-- `EFFORT_AB_ARMS`）。それでもこの列を足すのは、次の 2 つのためである。
--
--   1. **集計が鍵の綴りを解釈しなくてよい。** `model like '%-high'` で群を数える形に
--      すると、鍵の綴りを変えた日に集計だけが黙って空振りする（引き継ぎ 4 章
--      「綴りを絞った検査は、対象の綴りが変わった日に黙って空振りする」）。
--   2. **登録簿を後から動かしても、過去の行の意味が変わらない。** 実際に送った値を
--      行に焼き付けておけば、`sonnet-4-6-high` の `effort` を将来 `max` へ直しても、
--      A/B のときに測った行は `high` のままである。集計時に登録簿を引き直す形だと、
--      **過去の測定結果が後の設定変更で書き換わる。**
--
--
-- ## 3 つの状態を区別する
--
-- | 値 | 意味 |
-- |---|---|
-- | `NULL` | **この行は `effort` を記録していない**（このマイグレーションより前の行） |
-- | `'none'` | 記録した結果、**送っていなかった**（登録簿の `effort: null`） |
-- | `'low'` / `'medium'` / `'high'` / `'max'` | その値を送った |
--
-- **`NULL` と `'none'` を混ぜない。** 混ぜると、A/B の集計が「古い行」と「対照群」を
-- 同じものとして数える。4.1 のキャッシュ単価を `0` ではなく `null` にしているのと
-- 同じ線である（`src/generation-models.ts` の `EFFORT_NOT_SENT`）。
--
-- **既存の行が `NULL` になるのは、既定値の都合ではなく事実として正しい。** ただし
-- **0007 / 0009 の `DEFAULT 0` とは事情が違う**——あちらは「1 度も推敲されていない」
-- という**確かな事実**を 0 で表せたが、こちらは「送ったかどうかを記録していなかった」
-- ので、断定できる値が無い。**分からないものを `'none'` で埋めない。**
--
-- **したがって A/B の集計は、必ず時刻の窓で絞ること**（`src/cost-ledger.ts` の
-- `effortExperimentTotals` は窓を必須の引数にしてある）。窓をこのマイグレーションの
-- 適用より後に取れば、`NULL` の行は 1 つも入らない。
--
-- **既存の行がこの経路を通っていないことを疑う**のは #202 / #203 の教訓である
-- （「実装より前に完成した行は、その実装の経路を 1 度も通っていない」）。ここでは
-- 埋め戻しをしない代わりに、集計側が窓で締め出す。
--
--
-- ## CHECK 制約を書かない
--
-- 取りうる値は `src/generation-models.ts` の `GenerationEffort` が持っている。
-- ここへ書き写すと、値を足した日に片方だけが古くなる（shared-ai-rules 12 章）。
-- 書き込みは `src/cost-ledger.ts` の 1 か所だけで、そこは登録簿から値を引いている。
-- **綴りが登録簿の外へ出ないことは `test/cost-ledger.test.ts` が確かめる。**
--
--
-- ## 索引を張らない
--
-- 索引は 1 行の insert につき 1 行の書き込みを足す（3.6 / 0010）。この列を読むのは
-- **A/B の集計のときだけ**で、しかも窓で絞ったあとの数十〜数百行である。
-- 「将来使うかもしれない」で足さない（0001 の方針）。
--
--
-- ## 連番が 0011 である理由
--
-- `0009` が 2 つある（`0009_game_revisions.sql` と `0009_games_ogp.sql`）。
-- **リネームしてはいけない。** D1 は適用済みの一覧をファイル名で持つため、改名すると
-- 未適用と判定して流し直し、本番で落ちる。**番号は衝突したまま残し、次を 0011 に
-- するのが正しい始末である**（引き継ぎ 3 章）。
ALTER TABLE generations ADD COLUMN effort TEXT;
