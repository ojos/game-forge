-- 作者が書く作品の説明と、その変更の履歴（5.4 / 5.6 / 8.4 / #388）。
--
-- ## なぜ説明が要るのか
--
-- **作品ページに、作者が書いた文章が 1 文字も無かった。** 出ているのは題名（40 字）・
-- 作者名・系統・いいね数・スクリーンショットだけで、5.6 が「クレジットを尊重する」と
-- 定めているのに、**クレジットを書く欄が無い**（#388 の背景）。
--
-- **公開時には入力させない**（5.4 の 1 タップの導線は変えない）。#366 が題名を公開後に
-- 変えられるようにしたのと同じ形で、**公開後に作品ページから書く**（`src/games.ts` の
-- `describeGame`）。
--
-- ## `games.description` は NOT NULL で、空文字が「説明が無い」である
--
-- **「無い」の表し方を 1 つにする。** NULL と空文字の両方を許すと、画面と SQL の
-- どちらもが 2 通りを見分けることになり、片方だけを見た経路が生まれる。作者が説明を
-- 消す操作も「空文字を書く」1 つで済む。既存の行は `DEFAULT ''` で埋まるので、
-- **埋め戻しは要らない。**
--
-- **長さの CHECK は張らない。** 上限（`src/games.ts` の `MAX_DESCRIPTION_LENGTH`）を
-- 変えるたびに、SQLite では **`games` の作り直し**が要る（列の CHECK を後から変える
-- `ALTER` が無い）。`games` は最も大きく、最も多くの経路が読む表であり、上限の見直しの
-- ためにそれを作り直す形にしない。長さを守るのは口（`describeGame`）1 か所である。
--
-- ## `games.description_set_at` を足す（変更の間隔を 1 本の WHERE で見るため）
--
-- **頻度の上限は表示名と同じ考え方で置く**（5.9 の `display_name_set_at` / 3.6）。
-- 断った要求は 1 行も書かない——間隔の判定を UPDATE の WHERE に置く。
--
-- **履歴の表から最後の時刻を引く形にしない。** 説明と履歴は 1 つの batch で「履歴が先、
-- UPDATE が後」に書く（`renameGame` と同じ順序。旧値は UPDATE の前の行からしか取れない）。
-- **UPDATE の側で `not exists (select … from description_changes …)` を見ると、同じ batch で
-- 直前に積んだ履歴の行に当たり、UPDATE が必ず 0 行になる。** 時刻を `games` の行に持てば、
-- 2 文の WHERE がどちらも「batch の前の行」を見る。NULL は「1 度も書いていない」である。
--
-- ## 履歴は追記のみ（0026 / 0027 と同じ規律）
--
-- **更新も削除もしない。** アプリにこの表を UPDATE / DELETE する経路を 1 つも作らない
-- （`describeGame` が書くのは `insert` だけである）。保証できるのは口までで、表の側では
-- 止められない——資格情報を持つ人は `wrangler d1 execute` で消せる（0026 と同じ但し書き）。
--
-- **説明と履歴は 1 つの `D1.batch` で書く。** 履歴の insert が落ちれば batch ごと巻き戻り、
-- **説明も変わらない**（履歴の無い変更を作らない。#361 / #366 の規律）。
--
-- ## 審査との関係は #366 に揃える
--
-- **説明の変更も「穏当な説明で公開 → 通報 → `cleared` → 説明を書き換え」を成立させる。**
-- そこで `describeGame` は改名と同じく `review_state` を `nullif(review_state, 'cleared')` で
-- 戻す（`queued` にはしない——善意の変更で作品がトップから消える）。**審査の列そのものは
-- この migration では触らない。**
--
-- ## 作品と同じ寿命（確定26 / 3.7 の削除規約）
--
-- **`games` の行が消えるときは、この表の行も一緒に消す**（0027 と同じ）。いまの実装に
-- `games` を物理削除する経路は無いので、平常はこの表の行も消えない。**`on delete cascade`
-- は書かない**（発火しない宣言は「消えるはず」という誤読だけを残す。0009 / 0027）。
-- 外部キーは張る——`describeGame` は `games` を引いて書くので、実在しない id が入る経路が無い。
--
-- ## `id` を主キーにする（`(game_id, changed_at)` にしない）
--
-- 0027 と同じ理由である。**複合主キーにすると、同じ秒の 2 度目が一意制約で落ちて batch
-- ごと巻き戻る**——履歴の都合で作者の正当な操作を断る形になる。いまは間隔の上限が
-- 同じ秒の 2 度目を先に断るが、**間隔を 0 にした日に黙って効き始める制約**を置かない。
--
-- ## 索引を張る
--
-- **0027 と同じ形にそろえる**（`(game_id, changed_at)`）。「その作品の最後の変更」を引く
-- 相関副問い合わせ（審査の条件。#394 が `src/reports.ts` で扱う）を足した日に、候補 1 件
-- ごとの全走査にならないようにする。**書き込みの増分は説明の変更 1 回につき 1 行**で、
-- 変更は間隔の上限で縛られている（3.6）。
--
-- ## 説明そのものを持つ（UGC である）
--
-- **旧い説明と新しい説明の両方を持つ。** 片方だけでは「何がどう変わったか」が復元できず、
-- 8.4 の「記録を残す」に足りない。**どちらも UGC なので、画面へ出すときは `escapeHtml` を
-- 通すこと。** 改訂履歴を利用者に見せる画面は作らない（#388 の scope.out）。
--
-- **`new_description` に「空ではない」の CHECK を張らない。** 0027 の `new_title` と違い、
-- **説明を消す（空文字にする）のは正当な操作である。**
--
-- ## CHECK は時刻の 1 つだけ
--
-- **`changed_at` は 0 より大きい**（0027 と同じ理由——0 は「時計が読めなかった」形で、
-- 「最後の変更」を引く条件に 1970 年の変更として混ざる）。
--
-- **この CHECK は、説明と履歴が 1 つの batch であることの検査にも使っている**
-- （`test/work-description.test.ts` が `now = 0` で `describeGame` を呼び、**batch ごと
-- 巻き戻って説明も変わらない**ことを見る。0027 と同じ使い方）。
--
-- ## 連番が 0028 である理由
--
-- 着手時に空いている最小の番号である。**`0027` は #366（`title_changes`）が使用済み**で、
-- 適用済みの番号へ後から足せない。issue #388 の本文が 0028 を割り当てている。

ALTER TABLE games ADD COLUMN description TEXT NOT NULL DEFAULT '';

-- 作者が最後に説明を変えた時刻（UNIX 秒。0001 の方針）。NULL なら 1 度も変えていない。
ALTER TABLE games ADD COLUMN description_set_at INTEGER;

CREATE TABLE description_changes (
  id TEXT PRIMARY KEY,
  -- 説明を変えられた作品。**実在する作品しか入らない**（上記）。
  game_id TEXT NOT NULL REFERENCES games(id),
  -- 変える前の説明（UGC）。空文字なら、それまで説明が無かった。
  old_description TEXT NOT NULL,
  -- 変えた後の説明（UGC）。**空文字は入りうる**（説明を消す操作。上記）。
  new_description TEXT NOT NULL,
  -- 変えた時刻（UNIX 秒）。**0 以下は入らない**（上記）。
  changed_at INTEGER NOT NULL CHECK (changed_at > 0)
);

-- 「その作品の最後の説明の変更はいつか」を引くための索引（0027 と同じ並び）。
CREATE INDEX description_changes_game_changed_idx ON description_changes (game_id, changed_at);
