  /** 「さかのぼって見られない」とは言わない。 */
  neverSayCannotLookBack: '「前のやりとりをさかのぼって見られない」とは言いません。',
  /** 下書きに無いことが話題に出たら、聞き直す前に下書きへ入れて確かめる。 */
  foldIntoDraftBeforeAsking: '下書きに無いことが話題に出たら、聞き直す前に、まずそれを下書きへ入れて「これで合っていますか」と確かめます。',
