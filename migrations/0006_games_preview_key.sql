-- 作者プレビュー用の推測不能なキーを `games` へ足す（5.4 / 7.2 / #28）。
--
-- **これは #27（M4-2）の権限制御の答えでもある。**
--
-- 5.4 は「生成直後は `status='draft'`。作者だけがプレビューできる」と定め、その手段を
-- 2 つ挙げている。(a) Workers 経由で所有者チェックしてから R2 から返す、
-- (b) 推測不能なランダムキーによる unlisted 配信。**MVP は (b) を採る。**
--
-- **(a) が原理的に成立しないためである。** 7.2 の必須要件 1 により、サンドボックス用
-- ホストの配信レスポンスには `Content-Security-Policy: sandbox allow-scripts` が付く。
-- この文書は**不透明オリジン**になり、cookie を一切持たない。すなわち
-- **セッション cookie による所有者確認が、この経路には届かない。**
-- `allow-same-origin` を足せば cookie は戻るが、それは 7.2 が「絶対に付けない」と
-- 定めたものであり、付けた瞬間に UGC が同一サイトの実オリジンで動く（7.2 の危険性の表）。
--
-- したがって「所有者チェック」を成立させるには、プレビューだけをアプリ用ホストから
-- 配信する（＝ UGC を親オリジンへ持ち込む）しかなく、7.2 の一番外側の要件（別オリジン）を
-- 破ることになる。**unlisted キーは妥協ではなく、7.2 と両立する唯一の形である。**
--
-- ## NOT NULL にしない理由
--
-- SQLite は既定値なしの NOT NULL 列を ALTER TABLE ADD COLUMN で足せない。既定値を
-- 与えれば足せるが、**このキーは行ごとに違う乱数でなければ意味がない**ため、定数の
-- 既定値は置けない。テーブルを作り直す道もあるが、`games` は自己参照（parent_id）と
-- `generations` / `reports` からの外部キーを持ち、再構築の手順のほうが危険が大きい。
--
-- **アプリ側は必ず書く**（`src/games.ts` の `createDraftGame`）。列としての NULL 許容は、
-- 既に存在する行のためだけに開いている。
--
-- ## 既存行を埋め戻さない理由
--
-- 埋め戻しには行ごとの乱数が要る。SQL の `randomblob()` に頼る手はあるが、D1 は一部の
-- 組み込み関数を認可しない（実測: `sqlite_version()` が拒否される）ため、マイグレーションの
-- 成否が D1 の認可設定に依存する形になる。
--
-- **埋め戻さなくても失われる機能が無い。** プレビュー URL が要るのは `draft` の行だけで、
-- 未公開のまま 14 日で自動削除される（3.7 / 確定13）。`published` の行は
-- `/g/<game_id>/` で配信されるため、このキーを使わない。
--
-- ## 一意索引にする理由
--
-- 衝突すれば別人の未公開作品が引ける。128 ビットの乱数で衝突は現実には起きないが、
-- **「起きない」ことを鍵の性質だけに預けない。** 索引は同時に、配信経路の
-- 「このキーの作品はどれか」という問い合わせ（`src/sandbox-delivery.ts`）を
-- 全走査から救う。0004 と同じく、**必要とする問い合わせが決まっているから張る。**
--
-- SQLite の UNIQUE 索引は NULL を重複と見なさないため、上記の「既存行は NULL のまま」と
-- 両立する。
ALTER TABLE games ADD COLUMN preview_key TEXT;

CREATE UNIQUE INDEX games_preview_key_idx ON games(preview_key);
