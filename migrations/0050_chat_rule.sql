-- ## なぜ `users` の列なのか（別表にしない）
--
-- **1 人につき高々 1 つで、履歴を持たない値である。** 表示名・自己紹介・外部リンクと同じ形なので、
-- 同じ行に置く。別表にすると、**読むたびに join が 1 つ増える**（相談は 1 往復ごとにこの値を読む）。
--
-- **履歴を持たないのは、これが公開面に出ない値だからである。** 表示名と自己紹介は
-- `display_name_changes` / `profile_changes` に古い値を積む——**作者ページに出る値で、運営が
-- 「いつ何に変えたか」を辿れる必要がある**（8.4 の措置の根拠になる）。**相談のルールは作者本人に
-- しか効かず、誰の目にも触れない**ので、積む理由がない。
--
-- ## 既定は空文字（NULL にしない）
--
-- `bio` と同じ扱いである。**「まだ書いていない」と「空にした」を分ける必要が無い**値なので、
-- 3 つ目の状態を作らない——読む側（`src/chat-rule.ts`）が `is null or = ''` を書き忘れると、
-- **空のルールが 1 往復ぶんの文脈として送られる。**
--
-- ## 退会で消える
--
-- **段3 の 15 文目（`users` の匿名化）に 1 語足して消す**（`src/withdrawal.ts`）。文の数は変わらない。
-- **`/privacy` の「退会したときは削除します」の対象である。**
alter table users add column chat_rule text not null default '';
