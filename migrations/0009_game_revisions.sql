-- 推敲（自作 draft の作り直し）が要る 2 つの器（5.7 / 確定28 / #192）。
--
-- 5.7 は 2 つのことを要求している。**版をすべて残して任意の版へ戻せること**と、
-- **1 作品あたりの推敲回数に上限があること**である。前者は表、後者は列で持つ。
--
--
-- ## なぜ版を `games` の列で持たないのか
--
-- 「一つ前の版」だけなら列 3 本（`prev_source_key` / `prev_wasm_key` /
-- `prev_go_version`）で足りる。**5.7 が全版を要求しているので足りない。**
-- 上限が 3 回でも版は最大 4 つあり、列で持つと本数が上限に張り付く。
-- **上限は 10.2 の観測で見直す暫定値**（5.7）であり、**その値を上げるたびに
-- マイグレーションが要る形にしない。**
--
--
-- ## `seq` は表の中で採る
--
-- `(game_id, seq)` を主キーにし、`seq` は 1 から始めて 1 ずつ増やす。**時刻で
-- 並べない。** `created_at` は UNIX 秒（5.1）なので、同じ秒に 2 行入ると順序が
-- 決まらない。推敲は 1 回 90 秒かかるので現実には起こらないが、**「起こらないはず」で
-- 順序を決めない**（3.7 の隙間を「消えた作品」に見せない、と同じ線）。
--
--
-- ## 初回の生成も 1 版である
--
-- **`seq = 1` は推敲ではなく最初の生成が積む。** ここを推敲だけの表にすると、
-- 「最初の状態へ戻す」が表現できない。5.7 が「完成のたびに版を 1 つ積む」と
-- 書いているのはこの意味である。**したがって推敲の回数は版の数から引き算しない**
-- （下の `revise_count` を参照）。
--
--
-- ## `source_key` / `wasm_key` に外部キーを張らない
--
-- 張る先が無い。R2 のキーは D1 の表ではない。**確定26 のとおり、これらは作品を
-- またいで共有される**（同一ソースの作品は同じ成果物を指す）ので、**この表の行が
-- 増えることは、同じキーを指す参照者が増えることを意味する。**
--
-- **M5-4 のゴミ掃除（#35）はこの表も引かなければならない。** 確定26 の削除規約 ① は
-- 「消す前に `games` を引いて他の作品が参照していないことを確かめる」と書いているが、
-- **参照元は `games` だけではなくなった。** 引かないと、作者が戻すために持っている版の
-- 実体が消え、**戻した瞬間に配信が壊れる**（しかも壊れるのは削除の何日も後である）。
-- 5.7 と確定28 に明記してあり、#35 へも申し送ってある。
--
--
-- ## `prompt` は推敲の版だけが持つ（`seq = 1` は NULL）
--
-- **その版を作った差分プロンプトである。** 版の一覧で「どれがどれか」を作者が
-- 見分けるにはこれしかない。時刻だけでは 90 秒差の 4 行が並ぶだけで選べない。
--
-- **`seq = 1`（初回生成）は NULL であり、それが正常である。** 初回のプロンプトは
-- `games` のどこにも無く、あるのは費用台帳の `generations.prompt`（5.1）だけである。
-- そこは**確定27 により `game_id` を持たない**ので、版から引く経路が無い。
--
-- **プロンプトを 3 か所目へ複製しない。** 初回のプロンプトをここへ入れるには、
-- 作品行かオーケストレータのペイロードのどちらかに持たせて運ぶ必要があり、どちらも
-- 「同じ値の写しが増える」ことを意味する（確定12 が潰して回っている形である）。
-- **版の一覧で `seq = 1` は「最初の生成」と表示すれば、作者は選べる。**
--
--
-- ## 削除の連鎖
--
-- `on delete cascade` を書かない。**`games` の行は物理削除しない**（5.3 の
-- tombstone 化。M5-4）。書いても発火せず、「消えるはず」という誤読だけが残る。

CREATE TABLE game_revisions (
  game_id TEXT NOT NULL REFERENCES games(id),
  -- 1 から始まる版の番号。表の中で採る（上記）。
  seq INTEGER NOT NULL,
  -- その版の成果物。R2 のキーで、作品をまたいで共有されうる（確定26）。
  source_key TEXT NOT NULL,
  wasm_key TEXT NOT NULL,
  -- ビルドに使った Go の版。3.5 の `wasm_exec.js` の出し分けに要る。
  -- 戻したときに `games.go_version` へ書き戻すので、版ごとに持つ。
  go_version TEXT NOT NULL,
  -- その版を作った差分プロンプト。**`seq = 1`（初回生成）は NULL**（上記）。
  prompt TEXT,
  created_at INTEGER NOT NULL,
  PRIMARY KEY (game_id, seq)
);

-- 版の一覧は 1 作品ぶんを新しい順に引く（5.7）。主キーが `(game_id, seq)` なので
-- `where game_id = ? order by seq desc` はこの索引だけで満たせる。**別の索引は張らない。**

-- 走っている推敲のジョブ（5.7 / #192）。
--
-- ## なぜ `games.generation_state` に相乗りしないのか
--
-- **相乗りすると、推敲が失敗した瞬間に、それまで完成していた作品が壊れる。**
-- あの状態機械（0007）は初回生成 1 回きりの前提で、`pending → running → ready/failed`
-- を一方向に進む。推敲でこれを使い回すと `ready` の行を `pending` へ戻すことになり、
-- 失敗すれば `failed` が残る——**作品としては完成しているのに、である。**
--
-- 5.3 は 30KB の整理パスについて「コンパイルに失敗しても**元のソースへ戻して拒否する**」
-- と定めており、5.7 の「押したら作り直しが始まり、**完成したら差し替わる**」も現行版が
-- 生き続けることを含意している。**失敗しても作品は無傷でなければならない。**
--
-- したがって推敲中も `games` は `status='draft'` / `generation_state='ready'` のままで、
-- **0007 の不変条件（`preview_key` が非 NULL であることと `ready` であることは同値）も
-- 1 ミリも動かない。** 作者は推敲を待つあいだ、現行版を遊び続けられる。
--
--
-- ## `game_id` が主キーである
--
-- **1 つの作品に対して同時に走る推敲は 1 本だけ**という制約を、主キーで表現する。
-- 一意制約を別に張るより、行そのものが「いま走っているジョブ」を意味するほうが、
-- 数え直しの経路が生まれない。
--
-- ## 成功したら行を消す
--
-- 状態に `'ready'` を持たない。**成功の記録は `game_revisions` の行**であり、
-- ここに残す意味が無い。消せば次の推敲が同じ主キーを使えるようになる。
-- **失敗は `'failed'` で残す**——作品ページが理由を出せる必要があり、次の推敲は
-- その行を上書きする（UPSERT の `where state = 'failed'`）。
--
-- ## `prompt` を持つ
--
-- 完成したときに `game_revisions.prompt` へ書き写す。ジョブの起動時にしか
-- 差分プロンプトを知る機会が無く、**コールバックは持ってこない**（ペイロードで
-- 送り返させると、トークンを持つ者が版の履歴を偽れる）。
CREATE TABLE game_revision_jobs (
  -- 1 作品につき同時に 1 本（上記）。
  game_id TEXT PRIMARY KEY REFERENCES games(id),
  -- そのジョブだけを進められる使い捨てトークンのハッシュ（`games.job_token_hash` と同じ扱い）。
  job_token_hash TEXT NOT NULL,
  -- 完成時に `game_revisions.prompt` へ書き写す差分プロンプト。
  prompt TEXT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('pending', 'running', 'failed')),
  -- 失敗の分類名（8.3 の固定語彙）。走っているあいだは NULL。
  error TEXT,
  started_at INTEGER,
  created_at INTEGER NOT NULL
);

-- 1 作品あたりの推敲回数（5.7 の上限の判定に使う）。
--
-- ## なぜ版の数を数えないのか
--
-- **失敗した推敲は版を積まない。** ビルドが通らなければ成果物が無く、積むものが無い。
-- ところが 5.7 の上限は**推敲という行為**にかかっている——確定25 が「数えるのは費用の
-- 出る LLM 呼び出し回数で、リトライは含む」と定めているのと同じ線である。**版の数で
-- 数えると、失敗した推敲がただで何度でもやり直せる**（1 回 約 16 円が出ているのに）。
--
-- ## NOT NULL + DEFAULT 0 にできる理由
--
-- 0007 と同じ判断である。**既存の行は 1 度も推敲されていない**（この列を読む経路が
-- 存在しなかった）ので、0 での埋め戻しは既定値の都合ではなく**事実として正しい。**
ALTER TABLE games ADD COLUMN revise_count INTEGER NOT NULL DEFAULT 0;
