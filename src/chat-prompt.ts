/** 本文全体（`system` の 1 ブロックに載せる）。 */
export function renderChatPromptText(): string {
  return CHAT_PROMPT_SECTIONS.join('\n\n');
}

/**
 * チャットのシステムプロンプトを組み立てる。
 *
 * **末尾に区切りを 1 つ置く**（4.5）。本文は会話が伸びても変わらないので、**共有の
 * プレフィックスになる**——2 往復目からは入力の単価が 10 分の 1（$0.3/1M）で読める。
 * **キャッシュ次元を持たないモデルでは落とす**（`toConverseSystem` と同じ理由）。
 *
 * @param model 使うモデル
 * @returns `system` に載せるブロック列
 */
export const buildChatPrompt = (model: GenerationModel): readonly SystemBlock[] => {
  const blocks: SystemBlock[] = [{ text: renderChatPromptText() }];
  if (supportsPromptCaching(model)) {
    blocks.push({ cachePoint: true });
  }
  return blocks;
};
